# -*- coding: utf-8 -*-
"""ЗАМЕР НА 400 СУТОК: откуда снос при разомкнутой петле.

ВОПРОС. Контроль Ф28(г) требовал, чтобы при a_n = 0 прибавка доли повреждённых между половинами
прогона была неразличима. На сиде 4242 вышло +0,0019 при MDE 0,0047 (прошёл), на сиде 7331
+0,0063 при MDE 0,0045 (упал). Два ответа совместимы между собой (расхождение 1,7 SE), то есть
истинный снос около +0,005, а порог лежит ровно на нём: контроль решался сидом.

ДВА ОБЪЯСНЕНИЯ, и они требуют разного лечения.
  1. Артефакт запуска: разгон не доел переходный процесс, и в первой половине условия ещё не те.
     Лечится удлинением разгона, посылка контроля при этом верна.
  2. Хвост первого достижения: при постоянной нагрузке переключатель бистабилен, сломавшийся
     набор не возвращается, поэтому доля сломанных монотонно неубывающая и её прибавка НИКОГДА
     не ноль. Тогда посылка контроля ложна, и лечить надо правило, а не разгон.

ЧТО ГОВОРЯТ ПОСТОЯННЫЕ ВРЕМЕНИ. Самая медленная релаксация модели TAU_S = 2,625 сут, время
корреляции быстрого шума 0,3·T (7–24 ч), tauL = 0,1·T. Разгон 16 сут больше их всех на порядок,
медленный шум в этих блоках выключен (sigs = 0). Релаксации с сотнедневным временем в модели нет,
и это уже довод против (1). Замер нужен, чтобы увидеть ход РИСКА, а не досчитать снос.

ЧТО СЧИТАЕТСЯ. Окно делится на четыре равные части; в каждой берутся начала эпизодов и время
ПОД РИСКОМ (длина части минус время внутри эпизодов). Отношение даёт риск h_k. Поправка на время
под риском обязательна: поглощение само выедает пул, и поток событий падал бы даже при постоянном
риске. Критерий тренда точный и условный, матожидание и дисперсия выписаны в px.stats.haz_trend.

ЧТО РЕШАЕТСЯ ОТВЕТОМ.
  h_k падает  -> поглощение сильнее, чем что-либо ещё: опорный ход риска отрицателен, и Ф29
                 обязана сравнивать плечи, а не каждое с нулём.
  h_k ровен   -> опорный риск постоянен, посылка «при постоянных условиях риск не меняется»
                 верна, и Ф29 может мерить каждое плечо против своего нуля.
  h_k растёт  -> в модели есть накопление, которое работает и без петли, и его надо назвать
                 вслух: тогда петля не единственный его источник.

ПЕРЕПОЛНЕНИЕ. Записей эпизодов не больше NEPR = 24 на набор. За 400 суток активный набор может
переполнить, и потеряны будут поздние эпизоды именно у самых активных. Доля переполнивших
печатается: если она велика, на 400 сутках так мерить нельзя, и Ф29 остаётся на 200.

    python diag400.py                  300 наборов, 400 суток, сид 9157
    python diag400.py 200 400 1234     свои наборы, сутки, сид
"""
import sys
import numpy as np
from px import conf, stats as st
from px.batch import Runner, Block
from px.rules import _blocks as B

K = 4


def haz_table(rr, band, t0, t1, k=K):
    """Риск по частям окна из ПОДЁННЫХ накопителей: без потолка записей и без отбора."""
    on = np.asarray(rr['on_day'], float)[band]; ar = np.asarray(rr['risk_day'], float)[band]
    i0 = int(np.ceil(t0)); i1 = int(min(t1, on.shape[1]))
    ed = np.linspace(i0, i1, k + 1).astype(int)
    N = np.array([on[:, ed[q]:ed[q + 1]].sum() for q in range(k)])
    A = np.array([ar[:, ed[q]:ed[q + 1]].sum() for q in range(k)])
    return N, np.maximum(A, 1e-9)


def main(nsel=300, nd=400, seed=9157):
    cfg = conf.load('config/base.toml')
    cfg.d['sets']['nsel'] = nsel; cfg.d['run']['days'] = nd; cfg.d['run']['seed'] = seed
    S = cfg.sets(log=lambda *a: None)
    band = S['band']; nb = int(band.sum())
    print('наборов %d, в полосе %d, суток %d, сид шума %d, разгон %d сут'
          % (nsel, nb, nd, seed, cfg.d['run']['warm']))
    print('постоянные времени модели: TAU_S 2.625 сут, шум 0.3*T, tauL 0.1*T, медленный шум выключен\n')

    kd = B.KB(cfg)
    base = dict(kd=kd, sigs=B.SIGS[0], taus=B.TAU_S, ndays=nd,
                nu_mul=1.0, nu_mul2=1.0, t_mul=nd * 0.5, taun_dn=1.0, taun_up=60.0)
    arms = [('разомкнута', dict(a_n=0.0)),
            ('петля a=0.5', dict(a_n=0.5)),
            ('статика mu=0.7', dict(a_n=0.0, n0_mul=0.7))]
    bl = [Block('d400_%d' % i, **dict(base, **kw)) for i, (_, kw) in enumerate(arms)]
    R = Runner(S, cfg, nproc=min(3, len(bl)), log=lambda *a: None, cache=False)
    keys = {b.tag: R.request(b) for b in bl}
    R.run_all()

    warm_cut = 27.0        # 10*TAU_S: с запасом снимает остаток релаксации, назначено до счёта
    print('%-16s %8s %8s %8s %8s   %7s %7s %8s %6s' %
          ('плечо', 'h1', 'h2', 'h3', 'h4', 'Z', 'событ', 'частота', 'длит.'))
    out = {}
    for (nm, _), b in zip(arms, bl):
        rr = R.get(keys[b.tag])
        N, A = haz_table(rr, band, warm_cut, float(nd))
        h = N / A
        Z, n_ev, rate = st.haz_trend_day(np.asarray(rr['on_day'], float)[band],
                                         np.asarray(rr['risk_day'], float)[band],
                                         warm_cut, float(nd), K, 'increase')
        es = np.asarray(rr['epsum'], float)[band]; en = np.asarray(rr['epn'], float)[band]
        msk = en > 0; dur = float((es[msk] / en[msk]).mean()) if msk.any() else float('nan')
        ovf = float((np.asarray(rr['ep_ov'], int)[band] > 0).mean())
        print('%-16s %8.4f %8.4f %8.4f %8.4f   %+7.2f %7d %8.4f %6.2f'
              % (nm, h[0], h[1], h[2], h[3], Z, n_ev, rate, dur))
        out[nm] = (h, Z, n_ev, rate, dur, ovf, rr)
    print('\nриск h = срывы на набор-сутки под риском; окно %.0f…%d сут, частей %d' % (warm_cut, nd, K))
    print('считано по подённым накопителям: потолка записей нет, отбора нет')
    print('для справки, доля наборов, переполнивших прежние записи ep_rec (NEPR = 24):')
    for nm in out:
        print('  %-16s %.1f %%' % (nm, 100 * out[nm][5]))

    print('\nДЛЯ СВЯЗИ С Ф28: прибавка доли повреждённых между половинами прогона')
    for nm in out:
        sub = out[nm][6]
        p1 = np.asarray(sub['D_ph1'], float)[band]; p2 = np.asarray(sub['D_ph2'], float)[band]
        d = p2 - p1; d = d[np.isfinite(d)]
        se = float(np.std(d, ddof=1) / np.sqrt(len(d)))
        print('  %-16s %+0.4f при SE %.4f и MDE %.4f -> %s'
              % (nm, d.mean(), se, st.mde(se), 'рост' if d.mean() > st.mde(se) else 'не различимо'))

    print('\nЗАМЕР 23.10 ДАЛ: Z = -2.63 (разомкнута), -3.29 (петля), -4.19 (статика), то есть риск')
    print('ПАДАЕТ во всех плечах. Причина структурная: внутри набора самые уязвимые клетки')
    print('срываются первыми и остаются сломанными, под риском остаются всё менее уязвимые.')
    print('Поэтому Z годится только для СРАВНЕНИЯ ПЛЕЧ, а против нуля ничего не проверяет, и')
    print('в Ф29 ни одного критерия против абсолютного нуля не осталось.')
    print('ГОТОВО')


if __name__ == '__main__':
    a = [int(x) for x in sys.argv[1:4]]
    main(*a) if a else main()
