# -*- coding: utf-8 -*-
"""Ф5: стала ли переменная повреждения градуальной.

КАК ЗАПИСАНО
  Доля времени, которую доля повреждённых D проводит в середине шкалы (0,3-0,7), не меньше 0,05 —
  то есть хотя бы вчетверо больше, чем давало одноклеточное d (0,009-0,013, diag_gradual.py).

ВЫКЛАДКА ДЛЯ ДВОЙНИКА (см. px/predict.py, mid_share)
  Порог 0,05 — это «вчетверо больше одной клетки», то есть круглое число, а не ожидание.
  Ожидание выводится. Клетка с множителем v ломается при ln(nu*v) > ln(hi); множители равны
  exp(sigma_v*z) с гауссовым z, поэтому D = 1 - Phi(z*) при sigma_v*z* = ln(hi/nu), и
        0,3 < D < 0,7  <=>  ln(nu) попал в полосу ШИРИНОЙ 2c = 1,049*sigma_v вокруг барьера.
  Дальше это просто гауссова вероятность при текущем суточном подъёме, усреднённая по суткам.
  Гистерезис действует в две стороны (держит D в середине на обратном ходу, но и не пускает D
  обратно через середину, пока x не восстановился), поэтому ожидание даётся ВИЛКОЙ: от половины
  квазистатической оценки (если обратного прохода нет вовсе) до самой оценки.

  Что проверяет двойник. Если наблюдение попало в вилку — градуальность целиком объясняется
  РАЗБРОСОМ УЯЗВИМОСТИ, и связь через сеть (круг E -> L -> D -> g -> E) к ней ничего не добавила;
  именно это утверждают Koulakov и соавт. 2002. Если наблюдение ВЫШЕ вилки — сеть добавила
  промежуточных состояний, и шаг А сделал то, для чего делался. Если НИЖЕ — клетки заперты
  гистерезисом сильнее, чем квазистатика допускает, и градуальности в модели нет вовсе,
  как бы ни был широк разброс уязвимости.
"""
import numpy as np
from .. import predict as P
from .. import stats as st
from . import _blocks as B
from ._meas import meas, mid_time

NAME = 'Ф5'
NHD = 20
SINGLE = 0.011                 # одноклеточное d, diag_gradual.py


def needs(cfg): return [B.kbase_block(cfg)]


def run(ctx):
    S = ctx.S; cfg = ctx.cfg; nd = cfg.d['run']['days']; band = S['band']
    rr = ctx.b('kbase'); mm = meas(rr, nd)
    midD, midDm, se, neff, hD, hDm = mid_time(rr, nd, S['nsel'], mm['dur'], NHD)
    sigv = float(cfg.d['model']['sigv'])
    q = P.mid_share(S, sigv); quasi = float(np.mean(q[band])); half = 0.5 * quasi

    a = st.adjudicate(midD, 0.05, se, 'ge', null=SINGLE, n=int(neff))
    inside = bool(half - st.mde(se) <= midD <= quasi + st.mde(se))
    above = bool(midD > quasi + st.mde(se)); below = bool(midD < half - st.mde(se))
    ap = dict(value=midD, lo=half, hi=quasi, se=se, mde=st.mde(se), n=int(neff),
              verdict=('непроверяемо' if not (se == se) else ('в вилке' if inside else ('выше вилки' if above else 'ниже вилки'))))
    vt = lambda v: 'выполнено' if v is True else ('не выполнено' if v is False else str(v))
    md = ['\n## %s. Градуальна ли переменная повреждения (блок %s)\n' % (NAME, ctx.key('kbase')),
          '| величина | доля времени в середине шкалы (0,3–0,7) | во сколько раз больше одной клетки |\n|---|---|---|',
          '| доля повреждённых D | %.4f | %.1f |' % (midD, midD / SINGLE),
          '| среднее повреждение | %.4f | %.1f |' % (midDm, midDm / SINGLE),
          '\nГистограмма накапливается на весь блок (%d наборов, %d суток), маска полосы к ней не '
          'применима. SE посчитана по эффективному числу независимых отсчётов %.0f = наборы*сутки/длительность '
          'эпизода (%.2f сут): доля повреждённых держится примерно эпизод, поэтому отсчёты по шагам не '
          'независимы.\n' % (S['nsel'], nd, neff, mm['dur']),
          '\n| часть | получено | порог | нулевое значение | SE | MDE | вывод |\n|---|---|---|---|---|---|---|',
          '| как записано: не меньше 0,05 | %.4f | 0,05 | %.3f (одна клетка) | %.4f | %.4f | %s |'
          % (midD, SINGLE, se, a['mde'], vt(a['verdict'])),
          '| двойник: попадает ли в аналитическую вилку | %.4f | вилка %.4f … %.4f при sigma_v = %.2f | — | %.4f | %.4f | %s |'
          % (midD, half, quasi, sigv, se, ap['mde'], ap['verdict']),
          '\nВилка выведена из одного разброса уязвимости: полоса середины шкалы имеет ширину '
          '1,049·sigma_v = %.4f в логарифме нагрузки, и доля времени в ней — гауссова вероятность при '
          'суточном подъёме %.2f сигмы и зазоре %.2f сигмы.\n'
          % (1.049 * sigv, P.summary(S, cfg)['day_rise_sigma'], P.summary(S, cfg)['gap_sigma'])]
    if below:
        md.append('**Наблюдение НИЖЕ вилки.** Доля времени в середине меньше, чем даёт один разброс '
                  'уязвимости при квазистатическом прохождении полосы. Значит клетки заперты гистерезисом: '
                  'перешагнув порог, они держатся, и D стоит у краёв, а не в середине. Сеть промежуточных '
                  'состояний не создаёт — она их УБИРАЕТ. Это сильнее прежнего вывода «плавность даёт разброс, '
                  'а не сеть» и означает, что следующий шаг надо делать не в сторону сети, а в сторону '
                  'восстановления x (его пол и его разброс по клеткам).')
    elif above:
        md.append('**Наблюдение ВЫШЕ вилки.** Промежуточных состояний больше, чем даёт один разброс '
                  'уязвимости, то есть их действительно создаёт связь через сеть, и шаг А сделал то, для чего '
                  'делался. Это надо отдельно проверить перебором по sigma_v: если выше вилки при ВСЕХ '
                  'sigma_v, вывод стоит; если только при одном, это случайность выборки.')
    else:
        md.append('**Наблюдение в вилке.** Градуальность объясняется разбросом уязвимости целиком, и сеть '
                  'к ней ничего не добавила — ровно то, что утверждают Koulakov и соавт. 2002.')
    out = dict(mid_share_D=midD, mid_share_Dmean=midDm, single_cell=SINGLE, se=se,
               a=a, a_tight=ap, hist_D=[float(z) for z in hD], hist_Dmean=[float(z) for z in hDm],
               analytic=dict(quasi=quasi, half=half, sigv=sigv), n_eff=neff, dur=mm['dur'])
    ctx.verdict(NAME, 'как записано', midD, a['verdict'], note='порог 0,05 = вчетверо больше одной клетки')
    ctx.verdict(NAME, 'двойник', midD, ap['verdict'], note='аналитическая вилка %.4f…%.4f' % (half, quasi))
    return out, md
