    ok = bool(all((z['diff'] < 1e-9) or (z['diff'] != z['diff'] and z['pr_free'] != z['pr_free']) for z in chk))
    # --- (а), (а'), (б), (в)
    alive = [z for z in rows if z['n_cycles'] > 4 and z['n_sleep'] > 2]
    dead = [z for z in rows if z['n_sleep'] <= 2]
    k_dead = min((z['kd'] for z in dead), default=float('nan'))
    first = next((z['kd'] for z in alive if z['n_levels'] >= 2), float('nan'))
    a = bool(first == first)
