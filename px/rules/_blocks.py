N0M28 = [0.60, 0.65, 0.70, 0.75, 0.85, 1.0]   # статическое снижение ёмкости — эквивалент для фальсификатора
BRK28 = 1.6                          # чем ломаем в первой фазе
TDN28 = 1.0                          # потеря ёмкости быстрая, её не перебираем
DPROG = 200                          # суток в блоке прогрессирования: тренд нужно успеть увидеть

