# Без этого протокола «необратимость» проверить нельзя вовсе: все прогоны стартуют из здорового
# состояния, и при низкой нагрузке наборы просто не ломаются — это «не поймало», а не «отпустило».
NU_BREAK, NU_REL = 2.0, 0.6
