def haz_work(cfg):
    """Ф29, опорное и рабочее плечо: один прогон без петли и один с ней, оба длинные."""
    return [Block('n29_open', kd=KB(cfg), sigs=SIGS[0], taus=TAU_S, ndays=D29,
                  nu_mul=1.0, nu_mul2=1.0, t_mul=D29 * 0.5, a_n=0.0,
                  taun_dn=TDN28, taun_up=TUP29),
            Block('n29_loop', kd=KB(cfg), sigs=SIGS[0], taus=TAU_S, ndays=D29,
                  nu_mul=1.0, nu_mul2=1.0, t_mul=D29 * 0.5, a_n=AN29,
                  taun_dn=TDN28, taun_up=TUP29)]


def haz_stat(cfg):
    """Ф29, статический эквивалент: ёмкость снижена ПОСТОЯННО. У него риск постоянен во времени
    по построению, поэтому он и служит фальсификатором. Точка mu = 1 совпадает с n29_open по всем
    параметрам и потому работает контролем на тождество измерительной машины."""
    return [Block('n29_s_m%g' % mu, kd=KB(cfg), sigs=SIGS[0], taus=TAU_S, ndays=D29,
                  nu_mul=1.0, nu_mul2=1.0, t_mul=D29 * 0.5, a_n=0.0,
                  taun_dn=TDN28, taun_up=TUP29, n0_mul=mu) for mu in N0M29]


