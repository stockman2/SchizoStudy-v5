                           # SE = 0,0122, MDE = 0,0304, запас 22 %. Взято 36.
                           # ЦЕНА: блоков 2*(n-1), то есть 70 вместо 10, около 87 минут при
                           # 87 с на блок. Переопределяется в конфиге: [run] nseed = N.


def KB(cfg): return float(cfg.d['model']['kd'])


def kbase_block(cfg):
    """Рабочий блок со связью: k = k_база, рабочий шум, рабочая память защиты."""
    return Block('kbase', kd=KB(cfg), sigs=SIGS[0], taus=TAU_S)


def kscan(cfg):
    """Перебор силы связи. Точка k = 0 — тот же блок, что 'base'; k = k_база — тот же, что 'kbase'."""
    return [Block('k_%.2f' % ks, kd=ks, sigs=SIGS[0], taus=TAU_S) for ks in KSCAN]


def tag_k(ks): return 'k_%.2f' % ks


def seed_pairs(cfg):
    """Парное сравнение k = 0 против k = k_база на других зёрнах: по два блока на зерно.
    Первое зерно — рабочее, и его пара уже есть в переборе k, поэтому здесь только остальные."""
    sd0 = int(cfg.d['run']['seed']); ns = int(cfg.d['run'].get('nseed', NSEED3))
    return [Block('sd_%d_%s' % (sd, ('0' if kk == 0.0 else 'b')), kd=kk, sigs=SIGS[0], taus=TAU_S, seed=sd)
            for sd in [sd0 + 1000 * i for i in range(1, ns)] for kk in (0.0, KB(cfg))]


def asym_scan(cfg):
    """Асимметричная защита при рабочей связи: постоянная спада в DSCAN раз против подъёма.
    Множитель 1,0 дал бы ровно блок 'kbase', поэтому в перебор не входит."""
    return [Block('as_%.2f' % r, kd=KB(cfg), sigs=SIGS[0], taus=TAU_S, tausd=TAU_S * r)
            for r in DSCAN]


def da_scan(cfg):
    """Блоки для Ф26: дофаминовая петля против эквивалентного статического подъёма нагрузки.

    Устройство перебора. По одной оси — ПОСТОЯННЫЙ множитель нагрузки, то есть статический
    эквивалент; по другой — сила петли a_da при источнике «доля повреждённых» (петля Грейса
    идёт от повреждения через гиппокамп и VTA, мимо локальной активности коры). a_da = 0 —
    это разомкнутая петля, то есть прежняя модель, а множитель 1 — её рабочая точка.

    Зачем обе оси сразу. Петля поднимает нагрузку множителем (1 + a_da*D), и голое «сломалось
    больше наборов» ничего не доказывает: столько же сломал бы и постоянный множитель.
    Поэтому перебор по множителю даёт эквивалент, с которым петля сравнивается, а вместе они
    дают и проверку на гистерезис — при множителе НИЖЕ единицы петля обязана удерживать
    сломанные наборы, если состояние действительно необратимо.
    """
    nd = int(cfg.d['run']['days'])
    return [Block('da_m%g_a%g' % (mu, a), kd=KB(cfg), sigs=SIGS[0], taus=TAU_S,
                  nu_mul=mu, a_da=a, tau_d=TAU_D_DA, da_src=1.0)
            for mu in NUDA for a in ADA] + \
           [Block('da_hys_a%g' % a, kd=KB(cfg), sigs=SIGS[0], taus=TAU_S,
                  nu_mul=NU_BREAK, nu_mul2=NU_REL, t_mul=nd * 0.5,
                  a_da=a, tau_d=TAU_D_DA, da_src=1.0)
            for a in ADA]


def da_fine(cfg):
    """Ф27: та же пара блоков (рабочая точка и двухфазный протокол) на мелком переборе силы петли.
    Блоки с a = 0 и a = 3 уже просит Ф26, поэтому здесь только промежуточные точки, и перебор
    стоит вдвое меньше, чем выглядит."""
    nd = int(cfg.d['run']['days']); aa = ADA27_ALL
    return [Block('da_m1_a%g' % a, kd=KB(cfg), sigs=SIGS[0], taus=TAU_S,
                  nu_mul=1.0, a_da=a, tau_d=TAU_D_DA, da_src=1.0) for a in aa] + \
           [Block('da_hys_a%g' % a, kd=KB(cfg), sigs=SIGS[0], taus=TAU_S,
                  nu_mul=NU_BREAK, nu_mul2=NU_REL, t_mul=nd * 0.5,
                  a_da=a, tau_d=TAU_D_DA, da_src=1.0) for a in aa] + \
           [Block('da_hys2_a%g' % a, kd=KB(cfg), sigs=SIGS[0], taus=TAU_S,
                  nu_mul=NU_BREAK_SOFT, nu_mul2=NU_REL, t_mul=nd * 0.5,
                  a_da=a, tau_d=TAU_D_DA, da_src=1.0) for a in aa]


def cap_work(cfg):
    """Ф28, рабочая точка: эпизодичность и уровень при разной глубине потери ёмкости."""
    return [Block('cp_w_a%g' % a, kd=KB(cfg), sigs=SIGS[0], taus=TAU_S,
                  a_n=a, taun_dn=TDN28, taun_up=60.0) for a in AN28]


def cap_prog(cfg):
    """Ф28, прогрессирование: 200 суток, нагрузка НЕ меняется, смена фазы посередине нужна только
    чтобы получить накопители по половинам. Перебор по постоянной возврата: на пробе прибавка не
    зависела от глубины, и предполагается, что её задаёт именно возврат — это и проверяется."""
    return [Block('cp_p_a%g_u%g' % (a, u), kd=KB(cfg), sigs=SIGS[0], taus=TAU_S, ndays=DPROG,
                  nu_mul=1.0, nu_mul2=1.0, t_mul=DPROG * 0.5,
                  a_n=a, taun_dn=TDN28, taun_up=u) for a in (0.0, 0.5) for u in TUP28]


def cap_hys(cfg):
    """Ф28, гистерезис: ломаем множителем BRK28, потом сбрасываем на разную глубину."""
    nd = int(cfg.d['run']['days'])
    return [Block('cp_h_a%g_r%g' % (a, r), kd=KB(cfg), sigs=SIGS[0], taus=TAU_S,
                  nu_mul=BRK28, nu_mul2=r, t_mul=nd * 0.5,
                  a_n=a, taun_dn=TDN28, taun_up=60.0) for a in (0.0, 0.5) for r in REL28]


def cap_stat(cfg):
    """Ф28, статический эквивалент: ёмкость снижена ПОСТОЯННО, петли нет. Если он воспроизводит
    всё, петля — ручка. Прогрессирование он дать не может по построению, и это главная проверка."""
    return [Block('cp_s_m%g' % mu, kd=KB(cfg), sigs=SIGS[0], taus=TAU_S, ndays=DPROG,
                  nu_mul=1.0, nu_mul2=1.0, t_mul=DPROG * 0.5, a_n=0.0, n0_mul=mu) for mu in N0M28]


def band_scan(cfg):
    """Блоки для Ф25: полоса спасённых праймингом. При рабочей связи, три состояния защиты —
    рабочее (память 63 ч, прайминга нет), короткая память (12 ч) и с праймингом. Рабочее состояние
    это блок 'kbase', он уже есть, поэтому перебор стоит два блока."""
    # ЗАМОРОЗКА, а не короткая память. Проба 16.10 замораживала вторую ступень целиком, и
    # монотонность становилась точной. Короткая память (12 ч) этого НЕ делает: история у клетки
    # остаётся, просто идёт быстрее, и полоса от неё даже расширяется (замерено 17.10: 0,0141
    # против 0,0110). Замораживает её БОЛЬШОЕ taus: тогда множитель спада близок к единице, и sP
    # остаётся на своём начальном нуле, то есть медленной памяти у клетки нет вовсе.
    return [Block('bd_froz', kd=KB(cfg), sigs=SIGS[0], taus=1000.0),
            Block('bd_short', kd=KB(cfg), sigs=SIGS[0], taus=TAU_M),
            Block('bd_prime', kd=KB(cfg), sigs=SIGS[0], taus=TAU_S, apr=2.0, taup=0.5)]


def tslow_scan(cfg):
    """Перебор времени корреляции медленного шума при постоянных среднем и дисперсии нагрузки.
    Плюс парный контроль с КОРОТКОЙ памятью второй ступени на двух крайних точках: если зависимость
    от tslow делает именно адаптация защиты, то без долгой памяти она обязана ослабнуть."""
    return [Block('ts_%.3f' % t, kd=KB(cfg), sigs=SIGS_T, taus=TAU_S, tslow=t) for t in TSCAN] + \
           [Block('ts_nm_%.3f' % t, kd=KB(cfg), sigs=SIGS_T, taus=TAU_M, tslow=t)
            for t in (TSCAN[0], TSCAN[-1])]


def swing_scan(cfg):
    """Перебор размаха суточной нагрузки при k = 0: множитель при A_H. Множитель 1,0 даёт
    ровно блок 'base', поэтому перебор стоит три блока, а не четыре."""
    return [Block('a_%.2f' % af, kd=0.0, sigs=SIGS[0], taus=TAU_S,
                  aH=(None if af == 1.0 else ('A_H', af))) for af in ASCAN]


def tag_a(af): return 'a_%.2f' % af


def slow_scan(cfg):
    """Перебор медленного шума нагрузки при k = k_база плюс блок «шума нет И памяти защиты нет»:
    им Ф18 привязывает предвестник. sigma_м = 0 даёт ровно блок 'kbase'."""
    return [Block('s_%.2f' % ss, kd=KB(cfg), sigs=ss, taus=TAU_S) for ss in SSCAN] + \
           [Block('s_nomem', kd=KB(cfg), sigs=0.0, taus=TAU_M)]


def tag_s(ss): return 's_%.2f' % ss


def frac_block(cfg):
    """Контроль Ф7: связь идёт через ДОЛЮ повреждённых, а не через среднее повреждение."""
    return Block('frac', kd=KB(cfg), sigs=SIGS[0], taus=TAU_S, usedm=0.0)


def sr_scan(cfg):
    """Серотониновый триггер: перебор частоты всплесков и перебор их амплитуды.
    Контроль «всплесков нет вовсе» — это блок 'kbase'."""
    return [Block('sr_r_%.2f' % rt, kd=KB(cfg), sigs=SIGS[0], taus=TAU_S, sramp=SR_AMP, srate=rt) for rt in RSCAN] + \
           [Block('sr_a_%.1f' % am, kd=KB(cfg), sigs=SIGS[0], taus=TAU_S, sramp=am, srate=SR_RATE) for am in ASCAN_SR]


def tag_sr_r(rt): return 'sr_r_%.2f' % rt
def tag_sr_a(am): return 'sr_a_%.1f' % am


def j_scan(cfg):
    """Число клеток на двух сетках уязвимости. J = 32 на закреплённой сетке — это блок 'base'."""
    return [Block('j_%d_%d' % (Jx, int(vf)), kd=0.0, sigs=SIGS[0], taus=TAU_S, J=Jx, vfix=float(vf))
            for Jx in JS13 for vf in (1, 0)]


def tag_j(Jx, vf): return 'j_%d_%d' % (Jx, int(vf))


