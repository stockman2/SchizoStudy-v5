"""Общие наборы блоков. Правила, которым нужен ОДИН И ТОТ ЖЕ блок, обязаны просить его
через одну и ту же функцию: тогда спецификации совпадают дословно, хеши совпадают, и
сборщик считает блок один раз. Если бы каждое правило собирало спецификацию само, два
правила могли бы молча получить разные блоки, и парные сравнения между ними развалились бы.
"""
from ..batch import Block
from ..consts import TAU_M, TAU_S, SR_AMP, SR_RATE

# перебор памяти защиты: контроль без длинной памяти, три значения из сырого опыта и точка
# для проверки предсказания закона длительности (Ф16)
TAUS = [TAU_M, 24. / 24, 63. / 24, 88. / 24, 150. / 24]
SIGS = [0.0, 0.08]                       # рабочее значение и прежнее рабочее как парный контроль


def tag_ds(sg, ts): return 'ds_%.2f_%.0f' % (sg, ts * 24)


def defence_scan(cfg):
    """Десять блоков: 2 силы медленного шума на 5 длин памяти защиты, связь со сном выключена."""
    return [Block(tag_ds(sg, ts), kd=0.0, sigs=sg, taus=ts) for sg in SIGS for ts in TAUS]


def base_block(cfg):
    """Рабочий блок: k = 0, рабочий шум и рабочая память. Тот же, что ds_0.00_63 в переборе,
    и тот же, что 'base' у Ф19 — все три склеятся в один."""
    return Block('base', kd=0.0, sigs=SIGS[0], taus=TAU_S)


def no_memory_block(cfg):
    """Парный контроль: вторая ступень защиты без длинной памяти. Тот же, что ds_0.00_12."""
    return Block('nomem', kd=0.0, sigs=SIGS[0], taus=TAU_M)


