# При n = 5 наименьшее p равно 1/120 = 0.008, и запас есть. Размах прежний, шаг вдвое мельче.
TUP28 = [15.0, 30.0, 60.0, 120.0, 240.0]      # постоянная ВОЗВРАТА ёмкости, сутки
# Пять точек по той же причине, что и у TUP28: пункт (б) требует p <= 0.05, а при n = 3
