# -*- coding: utf-8 -*-
"""Ф21: где третья медленная величина, которой у нас нет в уравнениях.

ОТКУДА ВОПРОС. Ф18 показал: предвестник сна (многосуточный подъём длины бодрствования перед срывом)
при отнятии длинной памяти защиты падает достоверно — но уходит только ПЯТАЯ ЧАСТЬ превышения.
Значит склон делает не только память защиты. Медленный шум нагрузки исключён отдельно (Ф6(в′)).
Записанный заранее вывод Ф18(в) требует ИСКАТЬ третью медленную величину, а не достраивать имеющиеся.

ВЫКЛАДКА, СУЖАЮЩАЯ ПОИСК ДО ОДНОГО КАНДИДАТА. Перечислим все времена модели в сутках:
  - возврат перекиси (T) и релаксация нагрузки (0,1·T): сутки равны r·T, поэтому в сутках это
    1/r и 0,1/r, то есть 0,25-0,5 и 0,03-0,05 суток — быстро;
  - возврат x: время 1/(c^m + mu0·u²/(1+u)); при низкой нагрузке это 1/N0^m, в сутках порядка
    0,01 — быстро, и это согласуется с прямым измерением (у 73 % наборов x возвращается за сутки);
  - защита от рецептора (c_база): тоже T, то есть быстро;
  - первая ступень защиты: 12 ч = 0,5 суток;
  - вторая ступень: 63 ч = 2,6 суток — ЕДИНСТВЕННАЯ медленная постоянная, и она уже исключена
    как единственная причина;
  - медленный шум нагрузки: 5 суток, но он выключен и исключён.
Больше ВРЕМЁН в уравнениях нет. Значит третья медленная величина — не постоянная времени, а
НАКОПЛЕНИЕ: население из J клеток заполняется повреждёнными по одной, и характерное время этого
заполнения задаётся не константой, а РЕДКОСТЬЮ перехода, то есть расстоянием нагрузки до барьера в
сигмах шума. У такой величины нет своего tau в уравнениях — поэтому мы и не нашли её, перебирая
постоянные.

ПРАВИЛО Ф21, ЗАПИСАНО ДО СЧЁТА
  (а) Остаточный предвестник (высота при ОТНЯТОЙ длинной памяти защиты) связан с редкостью перехода:
      ранговая связь с зазором до барьера в сигмах (gap_up/sigma) по наборам не слабее 0,40 по модулю.
  (б) Контроль: с параметрами, которые не задают ни времени, ни редкости (N0, KB, gam, m), связь
      по модулю слабее 0,40. Иначе дело не в редкости, и кандидат неверен.
  (в) Время заполнения, измеренное прямо (средний промежуток между эпизодами), лежит в полосе
      1-8 суток, то есть на масштабе самого предвестника. Иначе объяснение не на том масштабе.

ЧТО ЗНАЧИТ КАЖДЫЙ ИСХОД. Если (а) и (в) выполнены, третья медленная величина найдена, и она не
требует новых уравнений: это заполнение населения, и в модель её добавлять не надо — надо перестать
искать. Если (а) не выполнено, остаётся единственная непроверенная возможность: медленная величина
спрятана в самой защите (например, асимметрия подъёма и спада белка), и тогда её надо вводить явно.

БЛОКОВ НЕ ДОБАВЛЯЕТ: берёт те же блоки, что Ф6 и Ф18 (рабочий и «без длинной памяти»).
"""
import numpy as np
from .. import stats as st
from ..consts import TAU_M, TAU_S
from . import _blocks as B
from ._meas import meas, curve6, rank_corr

NAME = 'Ф21'
SLOW = (('gap_sigma', 'зазор до барьера, сигм (редкость перехода)'),
        ('gap_mean', 'измеренный промежуток между эпизодами, сут'),
        ('T', 'возврат перекиси T'), ('r', 'длина суток r'))
CTRL = (('N0', 'приток защиты N0'), ('KB', 'константа индукции KB'),
        ('gam', 'показатель gam'), ('m', 'показатель m'), ('mu0', 'сила повреждения mu0'),
        ('e0', 'утечка e0'), ('KN', 'константа KN'), ('beta', 'сила индукции beta'))


def needs(cfg): return B.slow_scan(cfg)


def run(ctx):
    S = ctx.S; cfg = ctx.cfg; nd = cfg.d['run']['days']; band = S['band']
    nm, nmn, nmrel = curve6(ctx.b('s_nomem'), band)          # предвестник БЕЗ длинной памяти защиты
    cur, cnt, rel = curve6(ctx.b(B.tag_s(B.SSCAN[0])), band)  # он же с рабочей памятью
    mm = meas(ctx.b('s_nomem'), nd, band)
    h = nmrel[:, 0]                                           # высота остаточного предвестника по наборам
    ok = np.isfinite(h)
    gm = np.asarray(ctx.b('s_nomem')['gap_sum'], float)[band] / np.maximum(
        np.asarray(ctx.b('s_nomem')['gap_n'], float)[band], 1)
    col = dict(gap_sigma=(np.asarray(S['gap_up'])[band] + np.log(S['day_peak'])) / S['sigma_total'],
               gap_mean=np.where(np.asarray(ctx.b('s_nomem')['gap_n'], float)[band] > 0, gm, np.nan))
    for k in ('T', 'r', 'N0', 'KB', 'gam', 'm', 'mu0', 'e0', 'KN', 'beta'):
        col[k] = np.asarray(S['P'][k], float)[band]
    def rc(name):
        x = np.asarray(col[name], float); m_ = ok & np.isfinite(x)
        n = int(m_.sum())
        if n < 10 or np.ptp(x[m_]) == 0: return float('nan'), n
        from scipy.stats import rankdata
        return float(np.corrcoef(rankdata(x[m_]), rankdata(h[m_]))[0, 1]), n
    res = {}
    for name, _ in SLOW + CTRL:
        r_, n_ = rc(name)
        res[name] = dict(rho=r_, n=n_, se=st.rho_se(n_),
                         **{k: v for k, v in st.adjudicate(abs(r_) if r_ == r_ else float('nan'), 0.40,
                            st.rho_se(n_), 'ge', null=0.0, n=n_).items() if k in ('mde', 'verdict', 'n_required')})
    best = max((z for nm_, _ in SLOW for z in [(abs(res[nm_]['rho']), nm_)] if z[0] == z[0]), default=(float('nan'), None))
    a = res[best[1]]['verdict'] if best[1] else 'непроверяемо'
    ctrl_bad = [nm_ for nm_, _ in CTRL if res[nm_]['verdict'] is True]
    b = ('непроверяемо' if any(res[nm_]['verdict'] == 'непроверяемо' for nm_, _ in CTRL)
         else bool(not ctrl_bad))
    fill = float(np.nanmedian(col['gap_mean']))
    c = st.adjudicate(fill, 8.0, st.boot_se(col['gap_mean'][np.isfinite(col['gap_mean'])]) * max(fill, 1e-9),
                      'le', null=0.0, n=int(np.isfinite(col['gap_mean']).sum()))
    c['in_band'] = bool(1.0 <= fill <= 8.0)
    vt = lambda v: 'выполнено' if v is True else ('не выполнено' if v is False else str(v))
    md = ['\n## %s. Где третья медленная величина\n' % NAME,
          'Блоки те же, что у Ф6 и Ф18: рабочий %s (память %.0f ч) и без памяти %s (%.0f ч). Величина — '
          'высота ОСТАТОЧНОГО предвестника у каждого набора: длина бодрствования в последние сутки перед '
          'срывом, в долях собственного здорового уровня, при ОТНЯТОЙ длинной памяти защиты. С памятью '
          '%.4f, без неё %.4f.\n'
          % (ctx.key(B.tag_s(B.SSCAN[0])), TAU_S * 24, ctx.key('s_nomem'), TAU_M * 24,
             float(cur[0]), float(nm[0])),
          '\n| с чем связана высота | ранговая связь | наборов | SE | MDE | различимо |\n|---|---|---|---|---|---|']
    for name, lab in SLOW:
        z = res[name]
        md.append('| %s | %s | %d | %s | %s | %s |' % (lab, ('%+.3f' % z['rho']) if z['rho'] == z['rho'] else '—',
                  z['n'], ('%.3f' % z['se']) if z['se'] == z['se'] else '—',
                  ('%.3f' % z['mde']) if z['mde'] == z['mde'] else '—', vt(z['verdict'])))
    md.append('\n| контроль: с чем связи быть не должно | ранговая связь | наборов | вывод |\n|---|---|---|---|')
    for name, lab in CTRL:
        z = res[name]
        md.append('| %s | %s | %d | %s |' % (lab, ('%+.3f' % z['rho']) if z['rho'] == z['rho'] else '—',
                  z['n'], 'связь ЕСТЬ' if z['verdict'] is True else vt(z['verdict'])))
    md += ['\n| часть | получено | порог | вывод |\n|---|---|---|---|',
           '| а: связь с редкостью перехода | сильнейшая из медленных: %s, связь %s | не слабее 0,40 по модулю | %s |'
           % (dict(SLOW).get(best[1], '—'), ('%+.3f' % res[best[1]]['rho']) if best[1] else '—', vt(a)),
           '| б: контрольные параметры не связаны | %s | ни один не проходит 0,40 | %s |'
           % ('все слабее порога' if not ctrl_bad else 'связь нашлась у: ' + ', '.join(ctrl_bad), vt(b)),
           '| в: время заполнения на масштабе предвестника | %.2f суток | в полосе 1–8 суток | %s |'
           % (fill, vt(c['in_band']))]
    if a is True and c['in_band']:
        md.append('\n**Третья медленная величина найдена, и новых уравнений она не требует.** Это заполнение '
                  'населения: клетки переходят по одной, частота перехода задана расстоянием до барьера в '
                  'сигмах, и характерное время выходит %.2f суток — ровно масштаб предвестника. У этой '
                  'величины нет своего tau, поэтому перебор постоянных её найти не мог. Следствие, '
                  'проверяемое в следующем прогоне: предвестник должен становиться КРУЧЕ у наборов с малым '
                  'зазором и ПОЛОЖЕ у наборов с большим, причём без всякой защиты. Это прямая проверка, и '
                  'она не требует новых блоков — только разбить кривую предвестника по квартилям зазора.'
                  % fill)
    elif a is False:
        md.append('\n**Кандидат не подтвердился.** Высота остаточного предвестника с редкостью перехода не '
                  'связана, значит заполнение населения тут ни при чём. Тогда из перечисленного в выкладке '
                  'остаётся единственное непроверенное: медленная величина спрятана в самой защите, и '
                  'вероятнее всего это АСИММЕТРИЯ подъёма и спада белка (сейчас подъём и спад идут с одной '
                  'постоянной 63 ч, а в измерениях спад медленнее). Это уже требует правки уравнений, и это '
                  'следующий шаг, а не замазывание.')
    out = dict(a=dict(best=best[1], corr=res[best[1]]['rho'] if best[1] else float('nan'), verdict=a),
               b=dict(verdict=b, with_signal=ctrl_bad), c=dict(fill_days=fill, **c),
               corr=res, height_with_memory=float(cur[0]), height_without=float(nm[0]))
    ctx.verdict(NAME, 'а', res[best[1]]['rho'] if best[1] else float('nan'), a,
                note='связь остаточного предвестника с %s' % dict(SLOW).get(best[1], '—'))
    ctx.verdict(NAME, 'б', float(len(ctrl_bad)), b, note='контрольные параметры')
    ctx.verdict(NAME, 'в', fill, c['in_band'], note='время заполнения населения, сутки')
    return out, md
