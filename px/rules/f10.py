# -*- coding: utf-8 -*-
"""Ф10: ИЗ ЧЕГО СОСТОИТ ДЛИТЕЛЬНОСТЬ ЭПИЗОДА. Вопрос ставится ВНУТРИ набора, а не между наборами.

ОТКУДА ВОПРОС. Между наборами длительность эпизода объясняется их параметрами, и это неинтересно:
разные наборы — разные системы. Содержательный вопрос другой: у ОДНОГО набора эпизоды разной
длины — чем эта разница сделана? Двумя слагаемыми: «ход под нагрузкой» (сколько времени нагрузка
держалась выше верха окна, пока шёл эпизод) и «хвост» (сколько тянулось ПОСЛЕ того, как нагрузка
ушла вниз, то есть чистая работа починки). Длительность есть их сумма тождественно.

ПОЧЕМУ ЭТО ПРАВИЛО ПЕРЕПИСАНО 17.10. Раньше записи эпизодов делал ВТОРОЙ интегратор, живший в этом
файле, со своей самосверкой против px.model.simulate. 17.10 сверка отказала: интерполяция момента
пересечения порога появилась в simulate и не появилась в копии, расхождение вышло ровно в один шаг
на каждую границу эпизода (d_sum = 0.0375 = 60 шагов, d_min = 6.25e-4 = один шаг), и все пять
вердиктов стали непроверяемыми. Самосверка сработала как задумано, но вывод из этого один: дубликат
интегратора расходится при КАЖДОЙ правке модели. Поэтому он удалён. Записи эпизодов теперь пишет
сам simulate (ep_rec), правило стало обычным блочным, и расходиться больше нечему — сверять копию
не нужно, когда копии нет.

ЧТО ЭТО ДАЛО ПОПУТНО. Прежний отдельный прогон брал 150 наборов полосы и давал около 62 набора с
пятью эпизодами. Блок считает ВСЮ полосу, то есть выборка вырастает примерно в восемь раз, и
медианы по наборам становятся заметно устойчивее. Потолок записей на набор — NEPR в px/core.py,
переполнение считается и печатается: молчаливой потери нет.

ПРАВИЛО Ф10, ЗАПИСАНО ДО СЧЁТА (формулировки сохранены дословно с 15.10)
  (а) Хвост длиннее у тех эпизодов, где повреждение доходило выше: медиана по наборам ранговой
      связи «пик повреждения — хвост» не ниже 0,40.
  (б) Длительность определяется ходом под нагрузкой: медиана ранговой связи «время над верхом окна
      — длительность» не ниже 0,40.
  (в) Хвост — заметная часть эпизода: медиана по наборам медианы отношения хвост/длительность не
      ниже 0,30.
  (б′) ТОЧНОЕ РАЗЛОЖЕНИЕ. Поскольку длительность = ход + хвост тождественно, доли дисперсии
      cov(дл, ход)/var(дл) и cov(дл, хвост)/var(дл) обязаны давать в сумме РОВНО единицу. Нулевое
      значение для каждой — половина (поровну). Ожидание до счёта: ход объясняет не меньше 0,75.
  (в′) То же зеркально: хвост объясняет не больше 0,25. Сумма долей печатается как проверка
      самого разложения — она обязана быть единицей с точностью машинного нуля.
"""
import numpy as np
from scipy.stats import rankdata
from .. import stats as st
from ..batch import Block
from . import _blocks as B

NAME = 'Ф10'
DAYS = 100          # суток в блоке: внутринаборным связям нужно 5+ эпизодов на набор, а эпизод с
                    # промежутком около 10 суток за 60 суток даёт их три-четыре. Это своя группа
                    # батча (GROUP включает ndays), то есть один блок, а не отдельный прогон.
MINEP = 5           # меньше пяти эпизодов — связь внутри набора считать нельзя


def needs(cfg):
    return [Block('f10rec', kd=0.0, sigs=B.SIGS[0], taus=B.TAU_S, ndays=DAYS)]


def _spear(a, b):
    a = np.asarray(a, float); b = np.asarray(b, float)
    if len(a) < MINEP or np.ptp(a) == 0 or np.ptp(b) == 0: return float('nan')
    return float(np.corrcoef(rankdata(a), rankdata(b))[0, 1])


def run(ctx):
    S = ctx.S; cfg = ctx.cfg; band = S['band']
    warm = int(cfg.d['run']['warm'])
    rr = ctx.b('f10rec')
    rec = np.asarray(rr['ep_rec'], float); rn = np.asarray(rr['ep_rn'], int)
    ov = int(np.asarray(rr['ep_ov'], int)[band].sum())
    per = []
    for k in np.where(band)[0]:
        z = rec[k, :rn[k]]
        z = z[z[:, 4] >= warm]                       # эпизоды, НАЧАВШИЕСЯ после разгона
        if len(z) >= MINEP: per.append(z)

    # --- точное разложение дисперсии по каждому набору: длительность = ход + хвост
    sh_ab, sh_tl = [], []
    for z in per:
        dur = z[:, 0]; tail = z[:, 1]; drive = dur - tail
        v = float(np.var(dur))
        if v <= 1e-12: continue
        sh_ab.append(float(np.cov(dur, drive, bias=True)[0, 1] / v))
        sh_tl.append(float(np.cov(dur, tail, bias=True)[0, 1] / v))
    ra = [_spear(z[:, 2], z[:, 1]) for z in per]      # хвост против пика повреждения
    rb = [_spear(z[:, 0], z[:, 3]) for z in per]      # длительность против времени над границей
    sh = [float(np.median(z[:, 1] / np.maximum(z[:, 0], 1e-9))) for z in per]
    med = lambda a: float(np.nanmedian(a)) if len(a) and np.isfinite(a).any() else float('nan')
    se = lambda a: (float(np.nanstd(a, ddof=1) / np.sqrt(np.isfinite(a).sum()))
                    if np.isfinite(a).sum() >= 3 else float('nan'))
    A = st.adjudicate(med(ra), 0.40, se(ra), 'ge', null=0.0, n=int(np.isfinite(ra).sum()))
    Bp = st.adjudicate(med(rb), 0.40, se(rb), 'ge', null=0.0, n=int(np.isfinite(rb).sum()))
    C = st.adjudicate(med(sh), 0.30, se(sh), 'ge', null=0.0, n=len(sh), lim=(0., 1.))
    Bv = st.adjudicate(med(sh_ab), 0.75, se(sh_ab), 'ge', null=0.5, n=len(sh_ab), lim=(-1., 2.))
    Cv = st.adjudicate(med(sh_tl), 0.25, se(sh_tl), 'le', null=0.5, n=len(sh_tl), lim=(-1., 2.))
    chk = abs(med(sh_ab) + med(sh_tl) - 1.0)

    vt = lambda v: 'выполнено' if v is True else ('не выполнено' if v is False else str(v))
    md = ['\n## %s. Из чего состоит длительность эпизода (внутри набора)\n' % NAME,
          'Блок f10rec: вся полоса (%d наборов), %d суток, разгон %d, k = 0, всплесков нет. Эпизодов '
          'в счёте %d у %d наборов (нужно не меньше %d на набор). Переполнений потолка записей: %d.\n'
          % (int(band.sum()), DAYS, warm, sum(len(z) for z in per), len(per), MINEP, ov),
          '**Второго интегратора больше нет.** До 17.10 записи эпизодов делала копия шага, жившая в '
          'правиле, и её самосверка отказала после правки модели — расхождение вышло ровно в один шаг '
          'на границу. Теперь записи пишет сам px/model.py, поэтому сверять нечего: копии не '
          'существует. Выборка при этом выросла примерно в восемь раз.\n',
          '| часть | получено | порог | нулевое значение | SE | MDE | вывод |',
          '|---|---|---|---|---|---|---|',
          '| а: хвост растёт с пиком повреждения | медиана связи %+.3f по %d наборам | не меньше 0,40 | 0 | %s | %s | %s |'
          % (med(ra), int(np.isfinite(ra).sum()), ('%.3f' % se(ra)) if se(ra) == se(ra) else '—',
             ('%.3f' % A['mde']) if A['mde'] == A['mde'] else '—', vt(A['verdict'])),
          '| б: длительность растёт со временем над границей | медиана связи %+.3f | не меньше 0,40 | 0 | %s | %s | %s |'
          % (med(rb), ('%.3f' % se(rb)) if se(rb) == se(rb) else '—',
             ('%.3f' % Bp['mde']) if Bp['mde'] == Bp['mde'] else '—', vt(Bp['verdict'])),
          '| в: хвост — заметная часть эпизода | медиана отношения %.3f | не меньше 0,30 | 0 | %s | %s | %s |'
          % (med(sh), ('%.3f' % se(sh)) if se(sh) == se(sh) else '—',
             ('%.3f' % C['mde']) if C['mde'] == C['mde'] else '—', vt(C['verdict'])),
          '| б′: ход под нагрузкой объясняет разброс длительности | доля дисперсии %.3f | не меньше 0,75 | 0,5 (поровну) | %s | %s | %s |'
          % (med(sh_ab), ('%.3f' % se(sh_ab)) if se(sh_ab) == se(sh_ab) else '—',
             ('%.3f' % Bv['mde']) if Bv['mde'] == Bv['mde'] else '—', vt(Bv['verdict'])),
          '| в′: ремонт объясняет меньше четверти разброса | доля дисперсии %.3f | не больше 0,25 | 0,5 (поровну) | %s | %s | %s |'
          % (med(sh_tl), ('%.3f' % se(sh_tl)) if se(sh_tl) == se(sh_tl) else '—',
             ('%.3f' % Cv['mde']) if Cv['mde'] == Cv['mde'] else '—', vt(Cv['verdict'])),
          '', 'Проверка самого разложения: две доли обязаны давать в сумме единицу по построению, '
          'расхождение %.2e.' % chk]
    out = dict(n_sets=len(per), n_episodes=sum(len(z) for z in per), overflow=ov,
               a=dict(**A), b=dict(**Bp), c=dict(tail_share_med=med(sh), **C),
               b_var=dict(**Bv), c_var=dict(**Cv), decomp_check=chk,
               tail_share=[float(x) for x in sh])
    ctx.verdict(NAME, 'а', med(ra), A['verdict'], note='хвост против пика повреждения, внутри набора')
    ctx.verdict(NAME, 'б', med(rb), Bp['verdict'], note='длительность против времени над границей')
    ctx.verdict(NAME, 'в', med(sh), C['verdict'], note='доля хвоста в эпизоде; второго интегратора нет')
    ctx.verdict(NAME, 'б′', med(sh_ab), Bv['verdict'], note='доля дисперсии длительности от времени над границей')
    ctx.verdict(NAME, 'в′', med(sh_tl), Cv['verdict'], note='доля дисперсии от ремонта; сумма долей %.1e от единицы' % chk)
    return out, md
