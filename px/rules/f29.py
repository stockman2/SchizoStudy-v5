"""Ф29: ПЕТЛЯ ЁМКОСТИ, ИЗМЕРЕННАЯ ТОЛЬКО СОПОСТАВЛЕННЫМИ РАЗЛИЧИЯМИ.

ПОЧЕМУ ПРАВИЛО ТАКОЕ, А НЕ ДРУГОЕ. За два дня два правила разбились об одно и то же, и причину
надо назвать до всякого счёта, потому что она определяет устройство этого.

  Ф28(г) требовала, чтобы при разомкнутой петле прибавка доли повреждённых между половинами
  прогона была неразличима. Посылка ложна: при постоянной нагрузке переключатель бистабилен,
  сломавшийся набор не возвращается, поэтому доля сломанных монотонно неубывающая, её прибавка
  не ноль и от объёма выборки не зависит, а порог падает как 1/sqrt(n). Контроль проходил ЛИШЬ по
  малости выборки: на сиде 4242 прошёл (+0.0019 при MDE 0.0047), на 7331 упал (+0.0063 при 0.0045).

  Первая редакция Ф29 требовала, чтобы при разомкнутой петле был постоянен РИСК срыва, и это было
  выведено из постоянных времени (самая медленная релаксация TAU_S = 2.625 сут против разгона
  16 сут). Посылка тоже ложна, и это измерено 23.10: Z = -2.63, риск падает. Причина на уровень
  ниже — внутри набора 32 клетки разной уязвимости, самые уязвимые срываются первыми и остаются
  сломанными, поэтому под риском остаются всё менее уязвимые. Поправка на время под риском считает
  ВРЕМЯ, но не состав того, кто под риском.

ВЫВОД, который и есть устройство этого правила. В модели с поглощающими состояниями и разнородной
популяцией АБСОЛЮТНОГО НУЛЯ для накопительных величин не существует: доля сломанных растёт сама,
риск срыва падает сам. Любой критерий «против нуля» здесь проверяет не модель, а объём выборки.
Устоять может только СОПОСТАВЛЕННОЕ РАЗЛИЧИЕ — плечо против плеча, приведённого к тому же уровню
повреждения. Единственная часть правильной формы за два дня, Ф28(ж), и воспроизвелась на
независимом шуме: +0.0223 и +0.0211, оба раза 2,2 MDE. Здесь она стоит ядром правила.

ЧЕМ СОПОСТАВЛЯТЬ. Уровнем повреждения в первой половине, НЕ ёмкостью. Мера прогрессирования
ограничена сверху, и по ёмкости она немонотонна (горб на mu = 0.75 при сломанных 0.50): по ёмкости
сравнивались бы разные запасы до потолка. Статическое плечо берётся линейной интерполяцией между
НАКРЫВАЮЩИМИ точками сетки, а не ближайшей: ближайшая существует при любой сетке и потому молчит.
Не накрыли — непроверяемо.

ЧЕМ СЧИТАЕТСЯ ПОТОК СОБЫТИЙ. Подёнными накопителями on_day и risk_day, без потолка. Записи ep_rec
ограничены NEPR = 24 на набор, и замер 23.10 дал переполнение 15–20 %: переполняли «дребезжащие»
наборы у границы, то есть отбор зависел от самой измеряемой величины и выбрасывал целый режим
поведения, а не шум. Подённые накопители этого дефекта не имеют по построению.

ПОРОГИ, ВЫВЕДЕННЫЕ, А НЕ НАЗНАЧЕННЫЕ
  Прогрессирование. Парная внутри набора прибавка; ошибка разности двух плеч взята сверху,
  hypot(se1, se2), хотя наборы у плеч одни и те же и шум парный — завышать безопасно. Порог
  MDE = 2.4865*SE.
  Ход риска. При риске, постоянном во времени, распределение срывов по частям окна, условно по их
  числу, полиномиально с p_ik = A_ik/A_i; матожидание и дисперсия выписаны в stats.haz_trend_day
  без единого неизвестного параметра. Разность двух Z с независимых плеч имеет разброс не больше
  sqrt(2) (у интерполированного плеча он меньше: sqrt((1-w)^2 + w^2) <= 1), поэтому порог
  1.6449*sqrt(2) = 2.3262 — оценка сверху.
  Чувствительность хода риска. При h(t) = h*(1 + beta*u), u из [-1, 1], и K = 4 середины частей
  дают u = (-0.75, -0.25, +0.25, +0.75), откуда sigma_x^2 = 0.3125, Z = beta*sqrt(0.3125*N) и
  beta_min = 2.943/sqrt(N). Требование N >= 900 на плечо (beta_min <= 10 %) — ниже него часть
  непроверяема, а не провалена.
  Защёлка. Точный перестановочный критерий по пяти глубинам сброса, наименьшее достижимое
  p = 1/5! = 0.0083, порог 0.05 достижим с запасом.

ПРАВИЛО Ф29, ЗАПИСАНО ДО СЧЁТА
  (а) КОНТРОЛЬ ИЗМЕРИТЕЛЬНОЙ МАШИНЫ, первым. При a_n = 0 ёмкость от состояния не зависит и во
      времени не меняется, поэтому её среднее обязано равняться mu*<N0> по полосе при КАЖДОМ mu,
      с точностью округления накопителя (допуск 1e-9 при замеренных 8.8e-13). Контроль истинен по
      построению и от объёма выборки НЕ зависит — ровно то, чего не было у двух прежних. Он же
      поймал бы дефект ядра 21.10, где отклонение было 4,6 %. Сверять два блока с одинаковыми
      параметрами нельзя: Runner их склеивает, и контроль был бы тавтологией.
  (б) ПРОГРЕССИРОВАНИЕ СВЕРХ СОПОСТАВЛЕННОЙ СТАТИКИ. Прибавка петли минус прибавка статики,
      приведённой к тому же уровню первой половины, превышает MDE разности. Это форма Ф28(ж).
  (в) ХОД РИСКА СВЕРХ СОПОСТАВЛЕННОЙ СТАТИКИ. Z(петля) - Z(статика) > 2.3262. Против нуля ход
      риска НЕ проверяется: его ноль ложен и измерен.
  (г) ЗАЩЁЛКА. При мягком сбросе удержание не ниже половины И растёт с мягкостью сброса.
  (д) ЦЕНА. Эпизоды сохраняются: доля побывавших в обоих состояниях не ниже половины от
      разомкнутой модели. Мера свободна от цензурирования окном наблюдения (дефект Ф27).
  (е) ХАРАКТЕР ЭПИЗОДОВ: петля даёт НЕ более частые, а более длинные эпизоды. Частота срывов на
      набор-сутки под риском ниже, чем у разомкнутой, И средняя длительность выше. Замечено на
      замере 23.10 (частота 0.0079 против 0.0161, длительность 9.33 против 7.13 сут) и проверяется
      здесь на другом сиде и другой длине прогона.

ЧЕГО ПРАВИЛО НЕ ДЕЛАЕТ. Не переписывает вердикты Ф28 — там контроль упал, и все семь частей
остаются как записаны. Не спрашивает про постоянную возврата: Ф28(е) дала размах +0.0031 при
MDE 0.0117, то есть скорость задаёт глубина потери, а не возврат. И не содержит ни одного критерия
против абсолютного нуля.

ПРОГОНЯТЬ НА ТРЕТЬЕМ СИДЕ: 4242, 7331 и 9157 участвовали в проектировании.
"""
import math
import numpy as np
from .. import stats as st
from . import _blocks as B

NAME = 'Ф29'
ALT_LO, ALT_HI = 0.05, 0.95
BROKEN = 0.9
HALF = 0.5
ZC = 1.6449                      # односторонний 5 % у нормального распределения
ZD = ZC * math.sqrt(2.0)         # разность двух Z с независимых плеч: 2.3262, оценка сверху
CAPTOL = 1e-9                    # допуск контроля ёмкости: округление 8.8e-13, запас трёх порядков


def needs(cfg):
    return B.haz_work(cfg) + B.haz_stat(cfg) + B.haz_hys(cfg)


def _alt(rr, band):
    D = np.asarray(rr['Dbar'], float)[band]
    return float(((D > ALT_LO) & (D < ALT_HI)).mean()), float((D > BROKEN).mean())


def _lvl(rr, band):
    p1 = np.asarray(rr['D_ph1'], float)[band]; p1 = p1[np.isfinite(p1)]
    return float(p1.mean()) if len(p1) else float('nan')


def _prog(rr, band):
    """Парная внутри набора прибавка доли повреждённых: вторая половина минус первая."""
    p1 = np.asarray(rr['D_ph1'], float)[band]; p2 = np.asarray(rr['D_ph2'], float)[band]
    d = (p2 - p1); d = d[np.isfinite(d)]
    if len(d) < 3:
        return float('nan'), float('nan'), 0
    return float(d.mean()), float(np.std(d, ddof=1) / math.sqrt(len(d))), len(d)


def _dur(rr, band):
    es = np.asarray(rr['epsum'], float)[band]; en = np.asarray(rr['epn'], float)[band]
    m = en > 0
    return float((es[m] / en[m]).mean()) if m.any() else float('nan')


def _arm(rr, band, nd):
    d, se, n = _prog(rr, band)
    Z, N, rate = st.haz_trend_day(np.asarray(rr['on_day'], float)[band],
                                  np.asarray(rr['risk_day'], float)[band],
                                  B.WCUT29, float(nd), B.K29, 'increase')
    return dict(d=d, se=se, n=n, mde=st.mde(se), lvl=_lvl(rr, band), Z=Z, N=N, rate=rate,
                dur=_dur(rr, band), cap=float(np.nanmean(np.asarray(rr['ncbar'], float)[band])),
                ok=bool(N >= B.NMIN29 and Z == Z and d == d),
                beta_min=(2.943 / math.sqrt(N)) if N > 0 else float('nan'))


def _interp(sl, lvl, key):
    """Линейная интерполяция поля key статического плеча на уровень lvl между НАКРЫВАЮЩИМИ точками."""
    lo = [z for z in sl if z['lvl'] <= lvl]; hi = [z for z in sl if z['lvl'] >= lvl]
    if not lo or not hi or lvl != lvl:
        return float('nan'), float('nan'), False
    zl, zh = lo[-1], hi[0]
    w = 0.0 if zh['lvl'] == zl['lvl'] else (lvl - zl['lvl']) / (zh['lvl'] - zl['lvl'])
    val = zl[key] + w * (zh[key] - zl[key])
    sev = math.hypot((1 - w) * zl.get('se', 0.0), w * zh.get('se', 0.0))
    return val, sev, True


def run(ctx):
    S = ctx.S; band = S['band']; nd = B.D29
    vt = lambda v: 'выполнено' if v is True else ('не выполнено' if v is False else str(v))

    off = _arm(ctx.b('n29_open'), band, nd)
    on = _arm(ctx.b('n29_loop'), band, nd)
    stat = []
    for mu in B.N0M29:
        z = _arm(ctx.b('n29_s_m%g' % mu), band, nd); z['mu'] = mu; stat.append(z)

    hys = []
    for a_ in (0.0, B.AN29):
        for r_ in B.REL29:
            rr = ctx.b('n29_h_a%g_r%g' % (a_, r_))
            q1 = np.asarray(rr['D_ph1'], float)[band]; q2 = np.asarray(rr['D_ph2'], float)[band]
            b1 = float((q1 > BROKEN).mean()); b2 = float((q2 > BROKEN).mean())
            hys.append(dict(a=a_, rel=r_, br1=b1, br2=b2,
                            keep=(b2 / b1) if b1 > 1e-9 else float('nan')))
    h_on_l = [z for z in hys if z['a'] == B.AN29]

    # ---- (а) контроль измерительной машины: ёмкость против аналитического ожидания ----
    n0bar = float(np.mean(np.asarray(S['P']['N0'], float).ravel()[band]))
    dev = [abs(z['cap'] - z['mu'] * n0bar) / max(n0bar, 1e-30) for z in stat]
    worst = max(dev) if dev else float('inf')
    a_v = bool(worst <= CAPTOL)

    sl = sorted((z for z in stat if z['lvl'] == z['lvl'] and z['ok']), key=lambda z: z['lvl'])
    d_st, se_st, br1_ok = _interp(sl, on['lvl'], 'd')
    Z_st, _, br2_ok = _interp(sl, on['lvl'], 'Z')

    # ---- (б) прогрессирование сверх сопоставленной статики ----
    gain = on['d'] - d_st
    se_g = math.hypot(on['se'], se_st) if se_st == se_st else float('nan')
    mde_g = st.mde(se_g) if se_g == se_g else float('nan')
    b_v = ('непроверяемо' if a_v is not True or not br1_ok or not on['ok'] or gain != gain
           else bool(gain > mde_g))

    # ---- (в) ход риска сверх сопоставленной статики ----
    dz = on['Z'] - Z_st
    c_v = ('непроверяемо' if a_v is not True or not br2_ok or not on['ok'] or dz != dz
           else bool(dz > ZD))

    # ---- (г) защёлка ----
    soft = max(h_on_l, key=lambda z: z['rel'])
    rk, pk, nk = st.perm_rank_p([z['rel'] for z in h_on_l], [z['keep'] for z in h_on_l], 'increase')
    pkmin = 1.0 / math.factorial(nk) if nk and nk <= 8 else 0.0
    g_v = ('непроверяемо' if a_v is not True or not (soft['keep'] == soft['keep']) or pkmin > 0.05
           else bool(soft['keep'] >= HALF and (pk <= 0.05 if pk == pk else rk > 0)))

    # ---- (д) цена ----
    alt_on, _ = _alt(ctx.b('n29_loop'), band); alt_off, _ = _alt(ctx.b('n29_open'), band)
    rel = (alt_on / alt_off) if alt_off > 1e-12 else float('nan')
    d_v = ('непроверяемо' if a_v is not True or rel != rel else bool(rel >= HALF))

    # ---- (е) характер эпизодов: реже, но дольше ----
    e_v = ('непроверяемо' if a_v is not True or not (on['rate'] == on['rate'] and off['rate'] == off['rate']
                                                     and on['dur'] == on['dur'] and off['dur'] == off['dur'])
           else bool(on['rate'] < off['rate'] and on['dur'] > off['dur']))

    md = ['\n## %s. Петля ёмкости, измеренная только сопоставленными различиями\n' % NAME,
          'В модели с поглощающими состояниями и разнородной популяцией абсолютного нуля для '
          'накопительных величин нет: доля сломанных растёт сама, риск срыва падает сам (измерено '
          '23.10, Z = −2,63 при разомкнутой петле). Поэтому здесь нет ни одного критерия против '
          'нуля — только плечо против плеча, приведённого к тому же уровню повреждения.\n',
          '| плечо | ёмкость | уровень ф1 | прибавка | SE | Z хода риска | срывов | частота | длит. |',
          '|---|---|---|---|---|---|---|---|---|']
    for nm, z in [('разомкнута', off), ('петля a = %g' % B.AN29, on)] + \
                 [('статика mu = %g' % z['mu'], z) for z in stat]:
        md.append('| %s | %.4f | %.4f | %+.4f | %.4f | %+.2f | %d | %.4f | %.2f |'
                  % (nm, z['cap'], z['lvl'], z['d'], z['se'], z['Z'], z['N'], z['rate'], z['dur']))
    md += ['', '| глубина сброса | петля | сломано ф1 | сломано ф2 | удержание |', '|---|---|---|---|---|']
    for z in hys:
        md.append('| %g | %s | %.3f | %.3f | %s |'
                  % (z['rel'], 'нет' if z['a'] == 0 else 'a = %g' % z['a'], z['br1'], z['br2'],
                     ('%.3f' % z['keep']) if z['keep'] == z['keep'] else '—'))
    md += ['', '| часть | получено | ожидание до счёта | вывод |', '|---|---|---|---|',
           '| а: контроль машины — ёмкость равна mu·<N0> | наибольшее отклонение %.3g при <N0> = '
           '%.4f | не больше %.0e | %s |' % (worst, n0bar, CAPTOL, vt(a_v)),
           '| б: прогрессирование сверх сопоставленной статики | %+.4f при SE %.4f и MDE %.4f '
           '(петля %+.4f против статики %+.4f при уровне %.4f%s) | больше MDE | %s |'
           % (gain, se_g, mde_g, on['d'], d_st, on['lvl'],
              '' if br1_ok else '; СЕТКА НЕ НАКРЫЛА', vt(b_v)),
           '| в: ход риска сверх сопоставленной статики | %+.2f (петля %+.2f, статика %+.2f; '
           'различимый подъём %.1f %%) | больше %.4f | %s |'
           % (dz, on['Z'], Z_st, 100 * on['beta_min'], ZD, vt(c_v)),
           '| г: защёлка растёт с мягкостью сброса | удержание %s при сбросе %g, rho = %s (p = %s, '
           'наименьшее достижимое %.4f) | не ниже половины И монотонно | %s |'
           % (('%.3f' % soft['keep']) if soft['keep'] == soft['keep'] else '—', soft['rel'],
              ('%+.3f' % rk) if rk == rk else '—', ('%.4f' % pk) if pk == pk else '—', pkmin, vt(g_v)),
           '| д: эпизоды сохраняются | %s от разомкнутой | не ниже половины | %s |'
           % (('%.3f' % rel) if rel == rel else '—', vt(d_v)),
           '| е: эпизоды реже, но дольше | частота %.4f против %.4f, длительность %.2f против %.2f '
           '| частота ниже И длительность выше | %s |'
           % (on['rate'], off['rate'], on['dur'], off['dur'], vt(e_v))]

    out = dict(off=off, on=on, stat=stat, hys=hys, capdev=worst, n0bar=n0bar,
               d_stat=d_st, Z_stat=Z_st, bracketed=bool(br1_ok and br2_ok), alt_rel=rel,
               a=dict(verdict=a_v), b=dict(verdict=b_v, gain=gain, se=se_g, mde=mde_g),
               v=dict(verdict=c_v, dz=dz), g=dict(verdict=g_v, rho=rk, p=pk),
               d=dict(verdict=d_v), e=dict(verdict=e_v))
    ctx.verdict(NAME, 'а', worst, a_v, note='ёмкость против аналитического ожидания mu·<N0>: контроль машины')
    ctx.verdict(NAME, 'б', gain, b_v, note='прогрессирование сверх статики, сопоставленной по уровню первой половины')
    ctx.verdict(NAME, 'в', dz, c_v, note='ход риска сверх сопоставленной статики; против нуля не проверяется')
    ctx.verdict(NAME, 'г', soft['keep'], g_v, note='удержание при мягком сбросе и его рост с мягкостью')
    ctx.verdict(NAME, 'д', rel, d_v, note='эпизодичность в долях от разомкнутой модели')
    ctx.verdict(NAME, 'е', on['rate'] - off['rate'], e_v, note='эпизоды реже, но дольше: частота и длительность')
    return out, md
