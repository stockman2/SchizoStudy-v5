# -*- coding: utf-8 -*-
"""Ф24: РЕДКИЕ СИЛЬНЫЕ ТОЛЧКИ РАБОТАЮТ ЛУЧШЕ РОВНОГО ПОДЪЁМА НАГРУЗКИ.

ОТКУДА ВОПРОС. Два расхождения с арифметикой опасности, найденные 16.10, смотрят в
ПРОТИВОПОЛОЖНЫЕ стороны, и это и есть зацепка:
  Ф8(г′): наблюдаемый прирост частоты срывов от всплесков 0.00523 против предсказанных 0.00053 —
          наблюдение ВДЕСЯТЕРО сильнее;
  Ф2(б):  наблюдаемая доля повреждавшихся при двойном суточном размахе 0.2945 против предсказанных
          0.8468 — наблюдение ВТРОЕ слабее.
Ни выпуклость опасности (неравенство Йенсена), ни замена плотности на вероятность превышения такого
дать не могут: обе поправки двигают предсказание в ОДНУ сторону. Значит дело не в опасности, а в
том, чего в ней нет вовсе, — в ЗАПАЗДЫВАНИИ ЗАЩИТЫ. Всплеск на шесть часов приходит на
неадаптированную клетку; поднятый на сутки размах защита успевает частично скомпенсировать за свои
12 и 63 часа. Один механизм объясняет оба расхождения и объясняет, почему они разного знака.

КАК ЭТО ПРОВЕРИТЬ БЕЗ ЕДИНОГО ПОДОГНАННОГО ЧИСЛА. Соблазн — дописать в предсказатель множитель
адаптации. Он требует одного параметра (на сколько полная адаптация съедает превышение нагрузки),
а вывести его можно только из алгебры складки, то есть на деле подогнать. Поэтому вопрос ставится
иначе — сравнением, в котором всё лишнее закреплено:
  sigs  задаёт ДИСПЕРСИЮ нагрузки при неизменном среднем (среднее логнормали скомпенсировано
        сдвигом 0,5*sigs^2 в самой модели);
  tslow задаёт ВРЕМЯ КОРРЕЛЯЦИИ при неизменных среднем И дисперсии.
Значит перебор по tslow изолирует ровно одну вещь: успевает ли защита адаптироваться. Короткое
время корреляции — не успевает — срывов больше. Направление даёт механизм, а МЕСТО перелома даётся
двумя известными постоянными защиты, 12 ч = 0,5 сут и 63 ч = 2,625 сут. Подгонять нечего.

ОГОВОРКА, КОТОРУЮ НАДО ЧИТАТЬ ВМЕСТЕ С ВЫВОДОМ. Рабочее значение sigs равно нулю: медленный шум
нагрузки снят из модели дважды, по Ф6(в) и Ф18. Здесь он ВКЛЮЧЁН намеренно (0,08) — не как рабочее
положение, а как единственный доступный способ менять временной масштаб нагрузки, не трогая её
среднее и дисперсию. Вывод Ф24 относится к механизму запаздывания защиты, а не к обоснованию
медленного шума.

ПРАВИЛО Ф24, ЗАПИСАНО ДО СЧЁТА
  (а) ГЛАВНАЯ ЧАСТЬ. При постоянных среднем и дисперсии нагрузки доля повреждавшихся ПАДАЕТ с
      ростом времени корреляции: критерий тренда Кохрана–Армитеджа по упорядоченным tslow,
      направление «меньше», p не больше 0,05. Критерий тренда, а не наклон прямой: зависимость
      обязана насыщаться при tslow много больше постоянных защиты, и прямая по насыщающейся кривой
      занижена (ошибка найдена 14.10 на Ф3(б)).
  (б) МЕСТО ПЕРЕЛОМА, предсказано постоянными защиты. Не меньше половины всего падения доли
      происходит на участке между 0,5 и 2,625 суток, то есть между двумя постоянными защиты.
      Нулевое значение — доля участка в полном диапазоне перебора по логарифму времени, то есть
      ln(2.625/0.5)/ln(10/0.2) = 0.424: столько дало бы падение, равномерное по логарифму.
  (в) ПАРНЫЙ КОНТРОЛЬ, решающий. Если зависимость от tslow делает именно адаптация ВТОРОЙ ступени,
      то при короткой её памяти (taus = 12 ч вместо 63 ч) перепад между краями перебора обязан
      ослабнуть не меньше чем вдвое. Блоки те же наборы и то же зерно, меняется только память.
  (г) СОГЛАСИЕ СО ЗНАКАМИ, ради чего правило и писалось. Направление, найденное в (а), обязано
      объяснять оба исходных расхождения: короткое воздействие сильнее предсказания, длительное
      слабее. Это проверка на два знака из двух; при случайных знаках вероятность 1/4, то есть
      критерий слабый, и он записан как подтверждение связности рассказа, а не как доказательство.
"""
import math
import numpy as np
from .. import stats as st
from . import _blocks as B
from ._meas import meas

NAME = 'Ф24'
LO, HI = 0.5, 2.625          # постоянные защиты в сутках: 12 ч и 63 ч


def needs(cfg):
    return B.tslow_scan(cfg)


def run(ctx):
    S = ctx.S; cfg = ctx.cfg; nd = cfg.d['run']['days']; band = S['band']
    rows = []
    for t in B.TSCAN:
        mm = meas(ctx.b('ts_%.3f' % t), nd, band)
        rows.append(dict(tslow=t, share_ever=mm['share_ever'], n_sets=mm['n_sets'],
                         dur=mm['dur'], nday=mm['nday_pool'], n_ep=mm['n_ep']))
    ctl = []
    for t in (B.TSCAN[0], B.TSCAN[-1]):
        mm = meas(ctx.b('ts_nm_%.3f' % t), nd, band)
        ctl.append(dict(tslow=t, share_ever=mm['share_ever'], n_sets=mm['n_sets'], dur=mm['dur']))

    # ---- (а) тренд по упорядоченным tslow ----
    kk = [int(round(z['share_ever'] * z['n_sets'])) for z in rows]
    nn = [int(z['n_sets']) for z in rows]
    a = st.trend_test(kk, nn, [math.log(z['tslow']) for z in rows], direction='decrease')

    # ---- (б) где именно происходит падение ----
    sh = np.array([z['share_ever'] for z in rows], float)
    tot = float(sh[0] - sh[-1])
    i_lo = B.TSCAN.index(LO); i_hi = B.TSCAN.index(HI)
    seg = float(sh[i_lo] - sh[i_hi])
    frac = seg / tot if abs(tot) > 1e-12 else float('nan')
    null_b = math.log(HI / LO) / math.log(B.TSCAN[-1] / B.TSCAN[0])     # равномерно по логарифму
    se_b = (st.prop_se(sh[i_lo], nn[i_lo]) ** 2 + st.prop_se(sh[i_hi], nn[i_hi]) ** 2) ** 0.5
    se_frac = se_b / abs(tot) if abs(tot) > 1e-12 else float('nan')
    b = st.adjudicate(frac, 0.5, se_frac, 'ge', null=null_b, n=min(nn), lim=(-2., 2.))

    # ---- (в) парный контроль: короткая память второй ступени ----
    d_full = float(rows[0]['share_ever'] - rows[-1]['share_ever'])
    d_nm = float(ctl[0]['share_ever'] - ctl[1]['share_ever'])
    se_c = (st.prop_se(ctl[0]['share_ever'], ctl[0]['n_sets']) ** 2
            + st.prop_se(ctl[1]['share_ever'], ctl[1]['n_sets']) ** 2) ** 0.5
    # Утверждение: перепад при короткой памяти не больше половины перепада при долгой.
    c = st.adjudicate(d_nm, 0.5 * d_full, se_c, 'le', null=d_full, n=min(ctl[0]['n_sets'], ctl[1]['n_sets']))

    # ---- (г) согласие со знаками исходных расхождений ----
    # Короткое воздействие (всплеск) обязано быть СИЛЬНЕЕ предсказания, длительное (размах) слабее.
    # Знаки взяты из отчёта 16.10 и здесь только сверяются с направлением (а), а не измеряются.
    dir_ok = (a.get('verdict') is True)
    g = dict(spike_stronger=True, swing_weaker=True, direction_from_a=dir_ok,
             verdict=bool(dir_ok), p_random=0.25)

    vt = lambda v: 'выполнено' if v is True else ('не выполнено' if v is False else str(v))
    md = ['\n## %s. Редкие сильные толчки против ровного подъёма нагрузки\n' % NAME,
          'Перебор времени корреляции медленного шума при НЕИЗМЕННЫХ среднем и дисперсии нагрузки '
          '(sigs = %.2f, среднее логнормали скомпенсировано в самой модели). Рабочее значение sigs '
          'равно нулю; здесь шум включён намеренно — это единственный способ менять временной '
          'масштаб, не трогая среднее и дисперсию. Постоянные защиты для сравнения: %.2f и %.3f суток.\n'
          % (B.SIGS_T, LO, HI),
          '| время корреляции, сут | доля повреждавшихся | наборов | длительность, сут | срывов в сутки | эпизодов |',
          '|---|---|---|---|---|---|']
    for z in rows:
        md.append('| %.3f%s | %.4f | %d | %s | %.4f | %d |'
                  % (z['tslow'], ' (постоянная защиты)' if z['tslow'] in (LO, HI) else '',
                     z['share_ever'], z['n_sets'],
                     ('%.2f' % z['dur']) if z['dur'] == z['dur'] else '—', z['nday'], z['n_ep']))
    md += ['', '| контроль: память второй ступени 12 ч | доля повреждавшихся | наборов |', '|---|---|---|']
    for z in ctl:
        md.append('| tslow = %.3f | %.4f | %d |' % (z['tslow'], z['share_ever'], z['n_sets']))
    md += ['', '| часть | получено | ожидание до счёта | вывод |', '|---|---|---|---|',
           '| а: срывов меньше при большем времени корреляции | z = %s, p = %s по %d точкам | '
           'p не больше 0,05, направление «меньше» | %s |'
           % (('%.2f' % a['z']) if a.get('z') == a.get('z') else '—',
              ('%.3g' % a['p']) if a.get('p') == a.get('p') else '—', len(rows), vt(a['verdict'])),
           '| б: падение сосредоточено между постоянными защиты | доля участка %s из полного '
           'падения %.4f | не меньше 0,50; равномерно по логарифму дало бы %.3f | %s |'
           % (('%.3f' % frac) if frac == frac else '—', tot, null_b, vt(b['verdict'])),
           '| в: при короткой памяти перепад слабее вдвое | перепад %.4f против %.4f | не больше %.4f | %s |'
           % (d_nm, d_full, 0.5 * d_full, vt(c['verdict'])),
           '| г: знаки обоих исходных расхождений объяснены | всплеск сильнее, размах слабее | '
           'направление (а) обязано быть «меньше»; при случайных знаках p = 0,25 | %s |' % vt(g['verdict'])]
    if a.get('verdict') is True and c.get('verdict') is True:
        md.append('\n**Запаздывание защиты подтверждено как механизм.** Зависимость от времени корреляции '
                  'есть, она в предсказанную сторону, и при короткой памяти второй ступени она ослабевает — '
                  'то есть делает её именно адаптация, а не выпуклость опасности. Отсюда следствие для '
                  'предсказателя: арифметика опасности, считающая только СРЕДНЮЮ нагрузку, обязана '
                  'завышать отклик на длительное воздействие и занижать на короткое, что и наблюдалось в '
                  'Ф2(б) и Ф8(г′). Клинически это говорит, что опасен не уровень нагрузки, а её рваность.')
    elif a.get('verdict') is False:
        md.append('\n**Зависимости от времени корреляции нет.** Тогда запаздывание защиты не объясняет '
                  'расхождения Ф2(б) и Ф8(г′), и искать надо в другом месте. Первый кандидат — '
                  'нелинейность по самому размаху внутри суток: всплеск поднимает нагрузку выше верха '
                  'окна, а размах — нет, и опасность за верхом окна может идти по другому закону.')
    out = dict(rows=rows, control=ctl, a=dict(**a), b=dict(**b, frac=frac, total_drop=tot, null_uniform=null_b),
               c=dict(**c, drop_full=d_full, drop_short_memory=d_nm), g=g, sigs=B.SIGS_T)
    ctx.verdict(NAME, 'а', a.get('z', float('nan')), a['verdict'],
                note='тренд доли повреждавшихся по времени корреляции, направление «меньше»')
    ctx.verdict(NAME, 'б', frac, b['verdict'],
                note='доля падения между постоянными защиты; равномерно по логарифму дало бы %.3f' % null_b)
    ctx.verdict(NAME, 'в', d_nm, c['verdict'], note='перепад при памяти 12 ч против 63 ч, парно')
    ctx.verdict(NAME, 'г', 2.0, g['verdict'], note='знаки Ф2(б) и Ф8(г′) против направления (а); слабый критерий')
    return out, md
