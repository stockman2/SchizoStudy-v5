# -*- coding: utf-8 -*-
"""Ф26: ДОФАМИНОВАЯ ПЕТЛЯ — делает ли она что-нибудь, чего не делает простой подъём нагрузки.

ОТКУДА ВОПРОС. Дофамин из модели не вырезан, он вынесен за скобки с обоих концов: его вклад в
окислительную нагрузку сидит в nu0, его действие на баланс возбуждения и торможения несёт сама
активность, а петля Грейса (растормаживание -> гиппокамп -> VTA -> стриатум) берёт на вход ровно
то, что у модели на выходе. Литература подтверждает направление — катаболизм дофамина даёт
перекись, а избыток внеклеточного дофамина в развитии стойко снижает плотность PV-клеток,— но не
даёт НИ ОДНОГО количественного значения: ни скорости образования, ни постоянной времени петли.

ЧТО ДОБАВЛЕНО. Один скаляр d (тонус), которым движет сама доля повреждённых с постоянной tau_d, и
обратно в нагрузку множителем (1 + a_da*d). При a_da = 0 петля РАЗОМКНУТА и модель воспроизводится
побитово — проверено.

ЧЕГО ЭТА ПЕТЛЯ ЗАВЕДОМО НЕ СДЕЛАЕТ, и это выяснено пробой ДО написания правила. Она не дотянет
модель до лестницы захвата. Потолок там задаёт не повреждение, а сама связь: тождественно kD <= k,
а у сломанных наборов доля повреждённых уже 0,999. Накачивать нечего. Поэтому правило про лестницу
не спрашивает вовсе; оно спрашивает про РАСПРОСТРАНЁННОСТЬ — сколько наборов вообще сваливается в
необратимое состояние.

ГЛАВНАЯ ОПАСНОСТЬ, РАДИ КОТОРОЙ ПРАВИЛО И УСТРОЕНО ТАК. Петля поднимает нагрузку множителем
(1 + a_da*D). Голый результат «сломалось больше наборов» не доказывает ничего: ровно столько же
сломал бы и ПОСТОЯННЫЙ множитель той же величины. Если петля не даёт ничего сверх своего
статического эквивалента, то дофамин здесь — ручка без динамики, и добавлять его в модель незачем.
Это и есть фальсификатор, и методика взята у Ф22(б), где она уже сработала.

ПРАВИЛО Ф26, ЗАПИСАНО ДО СЧЁТА
  (а) Направление. При рабочем положении нагрузки замкнутая петля ломает БОЛЬШЕ наборов, чем
      разомкнутая, на тех же наборах и том же шуме. Порог — минимально различимый эффект.
  (б) ФАЛЬСИФИКАТОР, решающий. По перебору q строится статический эквивалент: точка, где средняя
      нагрузка та же, что создала петля. Если доля сломанных у петли совпадает с эквивалентом в
      пределах допуска равносильности — состояние-зависимость не даёт НИЧЕГО, и петля отвергается
      как ручка. Утверждение проходит только при превышении сверх эквивалента, большем MDE.
  (в) ГИСТЕРЕЗИС. При ПОНИЖЕННОЙ нагрузке (q ниже рабочего) замкнутая петля обязана удерживать
      сломанные наборы там, где разомкнутая их отпускает: разность долей при пониженной нагрузке
      не меньше, чем при рабочей. Это и есть содержательное отличие хронического состояния от
      эпизодического, и без него «необратимость» — просто слово.
  (г) ЦЕНА. В точке, где (а) выполняется, уже установленные величины обязаны остаться в измеренных
      пределах: длительность эпизода и высота предвестника — в пределах 3 SE от значений
      разомкнутой петли. Если петля покупает распространённость ценой разрушения закона
      длительности, это записывается, а не замалчивается.

ЦЕНА СЧЁТА. Пятнадцать блоков: пять положений нагрузки на три силы петли.
"""
import math
import numpy as np
from .. import stats as st
from . import _blocks as B
from ._meas import meas

NAME = 'Ф26'
BROKEN = 0.9          # доля повреждённых, выше которой набор считается сломанным необратимо
HEALTHY = 0.01        # и ниже которой — нетронутым; между ними в рабочей точке почти никого


def needs(cfg):
    return B.da_scan(cfg)


def _cell(ctx, dq, a, nd, band):
    rr = ctx.b('da_m%g_a%g' % (dq, a))
    D = np.asarray(rr['Dbar'], float)[band]
    L = np.asarray(rr['Lbar'], float)[band]
    mm = meas(rr, nd, band)
    n = int(len(D))
    br = float((D > BROKEN).mean()) if n else float('nan')
    return dict(dq=dq, a=a, n=n, broken=br, se=st.prop_se(br, n),
                healthy=float((D < HEALTHY).mean()) if n else float('nan'),
                Lbar=float(np.nanmean(L)), Dbar=float(np.nanmean(D)),
                dur=mm['dur'], share_ever=mm['share_ever'])


def run(ctx):
    S = ctx.S; cfg = ctx.cfg; nd = cfg.d['run']['days']; band = S['band']
    grid = {(z['dq'], z['a']): z for z in
            (_cell(ctx, mu, a, nd, band) for mu in B.NUDA for a in B.ADA)}
    A1 = max(B.ADA)                                   # сильная петля
    op = grid[(1.0, 0.0)]; cl = grid[(1.0, A1)]       # рабочая точка: разомкнуто / замкнуто

    # ---- (а) направление ----
    se_a = math.sqrt(op['se'] ** 2 + cl['se'] ** 2)
    a = st.adjudicate(cl['broken'], op['broken'] + st.mde(se_a), se_a, 'ge',
                      null=op['broken'], n=min(op['n'], cl['n']))

    # ---- (б) статический эквивалент ----
    # Петля подняла среднюю нагрузку с op['Lbar'] до cl['Lbar']. Ищем в q-переборе точку с
    # РАЗОМКНУТОЙ петлёй, у которой средняя нагрузка ближе всего к этой; сравниваем доли сломанных.
    stat = [grid[(mu, 0.0)] for mu in B.NUDA]
    eq = min(stat, key=lambda z: abs(math.log(max(z['Lbar'], 1e-30)) - math.log(max(cl['Lbar'], 1e-30))))
    mism = abs(math.log(max(eq['Lbar'], 1e-30)) - math.log(max(cl['Lbar'], 1e-30)))
    se_b = math.sqrt(eq['se'] ** 2 + cl['se'] ** 2)
    gap = cl['broken'] - eq['broken']
    b = st.adjudicate(gap, st.mde(se_b), se_b, 'ge', null=0.0, n=min(eq['n'], cl['n']))
    # Если подбор эквивалента плох (нагрузки разошлись больше чем на 20 % по логарифму), сравнение
    # нечестно, и это надо сказать, а не прятать за вердиктом.
    if mism > 0.25:
        b = dict(b, verdict='непроверяемо',
                 reason='эквивалент подобран плохо: нагрузки расходятся на %.0f %% по логарифму' % (100 * mism))

    # ---- (в) гистерезис: двухфазный протокол ----
    # Первая половина прогона — высокая нагрузка (ломает почти всех), вторая — низкая. Смотрим долю
    # повреждённых ВО ВТОРОЙ фазе: разомкнутая модель обязана отпустить, замкнутая — удержать.
    hys = {}
    for a_ in B.ADA:
        rr = ctx.b('da_hys_a%g' % a_)
        p1 = np.asarray(rr['D_ph1'], float)[band]; p2 = np.asarray(rr['D_ph2'], float)[band]
        n_ = int(len(p1))
        hys[a_] = dict(a=a_, n=n_, br1=float((p1 > BROKEN).mean()), br2=float((p2 > BROKEN).mean()),
                       se1=st.prop_se(float((p1 > BROKEN).mean()), n_),
                       se2=st.prop_se(float((p2 > BROKEN).mean()), n_))
    h0, h1 = hys[0.0], hys[A1]
    ret0 = h0['br1'] - h0['br2']            # сколько отпустила разомкнутая
    ret1 = h1['br1'] - h1['br2']            # сколько отпустила замкнутая
    se_c = math.sqrt(h0['se1'] ** 2 + h0['se2'] ** 2 + h1['se1'] ** 2 + h1['se2'] ** 2)
    # Утверждение: замкнутая отпускает МЕНЬШЕ, то есть удерживает сломанное состояние.
    c = st.adjudicate(ret1, ret0 - st.mde(se_c), se_c, 'le', null=ret0, n=min(h0['n'], h1['n']))
    d_work = cl['broken'] - op['broken']; d_low = ret1

    # ---- (г) цена ----
    if cl['dur'] != cl['dur'] and op['dur'] == op['dur']:
        # Эпизодов у петли НЕТ ВОВСЕ: всё, что могло сломаться, сломалось навсегда. Это не
        # «нечем мерить», а прямое нарушение — у больных эпизоды есть, а здесь их не осталось.
        g = dict(verdict=False, value=float('nan'), mde=float('nan'),
                 reason='у замкнутой петли не завершилось ни одного эпизода: состояние необратимо '
                        'у всех сломанных наборов, эпизодической структуры не осталось')
    elif op['dur'] == op['dur'] and cl['dur'] == cl['dur']:
        dd = abs(cl['dur'] - op['dur'])
        se_d = max(abs(op['dur']), 1e-9) * 0.05        # 5 % от длительности: грубая, но явная мера
        g = st.adjudicate(dd, 3.0 * se_d, se_d, 'le', null=0.5 * abs(op['dur']), n=min(op['n'], cl['n']))
    else:
        g = dict(verdict='непроверяемо', value=float('nan'), mde=float('nan'))

    vt = lambda v: 'выполнено' if v is True else ('не выполнено' if v is False else str(v))
    md = ['\n## %s. Дофаминовая петля: ручка или механизм\n' % NAME,
          'Тонус движет доля повреждённых (петля Грейса идёт от повреждения через гиппокамп и VTA), '
          'постоянная %.1f суток, обратно в нагрузку множителем (1 + a·d). Сила a = 0 — петля '
          'РАЗОМКНУТА, то есть прежняя модель; она воспроизводится побитово. Сломанным считается '
          'набор с долей повреждённых выше %.2f, нетронутым — ниже %.2f: в рабочей точке популяция '
          'бимодальна, и между этими кучами почти никого.\n' % (B.TAU_D_DA, BROKEN, HEALTHY),
          'Гистерезис считается отдельными блоками по двухфазному протоколу: первую половину '
          'прогона множитель %g (ломает почти всех), вторую — %g.\n' % (B.NU_BREAK, B.NU_REL),
          '| множитель нагрузки | сила петли | нагрузка | сломано | нетронуто | доля повреждённых | длительность |',
          '|---|---|---|---|---|---|---|']
    for dq in B.NUDA:
        for a_ in B.ADA:
            z = grid[(dq, a_)]
            md.append('| %g%s | %g%s | %.4f | %.3f ± %.3f | %.3f | %.4f | %s |'
                      % (dq, ' (рабочая)' if dq == 1.0 else '', a_, ' (разомкнуто)' if a_ == 0 else '',
                         z['Lbar'], z['broken'], z['se'], z['healthy'], z['Dbar'],
                         ('%.2f' % z['dur']) if z['dur'] == z['dur'] else '—'))
    md += ['', '| часть | получено | ожидание до счёта | вывод |', '|---|---|---|---|',
           '| а: петля ломает больше, чем разомкнутая | %.3f против %.3f | превышение не меньше '
           'MDE = %.3f | %s |' % (cl['broken'], op['broken'], st.mde(se_a), vt(a['verdict'])),
           '| б: ФАЛЬСИФИКАТОР — сверх статического эквивалента | %.3f против %.3f при сдвиге %+.2f '
           '(нагрузки сошлись на %.0f %%) | превышение не меньше MDE = %.3f | %s |'
           % (cl['broken'], eq['broken'], eq['dq'], 100 * (1 - mism), st.mde(se_b), vt(b['verdict'])),
           '| в: гистерезис — держит сломанное состояние | отпустила %.3f против %.3f у разомкнутой '
           '(сломано в первой фазе: %.3f и %.3f) | меньше на MDE = %.3f | %s |'
           % (ret1, ret0, h1['br1'], h0['br1'], st.mde(se_c), vt(c['verdict'])),
           '| г: цена — длительность не разрушена | %s против %s суток | в пределах 3 SE = %s | %s |'
           % (('%.2f' % cl['dur']) if cl['dur'] == cl['dur'] else '—',
              ('%.2f' % op['dur']) if op['dur'] == op['dur'] else '—',
              ('%.2f' % (3 * 0.05 * abs(op['dur']))) if op['dur'] == op['dur'] else '—',
              vt(g['verdict']))]
    # Вывод строится по ДВУМ частям сразу: (б) одна отвечает на вопрос «ручка или нет» неверно.
    # Ручка — это то, что воспроизводится постоянным подъёмом нагрузки ЦЕЛИКОМ. Если петля ломает
    # не больше эквивалента, но при снятии нагрузки не отпускает, а эквивалент отпускает, — это
    # не ручка, а другой механизм, и путать эти два случая нельзя.
    if c.get('verdict') is True and b.get('verdict') is False:
        md.append('\n**Петля не ручка, но и не усилитель: она ИЗБИРАТЕЛЬНА и НЕОБРАТИМА.** Статический '
                  'подъём нагрузки той же величины ломает БОЛЬШЕ наборов (%.3f против %.3f) — потому что '
                  'он бьёт по всем, тогда как множитель петли высок только у тех, кто уже повреждён, а у '
                  'здоровых остаётся около единицы. Зато при снятии нагрузки эквивалент отпускает %.3f '
                  'наборов, а петля — %.3f. Это и есть содержательное отличие: петля переводит болезнь из '
                  'эпизодической в ПОСТОЯННУЮ, чего в модели не делало ничто другое. Цена названа в части '
                  '(г) и она тяжёлая: эпизодической структуры не остаётся вовсе, а у больных эпизоды есть. '
                  'Значит петля в этой силе — не модель болезни, а модель её необратимого исхода.'
                  % (eq['broken'], cl['broken'], ret0, ret1))
    elif c.get('verdict') is not True and b.get('verdict') is False:
        md.append('\n**Петля оказалась ручкой.** Доля сломанных наборов воспроизводится постоянным '
                  'подъёмом нагрузки той же величины, и при снятии нагрузки петля отпускает сломанные '
                  'наборы так же, как эквивалент. Состояние-зависимость не даёт ничего, и вводить дофамин '
                  'отдельной переменной незачем: его вклад описывается положением средней нагрузки, а это '
                  'у нас параметр набора.')
    elif b.get('verdict') is True:
        md.append('\n**Петля даёт больше, чем её статический эквивалент.** Значит работает именно '
                  'состояние-зависимость. Следующий вопрос — какая постоянная времени требуется, чтобы '
                  'это воспроизвелось, и правдоподобна ли она. Литература на этот вопрос чисел не даёт, '
                  'поэтому ответ будет предсказанием модели, а не подгонкой.')
    out = dict(grid={'%+.2f|%g' % k: v for k, v in grid.items()}, open=op, closed=cl, equiv=eq,
               mismatch=mism, a=dict(**a), b=dict(**b, excess=gap),
               c=dict(**c, released_open=ret0, released_closed=ret1, hys=hys),
               g=dict(**g))
    ctx.verdict(NAME, 'а', cl['broken'], a['verdict'], note='доля необратимо сломанных наборов, петля против разомкнутой')
    ctx.verdict(NAME, 'б', gap, b['verdict'],
                note='сверх статического эквивалента (множитель %g, нагрузки сошлись на %.0f %%)' % (eq['dq'], 100 * (1 - mism)))
    ctx.verdict(NAME, 'в', ret1, c['verdict'],
                note='гистерезис, двухфазный протокол: отпустила %.3f против %.3f у разомкнутой' % (ret1, ret0))
    ctx.verdict(NAME, 'г', cl['dur'], g['verdict'], note='цена: длительность эпизода против разомкнутой петли')
    return out, md
