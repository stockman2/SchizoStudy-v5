# -*- coding: utf-8 -*-
"""Ф27: ЕСТЬ ЛИ ОКНО, где болезнь уже хроническая, но ещё эпизодическая.

ОТКУДА ВОПРОС. Ф26 показала, что дофаминовая петля — не ручка и не усилитель, а ЗАЩЁЛКА:
разомкнутая модель при снятии нагрузки отпускает ВСЕ сломанные наборы (0,9936 -> 0,0000 ровно),
петля при силе 10 отпускает 0,24 %. Но цена оказалась тяжёлой: эпизодической структуры не остаётся
вовсе, а у больных эпизоды есть. То есть петля в той силе описывает не болезнь, а её необратимый
исход.

При этом перебор по силе в Ф26 был грубый — 0, 3, 10,— и весь переход спрятался в непросмотренном
промежутке: доля сломанных прыгает с 0,083 при нуле до 0,687 при тройке. А защёлка дозозависима:
при силе 3 петля отпускает 3,8 %, при силе 10 — всего 0,24 %. Значит ниже тройки есть сила, при
которой защёлка ещё не захлопывается полностью.

ВОПРОС, И ОН БИНАРНЫЙ. Существует ли сила петли, при которой ОДНОВРЕМЕННО:
  гистерезис УЖЕ есть  — сломанное состояние удерживается при снятии нагрузки,
  эпизоды ЕЩЁ есть     — система остаётся возвратной, эпизоды завершаются.
Это и есть клиническая картина: хроническая болезнь с обострениями. Сейчас неизвестно, достижима
она моделью или нет, и ответ ценен в обе стороны. Окно есть — впервые режим, воспроизводящий
хроничность и эпизодичность разом, и вопрос переходит к постоянной времени и её правдоподобию.
Окна нет — это ЧИСТОЕ ОПРОВЕРЖЕНИЕ петли как модели болезни: при любой силе она даёт либо
обратимые эпизоды, либо необратимое выключение, но не то и другое вместе.

ПОРОГИ, И ПОЧЕМУ ИМЕННО ПОЛОВИНА. Обе величины измерены на краях с огромным запасом: удержание
идёт от 0,000 при силе 0 до 0,998 при силе 10, эпизоды — от полной структуры до полного её
отсутствия. Половина — середина между двумя ИЗМЕРЕННЫМИ краями, а не выбранное число, и отстоит от
каждого края на сотни стандартных ошибок (при 1255 наборах SE доли около 0,014, MDE около 0,035).
Назначать более тонкий порог не нужно: вопрос качественный, а не количественный.

ПРАВИЛО Ф27, ЗАПИСАНО ДО СЧЁТА
  (г) Контроль, первым. При силе 0 удержание обязано быть нулевым: разомкнутая модель отпускает
      всё. Если нет — двухфазный протокол неисправен, и остальные части читать нельзя.
  (а) ГЛАВНАЯ. Существует ли в переборе точка, где удержание не ниже половины И доля наборов,
      ПОБЫВАВШИХ В ОБОИХ состояниях, не ниже половины от разомкнутой модели.
      Про меру эпизодичности. Считать завершённые эпизоды нельзя: при силе 0,25 длительность
      доходит до 22 суток в окне 30, и счётчик падает не потому, что система стала поглощающей, а
      потому, что эпизод не успевает кончиться — это цензурирование окном наблюдения, а не свойство
      модели (дефект найден 21.10 на пилоте, ДО прогона). Доля побывавших в обоих состояниях от
      длины окна так не зависит: застрявший набор туда не попадёт ни при каком окне.
  (б) МОНОТОННОСТЬ. Обе величины обязаны идти по силе монотонно: удержание вверх, эпизоды вниз.
      Проверяется точным перестановочным критерием. Если монотонности нет, понятие «окно»
      некорректно и мельчить перебор бессмысленно — это надо знать до того, как тратить прогон.
  (в) КРИТИЧЕСКИЕ СИЛЫ. Печатаются две: где удержание пересекает половину и где эпизоды падают
      ниже половины, обе линейной интерполяцией между соседними точками. Окно существует тогда и
      только тогда, когда первая МЕНЬШЕ второй, и их разность — ширина окна. Это количественная
      форма части (а) и одновременно прицел для следующего, более мелкого перебора.
"""
import math
import numpy as np
from .. import stats as st
from . import _blocks as B
from ._meas import meas

NAME = 'Ф27'
BROKEN = 0.9
HALF = 0.5
# Границы «побывал в обоих состояниях»: набор с долей времени в повреждённом строго между ними
# и есть эпизодический — он не застрял ни в здоровье, ни в болезни.
ALT_LO, ALT_HI = 0.05, 0.95


def needs(cfg):
    return B.da_fine(cfg)


def _cross(xs, ys, level, rising):
    """Сила, при которой кривая пересекает уровень, линейной интерполяцией между соседями.
    rising — ищем переход снизу вверх. Нет пересечения — nan."""
    for i in range(len(xs) - 1):
        y0, y1 = ys[i], ys[i + 1]
        if not (np.isfinite(y0) and np.isfinite(y1)): continue
        if (rising and y0 < level <= y1) or ((not rising) and y0 >= level > y1):
            if abs(y1 - y0) < 1e-12: return float(xs[i])
            return float(xs[i] + (xs[i + 1] - xs[i]) * (level - y0) / (y1 - y0))
    return float('nan')


def run(ctx):
    S = ctx.S; cfg = ctx.cfg; nd = cfg.d['run']['days']; band = S['band']
    aa = list(B.ADA27_ALL)
    rows = []
    for a_ in aa:
        work = ctx.b('da_m1_a%g' % a_); hys = ctx.b('da_hys_a%g' % a_)
        mm = meas(work, nd, band)
        n = int(band.sum())
        p1 = np.asarray(hys['D_ph1'], float)[band]; p2 = np.asarray(hys['D_ph2'], float)[band]
        br1 = float((p1 > BROKEN).mean()); br2 = float((p2 > BROKEN).mean())
        keep = (br2 / br1) if br1 > 1e-9 else float('nan')     # доля удержанных из сломанных
        hys2 = ctx.b('da_hys2_a%g' % a_)                       # мягкий слом: множитель 1.2 вместо 2
        q1 = np.asarray(hys2['D_ph1'], float)[band]; q2 = np.asarray(hys2['D_ph2'], float)[band]
        s1 = float((q1 > BROKEN).mean()); s2 = float((q2 > BROKEN).mean())
        keep_s = (s2 / s1) if s1 > 1e-9 else float('nan')
        Dw = np.asarray(work['Dbar'], float)[band]
        # ЭПИЗОДИЧНОСТЬ БЕЗ ЦЕНЗУРИРОВАНИЯ. Считать завершённые эпизоды нельзя: при силе петли 0,25
        # длительность доходит до 22 суток в окне 30, и счётчик падает не потому, что система стала
        # поглощающей, а потому, что эпизод не успевает кончиться. Доля наборов, побывавших В ОБОИХ
        # состояниях, от длины окна так не зависит: застрявший набор туда не попадёт никогда.
        alt = float(((Dw > ALT_LO) & (Dw < ALT_HI)).mean())
        ep_rate = float(np.asarray(work['epn'], float)[band].sum() / max(n, 1))
        rows.append(dict(a=a_, n=n, alt=alt, se_alt=st.prop_se(alt, n),
                         keep_soft=keep_s, br1_soft=s1, br2_soft=s2,
                         broken=float((Dw > BROKEN).mean()),
                         br1=br1, br2=br2, keep=keep, se_keep=st.prop_se(keep, n) if keep == keep else float('nan'),
                         ep_rate=ep_rate, dur=mm['dur'], share_ever=mm['share_ever']))
    ref = rows[0]                                              # сила 0: разомкнутая модель
    for z in rows:
        z['ep_rel'] = z['alt'] / ref['alt'] if ref['alt'] > 1e-12 else float('nan')
        z['done_rel'] = z['ep_rate'] / ref['ep_rate'] if ref['ep_rate'] > 1e-12 else float('nan')

    # ---- (г) контроль протокола ----
    se_g = st.prop_se(ref['keep'] if ref['keep'] == ref['keep'] else 0.0, ref['n'])
    g = st.adjudicate(ref['keep'] if ref['keep'] == ref['keep'] else 0.0, st.mde(se_g), se_g, 'le',
                      null=HALF, n=ref['n'])

    # ---- (а) существует ли окно ----
    win = [z for z in rows if z['keep'] == z['keep'] and z['ep_rel'] == z['ep_rel']
           and z['keep'] >= HALF and z['ep_rel'] >= HALF]
    a_v = ('непроверяемо' if g['verdict'] is not True else bool(len(win) > 0))

    # ---- (б) монотонность обеих величин ----
    ok = [z for z in rows if z['keep'] == z['keep'] and z['ep_rel'] == z['ep_rel']]
    rk, pk, nk = st.perm_rank_p([z['a'] for z in ok], [z['keep'] for z in ok], 'increase')
    re_, pe, ne = st.perm_rank_p([z['a'] for z in ok], [z['ep_rel'] for z in ok], 'decrease')
    b_v = ('непроверяемо' if not (pk == pk and pe == pe) else bool(pk <= 0.05 and pe <= 0.05))

    # ---- (в) критические силы и ширина окна ----
    xs = [z['a'] for z in ok]
    a_keep = _cross(xs, [z['keep'] for z in ok], HALF, True)    # где защёлка включается
    oks = [z for z in rows if z['keep_soft'] == z['keep_soft'] and z['ep_rel'] == z['ep_rel']]
    a_keep_s = _cross([z['a'] for z in oks], [z['keep_soft'] for z in oks], HALF, True)
    a_ep = _cross(xs, [z['ep_rel'] for z in ok], HALF, False)   # где эпизоды исчезают
    width = (a_ep - a_keep) if (a_keep == a_keep and a_ep == a_ep) else float('nan')
    c_v = ('непроверяемо' if not (width == width) else bool(width > 0))
    # ---- (д) то же на МЯГКОМ протоколе слома ----
    width_s = (a_ep - a_keep_s) if (a_keep_s == a_keep_s and a_ep == a_ep) else float('nan')
    win_s = [z for z in rows if z['keep_soft'] == z['keep_soft'] and z['ep_rel'] == z['ep_rel']
             and z['keep_soft'] >= HALF and z['ep_rel'] >= HALF]
    d_v = ('непроверяемо' if g['verdict'] is not True else bool(len(win_s) > 0))

    vt = lambda v: 'выполнено' if v is True else ('не выполнено' if v is False else str(v))
    md = ['\n## %s. Есть ли окно: хроническая болезнь с обострениями\n' % NAME,
          'Мелкий перебор силы петли между 0 и 3 — в Ф26 он был грубый (0, 3, 10), и весь переход '
          'спрятался в промежутке. Удержание — доля сломанных в первой фазе, оставшихся сломанными '
          'во второй, когда нагрузка снята. Эпизоды — число завершённых эпизодов на набор в долях '
          'от разомкнутой модели. Пороги по половине: это середина между двумя ИЗМЕРЕННЫМИ краями, '
          'и каждый край отстоит от неё на сотни стандартных ошибок.\n',
          '| сила петли | сломано | удержание | мягко | в долях от разомкнутой | завершённых | длительность |',
          '|---|---|---|---|---|---|---|---|']
    for z in rows:
        md.append('| %g%s | %.3f | %s | %s | %.3f | %s | %.3f | %s |'
                  % (z['a'], ' (разомкнуто)' if z['a'] == 0 else '', z['broken'],
                     ('%.3f' % z['keep']) if z['keep'] == z['keep'] else '—',
                     ('%.3f' % z['keep_soft']) if z['keep_soft'] == z['keep_soft'] else '—', z['alt'],
                     ('%.3f' % z['ep_rel']) if z['ep_rel'] == z['ep_rel'] else '—', z['ep_rate'],
                     ('%.2f' % z['dur']) if z['dur'] == z['dur'] else '—'))
    md += ['', '| часть | получено | ожидание до счёта | вывод |', '|---|---|---|---|',
           '| г: контроль — при силе 0 удержание нулевое | %s | не больше MDE = %.3f | %s |'
           % (('%.3f' % ref['keep']) if ref['keep'] == ref['keep'] else '—', st.mde(se_g), vt(g['verdict'])),
           '| а: ОКНО существует | точек, где удержание и эпизоды оба не ниже половины: %d%s | '
           'хотя бы одна | %s |'
           % (len(win), (' (силы %s)' % ', '.join('%g' % z['a'] for z in win)) if win else '', vt(a_v)),
           '| б: обе величины монотонны по силе | удержание ρ = %s (p = %s), эпизоды ρ = %s (p = %s) | '
           'оба p не больше 0,05 | %s |'
           % (('%+.3f' % rk) if rk == rk else '—', ('%.4f' % pk) if pk == pk else '—',
              ('%+.3f' % re_) if re_ == re_ else '—', ('%.4f' % pe) if pe == pe else '—', vt(b_v)),
           '| в: защёлка включается раньше, чем гаснут эпизоды | %s против %s, ширина окна %s | '
           'разность больше нуля | %s |'
           % (('%.2f' % a_keep) if a_keep == a_keep else 'не достигнуто',
              ('%.2f' % a_ep) if a_ep == a_ep else 'не достигнуто',
              ('%+.2f' % width) if width == width else '—', vt(c_v)),
           '| д: то же при МЯГКОМ сломе (множитель %g вместо %g) | защёлка при %s, окно %s, точек %d | '
           'хотя бы одна точка | %s |'
           % (B.NU_BREAK_SOFT, B.NU_BREAK,
              ('%.2f' % a_keep_s) if a_keep_s == a_keep_s else 'не достигнуто',
              ('%+.2f' % width_s) if width_s == width_s else '—', len(win_s), vt(d_v))]
    if a_v is True:
        md.append('\n**Окно есть, и это первый режим модели, где хроничность и эпизодичность '
                  'сосуществуют.** При силе петли в найденном промежутке сломанное состояние уже '
                  'удерживается при снятии нагрузки, но система остаётся возвратной и эпизоды '
                  'завершаются. Дальше вопрос переходит к постоянной времени: какая требуется, чтобы '
                  'окно попало в рабочую точку, и правдоподобна ли она. Напомним: количественных '
                  'значений постоянной дофаминовой петли литература не даёт вовсе, поэтому ответ '
                  'будет предсказанием модели, а не подгонкой.')
    elif a_v is False and c_v is False:
        md.append('\n**Окна нет, и это опровержение петли как модели болезни.** Защёлка включается '
                  'ПОЗЖЕ, чем гаснут эпизоды: при любой силе модель даёт либо обратимые эпизоды, либо '
                  'необратимое выключение, но не то и другое вместе. Клиническая картина — хроническое '
                  'течение с обострениями — этим механизмом не воспроизводится. Дальше искать надо не '
                  'в силе петли, а в её устройстве: например, защёлка, действующая не на нагрузку, а '
                  'на порог восстановления, оставила бы эпизодам место.')
    elif b_v is False:
        md.append('\n**Монотонности нет, и понятие окна некорректно.** Одна из двух величин идёт по '
                  'силе петли не монотонно, значит «окно» не задаётся одним промежутком, и мельчить '
                  'перебор бессмысленно до того, как будет понятно, откуда немонотонность.')
    out = dict(rows=rows, ref=ref, a=dict(verdict=a_v, n_window=len(win),
                                          window=[z['a'] for z in win]),
               b=dict(verdict=b_v, rho_keep=rk, p_keep=pk, rho_ep=re_, p_ep=pe),
               c=dict(verdict=c_v, a_keep=a_keep, a_ep=a_ep, width=width),
               d=dict(verdict=d_v, a_keep_soft=a_keep_s, width=width_s,
                      window=[z['a'] for z in win_s]), g=dict(**g))
    ctx.verdict(NAME, 'г', ref['keep'] if ref['keep'] == ref['keep'] else 0.0, g['verdict'],
                note='контроль двухфазного протокола: при силе 0 удержание обязано быть нулевым')
    ctx.verdict(NAME, 'а', float(len(win)), a_v,
                note='окно, где удержание и эпизоды оба не ниже половины; силы: %s'
                     % (', '.join('%g' % z['a'] for z in win) if win else 'нет'))
    ctx.verdict(NAME, 'б', rk, b_v, note='монотонность удержания (вверх) и эпизодов (вниз) по силе петли')
    ctx.verdict(NAME, 'в', width, c_v,
                note='защёлка при %s, эпизоды гаснут при %s'
                     % (('%.2f' % a_keep) if a_keep == a_keep else '—',
                        ('%.2f' % a_ep) if a_ep == a_ep else '—'))
    ctx.verdict(NAME, 'д', float(len(win_s)), d_v,
                note='окно при МЯГКОМ сломе (множитель %g): защёлка при %s'
                     % (B.NU_BREAK_SOFT, ('%.2f' % a_keep_s) if a_keep_s == a_keep_s else '—'))
    return out, md
