# -*- coding: utf-8 -*-
"""Ф28: ПЕТЛЯ ЧЕРЕЗ ЁМКОСТЬ ЗАЩИТЫ — действует на восстановление, а не на нагрузку.

ОТКУДА ВОПРОС. Ф26 и Ф27 закрыли нагрузочную петлю вердиктами: она делает состояние необратимым,
но убивает эпизоды при ЛЮБОЙ силе. Защёлка включается при силе 1,11, а эпизоды гаснут при 0,18 —
разрыв шестикратный, и он не краевой, а структурный. Причина: нагрузка есть величина НА НАБОР,
одна на все клетки, поэтому петля через неё двигает популяцию целиком, и набор уезжает в D = 1.

ЧТО ЗДЕСЬ ДРУГОЕ. Петля действует ПОКЛЕТОЧНО и на ёмкость: пока клетка повреждена, её N0 тянется
к N0*(1 - a_n); когда восстановилась — обратно к N0, но с ДРУГОЙ постоянной. Теряет быстро,
набирает медленно — защёлка не на нагрузке, а на восстановлении. Повреждённая клетка теряет своё,
соседняя нет, популяция остаётся разнородной, и эпизодам есть где быть.

Биологически это и есть измеренная часть: окислительное повреждение PV-клеток снижает экспрессию
самого парвальбумина, рвёт перинейрональную сеть, бьёт по митохондриям. Клетка теряет ЁМКОСТЬ, а
не получает больше нагрузки. Асимметричная релаксация у нас уже проверена на Ф23.

ГЛУБИНА СБРОСА СТОИТ ОСЬЮ ПЕРЕБОРА, А НЕ КОНСТАНТОЙ, и это главное устройство правила. На пробе
21.10 ответ про гистерезис менялся с 0,037 до 0,648 в зависимости от того, насколько глубоко
снимали нагрузку: при глубоком сбросе клетка здорова и с половинной ёмкостью, и памяти негде
проявиться. Константа дала бы ответ про режим измерения, а не про модель. Эту ошибку мы ловили
трижды за неделю, и здесь она закрыта устройством перебора.

ПРАВИЛО Ф28, ЗАПИСАНО ДО СЧЁТА
  (г) Контроль, первым. При a_n = 0 модель обязана быть прежней: ёмкость равна N0, а прибавка
      повреждения между половинами прогона неразличима. Если контроль не прошёл, остальное
      читать нельзя.
  (а) ЭПИЗОДЫ СОХРАНЯЮТСЯ — то, чего нагрузочная петля не смогла. Доля наборов, побывавших в
      обоих состояниях, не ниже половины от разомкнутой модели. Мера та же, что в Ф27, и она
      свободна от цензурирования окном наблюдения.
  (б) ЗАЩЁЛКА ЕСТЬ. При мягком сбросе удержание сломанного состояния не ниже половины, и оно
      РАСТЁТ с мягкостью сброса. Второе обязательно: если удержание не зависит от глубины сброса,
      значит оно не про память ёмкости, а про что-то ещё.
  (в) ПРОГРЕССИРОВАНИЕ. Парная внутри набора прибавка доли повреждённых между второй и первой
      половиной прогона превышает MDE при петле и НЕ превышает без неё. Парно — обязательно:
      разброс между наборами громадный и топит внутринаборный сдвиг (ошибка поймана 21.10, когда
      сравнение двух средних дало «прогрессирования нет», а парное на тех же данных дало рост
      вдвое выше MDE).
  (ж) ПРИБАВКА СВЕРХ СТАТИКИ, записано 21.10 ПОСЛЕ прогона и потому требует НЕЗАВИСИМОГО сида.
      Прибавка петли минус прибавка статики, сопоставленной по уровню повреждения в первой
      половине, превышает MDE разности. Сопоставление по уровню, а не по ёмкости: мера
      ограничена сверху, прибавка по статике немонотонна по ёмкости (горб на mu = 0.75), и
      сопоставление по ёмкости сравнивало бы разные запасы до потолка. Ошибка разности взята
      сверху (hypot), хотя наборы у плеч одни и те же и шум парный.
      Этот пункт НЕ исправляет (д) и не отменяет его вердикт: (д) спросил, даёт ли статика
      тренд вовсе, и ответ «даёт» остаётся. (ж) спрашивает другое — добавляет ли петля сверх.
  (д) ФАЛЬСИФИКАТОР. Статическое снижение ёмкости до той же средней величины НЕ воспроизводит
      прогрессирование: оно обязано остаться неразличимым, потому что постоянная величина тренда
      не создаёт по построению. Если статика воспроизводит и уровень, и тренд — петля есть ручка,
      и её надо отвергнуть.
  (е) СКОРОСТЬ ПРОГРЕССИРОВАНИЯ задаёт постоянная ВОЗВРАТА, а не глубина потери. Половина этого
      уже наблюдалась на пилоте (прибавка не менялась с глубиной: +0,0218 / +0,0214 / +0,0204),
      и эта половина здесь ПОДТВЕРЖДАЕТСЯ, а не предсказывается — помечено как в Ф18(а). Вторая
      половина, зависимость от постоянной возврата, на пилоте не проверялась вовсе и является
      предсказанием: прибавка обязана падать с ростом постоянной возврата.
"""
import math
import numpy as np
from .. import stats as st
from . import _blocks as B
from ._meas import meas

NAME = 'Ф28'
BROKEN = 0.9
ALT_LO, ALT_HI = 0.05, 0.95
HALF = 0.5


def needs(cfg):
    return B.cap_work(cfg) + B.cap_prog(cfg) + B.cap_hys(cfg) + B.cap_stat(cfg)


def _alt(rr, band):
    D = np.asarray(rr['Dbar'], float)[band]
    return float(((D > ALT_LO) & (D < ALT_HI)).mean()), float((D > BROKEN).mean())


def _lvl(rr, band):
    """Средний уровень повреждения в ПЕРВОЙ половине: по нему сопоставляются плечи в (ж).

    Сопоставлять по ёмкости нельзя: мера (вторая половина минус первая) ОГРАНИЧЕНА сверху, и
    при доле сломанных около половины ей просто некуда расти. 21.10 это видно прямо — прибавка
    по статике немонотонна по ёмкости, горб на mu = 0.75. Уровень первой половины ставит оба
    плеча в одну точку насыщающейся шкалы, и сравнение становится сравнением приростов, а не
    сравнением запасов до потолка."""
    p1 = np.asarray(rr['D_ph1'], float)[band]
    p1 = p1[np.isfinite(p1)]
    return float(p1.mean()) if len(p1) else float('nan')


def _prog(rr, band):
    """Парная прибавка доли повреждённых: вторая половина минус первая, внутри набора."""
    p1 = np.asarray(rr['D_ph1'], float)[band]; p2 = np.asarray(rr['D_ph2'], float)[band]
    d = (p2 - p1); d = d[np.isfinite(d)]
    if len(d) < 3: return float('nan'), float('nan'), 0
    return float(d.mean()), float(np.std(d, ddof=1) / math.sqrt(len(d))), len(d)


def run(ctx):
    S = ctx.S; cfg = ctx.cfg; nd = cfg.d['run']['days']; band = S['band']

    # ---- рабочая точка: эпизодичность ----
    work = []
    for a_ in B.AN28:
        rr = ctx.b('cp_w_a%g' % a_); mm = meas(rr, nd, band)
        alt, br = _alt(rr, band)
        work.append(dict(a=a_, alt=alt, broken=br, dur=mm['dur'], n=int(band.sum()),
                         cap=float(np.nanmean(np.asarray(rr['ncbar'], float)[band])),
                         se_alt=st.prop_se(alt, int(band.sum()))))
    w0 = work[0]
    for z in work: z['alt_rel'] = z['alt'] / w0['alt'] if w0['alt'] > 1e-12 else float('nan')
    wA = [z for z in work if z['a'] == 0.5][0]

    # ---- прогрессирование ----
    prog = []
    for a_ in (0.0, 0.5):
        for u in B.TUP28:
            rr = ctx.b('cp_p_a%g_u%g' % (a_, u))
            d, se, nn = _prog(rr, band)
            prog.append(dict(a=a_, tup=u, d=d, se=se, n=nn, mde=st.mde(se), lvl=_lvl(rr, band),
                             cap=float(np.nanmean(np.asarray(rr['ncbar'], float)[band]))))
    p_off = [z for z in prog if z['a'] == 0.0]
    p_on = [z for z in prog if z['a'] == 0.5]
    ref_p = p_off[len(p_off) // 2]

    # ---- гистерезис ----
    hys = []
    for a_ in (0.0, 0.5):
        for r_ in B.REL28:
            rr = ctx.b('cp_h_a%g_r%g' % (a_, r_))
            q1 = np.asarray(rr['D_ph1'], float)[band]; q2 = np.asarray(rr['D_ph2'], float)[band]
            b1 = float((q1 > BROKEN).mean()); b2 = float((q2 > BROKEN).mean())
            hys.append(dict(a=a_, rel=r_, br1=b1, br2=b2,
                            keep=(b2 / b1) if b1 > 1e-9 else float('nan'),
                            se=st.prop_se((b2 / b1) if b1 > 1e-9 else 0.0, int(band.sum()))))
    h_on = [z for z in hys if z['a'] == 0.5]; h_off = [z for z in hys if z['a'] == 0.0]

    # ---- статический эквивалент ----
    stat = []
    for mu in B.N0M28:
        rr = ctx.b('cp_s_m%g' % mu)
        d, se, nn = _prog(rr, band)
        alt, br = _alt(rr, band)
        stat.append(dict(mu=mu, d=d, se=se, n=nn, mde=st.mde(se), alt=alt, broken=br,
                         lvl=_lvl(rr, band),
                         cap=float(np.nanmean(np.asarray(rr['ncbar'], float)[band]))))

    vt = lambda v: 'выполнено' if v is True else ('не выполнено' if v is False else str(v))

    # ---- (г) контроль ----
    g_ok = bool(abs(ref_p['d']) <= ref_p['mde']) if ref_p['d'] == ref_p['d'] else 'непроверяемо'

    # ---- (а) эпизоды ----
    a_v = ('непроверяемо' if g_ok is not True else bool(wA['alt_rel'] >= HALF))

    # ---- (б) защёлка и её рост с мягкостью сброса ----
    soft = max(h_on, key=lambda z: z['rel'])
    rk, pk, nk = st.perm_rank_p([z['rel'] for z in h_on], [z['keep'] for z in h_on], 'increase')
    pkmin = 1.0 / math.factorial(nk) if nk and nk <= 8 else 0.0
    b_v = ('непроверяемо' if g_ok is not True or not (soft['keep'] == soft['keep']) or pkmin > 0.05
           else bool(soft['keep'] >= HALF and (pk <= 0.05 if pk == pk else rk > 0)))

    # ---- (в) прогрессирование ----
    on_ok = [z for z in p_on if z['d'] == z['d'] and z['d'] > z['mde']]
    off_bad = [z for z in p_off if z['d'] == z['d'] and z['d'] > z['mde']]
    c_v = ('непроверяемо' if g_ok is not True else bool(len(on_ok) == len(p_on) and not off_bad))

    # ---- (д) фальсификатор: статика не даёт тренда ----
    # СОВПАДЕНИЕ ПО ЁМКОСТИ — УСЛОВИЕ, А НЕ ПОЖЕЛАНИЕ. Фальсификатор сравнивает петлю со
    # статикой ТОЙ ЖЕ средней ёмкости; если ближайшая точка сетки до ёмкости петли не доходит,
    # сравниваются два разных режима, и ответ будет про глубину снижения, а не про петлю.
    # Допуск назначен до счёта из устройства перебора: половина наименьшего шага сетки по
    # ёмкости. Шире — и «совпадение» перестанет быть совпадением; уже — и его не достичь
    # ни на какой сетке. Не накрыли — пункт НЕПРОВЕРЯЕМ, а не «не выполнен».
    cap_on = p_on[len(p_on) // 2]['cap']
    eq = min(stat, key=lambda z: abs(z['cap'] - cap_on)) if stat else None
    caps = sorted(z['cap'] for z in stat) if stat else []
    step = min((b - a for a, b in zip(caps, caps[1:])), default=float('nan'))
    tol = 0.5 * step
    miss = (abs(eq['cap'] - cap_on) > tol) if eq is not None and tol == tol else True
    d_v = ('непроверяемо' if eq is None or not (eq['d'] == eq['d']) or miss
           else bool(abs(eq['d']) <= eq['mde']))

    # ---- (ж) ПРИБАВКА СВЕРХ СТАТИКИ: то, чего пункт (д) не умеет спросить ----
    # (д) спрашивает «даёт ли статика тренд вовсе» и отвечает «да», потому что снижение ёмкости
    # приближает популяцию к порогу и она продолжает сползать. Это не делает петлю ручкой:
    # нужный вопрос — ДОБАВЛЯЕТ ли состояние-зависимость сверх постоянного снижения. Здесь он и
    # задан, с порогом, назначенным до счёта из матожиданий и дисперсий.
    #
    # Плечи сопоставляются по УРОВНЮ ПЕРВОЙ ПОЛОВИНЫ, а не по ёмкости: мера ограничена сверху,
    # и сопоставление по ёмкости сравнивало бы разные запасы до потолка. Статика берётся линейной
    # интерполяцией между двумя точками сетки, НАКРЫВАЮЩИМИ уровень петли, а не ближайшей точкой:
    # ближайшая существует при любой сетке и потому молчит. Не накрыли — пункт непроверяем.
    #
    # Ошибка разности — hypot двух ошибок, то есть оценка СВЕРХУ: наборы у плеч одни и те же,
    # шум парный, истинная ошибка меньше. Завышать её безопасно, занижать — нельзя.
    ref_on = p_on[len(p_on) // 2]
    sl = sorted((z for z in stat if z['lvl'] == z['lvl'] and z['d'] == z['d']), key=lambda z: z['lvl'])
    lo = [z for z in sl if z['lvl'] <= ref_on['lvl']]
    hi = [z for z in sl if z['lvl'] >= ref_on['lvl']]
    if lo and hi and ref_on['d'] == ref_on['d']:
        zl, zh = lo[-1], hi[0]
        w = 0.0 if zh['lvl'] == zl['lvl'] else (ref_on['lvl'] - zl['lvl']) / (zh['lvl'] - zl['lvl'])
        d_st = zl['d'] + w * (zh['d'] - zl['d'])
        se_st = math.hypot((1 - w) * zl['se'], w * zh['se'])
        gain = ref_on['d'] - d_st
        se_g = math.hypot(ref_on['se'], se_st)
        zh_ok = True
    else:
        zl = zh = None; d_st = se_st = gain = se_g = float('nan'); zh_ok = False
    mde_g = st.mde(se_g) if se_g == se_g else float('nan')
    zh_v = ('непроверяемо' if g_ok is not True or not zh_ok or not (gain == gain)
            else bool(gain > mde_g))

    # ---- (е) чем задана скорость ----
    ds = [z['d'] for z in p_on]
    re_, pe, ne = st.perm_rank_p([z['tup'] for z in p_on], ds, 'decrease')
    # ПОРОГ ОБЯЗАН БЫТЬ ДОСТИЖИМ. У точного перестановочного критерия наименьшее односторонее
    # p равно 1/n!, поэтому при n = 3 требование p <= 0.05 нельзя выполнить ни при каком
    # поведении модели, и «не выполнено» было бы ложным обвинением модели в том, что она
    # провалила непроходимую проверку. Проверяем достижимость и честно говорим «непроверяемо».
    pmin = 1.0 / math.factorial(ne) if ne and ne <= 8 else 0.0
    e_v = ('непроверяемо' if not (pe == pe) or pmin > 0.05 else bool(pe <= 0.05))

    md = ['\n## %s. Петля через ёмкость защиты: действует на восстановление\n' % NAME,
          'Поклеточная потеря ёмкости: пока клетка повреждена, её N0 тянется к N0·(1−a), потом '
          'возвращается, но медленнее. Глубина сброса нагрузки стоит ОСЬЮ перебора, а не '
          'константой: на пробе ответ про гистерезис менялся с 0,04 до 0,65 в зависимости от неё.\n',
          '| глубина потери | ёмкость | сломано | побывали в обоих | в долях от разомкнутой | длительность |',
          '|---|---|---|---|---|---|']
    for z in work:
        md.append('| %g%s | %.4f | %.3f | %.3f | %s | %s |'
                  % (z['a'], ' (петли нет)' if z['a'] == 0 else '', z['cap'], z['broken'], z['alt'],
                     ('%.3f' % z['alt_rel']) if z['alt_rel'] == z['alt_rel'] else '—',
                     ('%.2f' % z['dur']) if z['dur'] == z['dur'] else '—'))
    md += ['', '| глубина сброса | петля | сломано ф1 | сломано ф2 | удержание |', '|---|---|---|---|---|']
    for z in hys:
        md.append('| %g | %s | %.3f | %.3f | %s |'
                  % (z['rel'], 'нет' if z['a'] == 0 else 'a = %g' % z['a'], z['br1'], z['br2'],
                     ('%.3f' % z['keep']) if z['keep'] == z['keep'] else '—'))
    md += ['', '| петля | возврат, сут | ёмкость | прибавка за половину | SE | MDE | вывод |',
           '|---|---|---|---|---|---|---|']
    for z in prog:
        md.append('| %s | %g | %.4f | %+.4f | %.4f | %.4f | %s |'
                  % ('нет' if z['a'] == 0 else 'a = %g' % z['a'], z['tup'], z['cap'], z['d'],
                     z['se'], z['mde'], 'рост' if z['d'] > z['mde'] else 'не различимо'))
    md += ['', '| статическое снижение | ёмкость | побывали в обоих | прибавка | MDE | вывод |',
           '|---|---|---|---|---|---|']
    for z in stat:
        md.append('| %g | %.4f | %.3f | %+.4f | %.4f | %s |'
                  % (z['mu'], z['cap'], z['alt'], z['d'], z['mde'],
                     'рост' if z['d'] > z['mde'] else 'не различимо'))
    md += ['', '| часть | получено | ожидание до счёта | вывод |', '|---|---|---|---|',
           '| г: контроль — при a = 0 тренда нет | %+.4f при MDE %.4f | не больше MDE | %s |'
           % (ref_p['d'], ref_p['mde'], vt(g_ok)),
           '| а: эпизоды сохраняются | %.3f от разомкнутой | не ниже половины | %s |'
           % (wA['alt_rel'], vt(a_v)),
           '| б: защёлка есть и растёт с мягкостью сброса | удержание %s при сбросе %g, ρ = %s '
           '(p = %s, точек %d, наименьшее достижимое p %.4f%s) | не ниже половины И монотонно | %s |'
           % (('%.3f' % soft['keep']) if soft['keep'] == soft['keep'] else '—', soft['rel'],
              ('%+.3f' % rk) if rk == rk else '—', ('%.4f' % pk) if pk == pk else '—',
              nk, pkmin, '; ПОРОГ НЕДОСТИЖИМ' if pkmin > 0.05 else '', vt(b_v)),
           '| в: прогрессирование есть с петлёй и нет без неё | с петлёй %d из %d точек выше MDE, '
           'без петли %d | все с петлёй и ни одной без | %s |'
           % (len(on_ok), len(p_on), len(off_bad), vt(c_v)),
           '| д: ФАЛЬСИФИКАТОР — статика тренда не даёт | %+.4f при MDE %.4f (ёмкость статики %.4f '
           'против петли %.4f, допуск совпадения %.4f%s) | не больше MDE при совпавшей ёмкости | %s |'
           % (eq['d'] if eq else float('nan'), eq['mde'] if eq else float('nan'),
              eq['cap'] if eq else float('nan'), cap_on, tol,
              '; СЕТКА НЕ НАКРЫЛА, сравнивать не с чем' if miss else '', vt(d_v)),
           '| ж: петля добавляет сверх статики | %+.4f при SE %.4f и MDE %.4f (петля %+.4f против '
           'статики %+.4f, сопоставление по уровню первой половины %.4f%s) | больше MDE | %s |'
           % (gain, se_g, mde_g, ref_on['d'], d_st, ref_on['lvl'],
              '' if zh_ok else '; СЕТКА НЕ НАКРЫЛА уровень петли', vt(zh_v)),
           '| е: скорость задаёт возврат, не глубина | ρ по возврату %s (p = %s, точек %d, '
           'наименьшее достижимое p %.4f%s) | падает с ростом возврата, p не больше 0,05 | %s |'
           % (('%+.3f' % re_) if re_ == re_ else '—', ('%.4f' % pe) if pe == pe else '—',
              ne, pmin, '; ПОРОГ НЕДОСТИЖИМ' if pmin > 0.05 else '', vt(e_v))]
    if a_v is True and b_v is True and c_v is True and d_v is True:
        md.append('\n**Петля через ёмкость даёт всё, чего не дала нагрузочная.** Эпизоды сохраняются, '
                  'защёлка есть и зависит от глубины сброса как должна, прогрессирование измеримо, и '
                  'статическое снижение ёмкости его не воспроизводит. Это первый режим модели, где '
                  'хроническое течение и обострения сосуществуют, и где состояние ухудшается со '
                  'временем само. Дальше вопрос переходит к постоянным: какие нужны, чтобы это '
                  'попало в клинические масштабы, и правдоподобны ли они.')
    elif d_v is False:
        # ТЕКСТ ОБЯЗАН ГОВОРИТЬ РОВНО ТО, ЧТО В ЧИСЛАХ. Прежняя формулировка утверждала, что
        # статика «воспроизводит и уровень, и тренд». Уровень она воспроизводит ПО ПОСТРОЕНИЮ —
        # мы его подогнали допуском совпадения, — а про тренд надо смотреть на долю, а не на
        # «различимо ли». 21.10 статика дала 31 % тренда петли, и вывод «петля есть ручка» из
        # этого не следует. Непройденный пункт (д) значит, что тренд НЕ ИСКЛЮЧИТЕЛЬНО признак
        # петли; он не значит, что петля ничего не добавляет. Разницу мерит отдельная часть (ж).
        _sh = (eq['d'] / p_on[len(p_on) // 2]['d']) if p_on[len(p_on) // 2]['d'] else float('nan')
        _df = p_on[len(p_on) // 2]['d'] - eq['d']
        _sd = math.hypot(p_on[len(p_on) // 2]['se'], eq['se'])
        md.append('\n**Тренд не исключительно признак петли.** Статическое снижение ёмкости до той '
                  'же средней величины тоже даёт прибавку: %+.4f при MDE %.4f, то есть %.0f %% '
                  'тренда петли (%+.4f). Сверх статики петля добавляет %+.4f при SE %.4f и MDE '
                  '%.4f — %s. Уровень ёмкости статика воспроизводит по построению, он подогнан '
                  'допуском совпадения, и его совпадение выводом не является.'
                  % (eq['d'], eq['mde'], 100 * _sh, p_on[len(p_on) // 2]['d'], _df, _sd,
                     2.4865 * _sd, 'различимо' if _df > 2.4865 * _sd else 'не различимо'))
    out = dict(work=work, prog=prog, hys=hys, stat=stat, equiv=eq,
               cap_on=cap_on, cap_tol=tol, cap_miss=bool(miss),
               a=dict(verdict=a_v, alt_rel=wA['alt_rel']),
               b=dict(verdict=b_v, keep_soft=soft['keep'], rho=rk, p=pk),
               c=dict(verdict=c_v, n_on=len(on_ok), n_off=len(off_bad)),
               d=dict(verdict=d_v),
               zh=dict(verdict=zh_v, gain=gain, se=se_g, mde=mde_g, d_loop=ref_on['d'],
                       d_stat=d_st, lvl=ref_on['lvl'], bracketed=bool(zh_ok)),
               e=dict(verdict=e_v, rho=re_, p=pe), g=dict(verdict=g_ok))
    ctx.verdict(NAME, 'г', ref_p['d'], g_ok, note='контроль: при a = 0 прибавка между половинами неразличима')
    ctx.verdict(NAME, 'ж', gain, zh_v,
                note='прибавка петли сверх статики, сопоставленной по уровню первой половины')
    ctx.verdict(NAME, 'а', wA['alt_rel'], a_v, note='эпизодичность в долях от разомкнутой модели')
    ctx.verdict(NAME, 'б', soft['keep'], b_v, note='удержание при мягком сбросе и его рост с мягкостью')
    ctx.verdict(NAME, 'в', float(len(on_ok)), c_v, note='прогрессирование: парно внутри набора')
    ctx.verdict(NAME, 'д', eq['d'] if eq else float('nan'), d_v,
                note='статический эквивалент ёмкости тренда не даёт')
    ctx.verdict(NAME, 'е', re_, e_v,
                note='скорость задаёт постоянная возврата; независимость от глубины — ПОДТВЕРЖДЕНИЕ пилота')
    return out, md
