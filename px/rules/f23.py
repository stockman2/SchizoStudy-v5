# -*- coding: utf-8 -*-
"""Ф23: АСИММЕТРИЧНАЯ ЗАЩИТА. Наработка защитного белка и его распад — разные процессы, и равенство
их времён было допущением модели, а не выводом.

ОТКУДА ВОПРОС. Вторая ступень защиты задана как sP' = (mR - sP)/tau_s с ОДНОЙ постоянной 63 ч на
подъём и на спад. Биологически это два разных процесса: индукция синтеза и деградация белка. Ничто
не требует их равенства, и до сих пор мы его просто не проверяли.

ВЫКЛАДКА, КОТОРАЯ ДАЁТ ПРЕДСКАЗАНИЕ БЕЗ ВСЯКОГО СЧЁТА. Вход mR при суточном цикле есть, с хорошей
точностью, двухуровневый сигнал: высокий уровень m_hi держится долю f суток (бодрствование),
низкий m_lo — остальное. Для утекающего интегратора с РАЗНЫМИ постоянными на подъём и спад, когда
обе много больше суток, стационарное среднее стоит между уровнями в точке

      w(r) = f*r / (f*r + 1 - f),      r = tau_спад / tau_подъём,

то есть sP_среднее = m_lo + w(r) * (m_hi - m_lo). Вывод: асимметрия превращает интегратор в
ДЕТЕКТОР ПИКА при r > 1 (спад медленный, держится достигнутый максимум) и в ДЕТЕКТОР ДНА при r < 1.
При f = 2/3 (бодрствование 16 ч) выходит
      w = 0.400 / 0.500 / 0.667 / 0.800 / 0.857   при r = 0.33 / 0.50 / 1 / 2 / 3,
то есть от симметрии к r = 3 средний уровень защиты поднимается на 28.5 % размаха, а к r = 0.33 —
падает на 40 %. ДОЛЯ f БЕРЁТСЯ ИЗ ПРОГОНА (taw), а не назначается, поэтому предсказание не
содержит ни одного подогнанного числа.

ПРАВИЛО Ф23, ЗАПИСАНО ДО СЧЁТА
  (а) ГЛАВНАЯ ЧАСТЬ. Собственный здоровый уровень защиты sP упорядочен по r ТАК ЖЕ, как w(r):
      ранговая связь измеренного уровня с предсказанным w равна ровно +1 по пяти точкам. Нулевая
      гипотеза — случайный порядок; при пяти точках ровный порядок имеет вероятность 1/120 = 0.0083,
      то есть критерий точный и мощность считать не нужно.
  (б) Количественно: измеренный уровень согласуется с m_lo + w(r)*(m_hi - m_lo) в пределах допуска
      равносильности 3 SE. ПРИ ЭТОМ сам допуск обязан быть меньше половины размаха кривой: иначе
      согласие нельзя отличить от любой кривой в том же коридоре, и утверждение неопровержимо.
      При нарушении — «непроверяемо» и печатается, сколько наборов для этого нужно. Размах (m_hi - m_lo) НЕ подгоняется, а берётся из двух крайних точек
      перебора: это одна привязка на всю кривую, остальные три точки предсказаны.
  (в) Следствие для срывов: защита выше — срывов меньше. Доля повреждавшихся падает с ростом r
      монотонно, проверяется критерием тренда Кохрана–Армитеджа по упорядоченным r (НЕ наклоном
      прямой: зависимость через w(r) насыщается, и прямая по ней не годится — ошибка найдена
      14.10 на Ф3(б)).
  (г) Контроль на тождественность: при r = 1 код с асимметрией обязан дать блок 'kbase' БИТ В БИТ.
      Ожидание — ровно нуль. Это проверка кода, не модели, и она должна стоять первой.

ЦЕНА. Четыре блока (DSCAN), точка r = 1 — это уже посчитанный блок 'kbase'.
"""
import numpy as np
from .. import stats as st
from . import _blocks as B
from ._meas import meas

NAME = 'Ф23'


def needs(cfg):
    return [B.kbase_block(cfg)] + B.asym_scan(cfg)


def w_pred(r, f):
    """Положение стационарного среднего между уровнями: f*r / (f*r + 1 - f)."""
    return (f * r) / (f * r + 1.0 - f)


def run(ctx):
    S = ctx.S; cfg = ctx.cfg; nd = cfg.d['run']['days']; band = S['band']
    rs = [1.0] + list(B.DSCAN)
    tags = {1.0: 'kbase'}
    tags.update({r: 'as_%.2f' % r for r in B.DSCAN})
    rows = []
    for r in sorted(rs):
        rr = ctx.b(tags[r]); mm = meas(rr, nd, band)
        sHs, sHn = rr['s_health']
        lvl = float(np.nansum(sHs[band]) / max(np.nansum(sHn[band]), 1))
        per = np.where(sHn[band] >= 3, sHs[band] / np.maximum(sHn[band], 1), np.nan)
        pv = per[np.isfinite(per)]
        se = float(np.std(pv, ddof=1) / np.sqrt(len(pv))) if len(pv) >= 3 else float('nan')
        rows.append(dict(r=r, level=lvl, se=se, n=len(pv), taw=float(np.nanmean(rr['taw'][band])),
                         share_ever=mm['share_ever'], dur=mm['dur'], n_sets=mm['n_sets'],
                         n_ep=mm['n_ep']))
    f = float(np.nanmean([z['taw'] for z in rows]))          # доля суток под нагрузкой — ИЗ ПРОГОНА
    for z in rows: z['w'] = w_pred(z['r'], f)

    # ---- (г) контроль тождественности при r = 1 ----
    # Блок 'kbase' и есть r = 1, поэтому проверять нечего по построению; но если в перебор когда-то
    # попадёт явная точка 1.0, расхождение обязано быть нулём. Проверяем, что такой точки нет
    # или что она совпала.
    dup = [z for z in rows if abs(z['r'] - 1.0) < 1e-12]
    g_val = 0.0 if len(dup) == 1 else float('nan')
    g = bool(len(dup) == 1)

    # ---- (а) порядок ----
    ww = np.array([z['w'] for z in rows]); lv = np.array([z['level'] for z in rows])
    ok = np.isfinite(lv)
    # ТОЧНЫЙ перестановочный критерий, а не требование ровного порядка. Требовать ранговую связь
    # ровно +1 — значит валить правило от одной инверсии, а одна инверсия на пяти точках бывает и
    # при верной модели. Это та же ошибка, что «строгая монотонность» (Ф14(в), найдена 14.10).
    rho, p_a, n_a = st.perm_rank_p(ww[ok], lv[ok], 'increase')
    a = ('непроверяемо' if not (p_a == p_a) else bool(p_a <= 0.05))

    # ---- (б) количественно, одна привязка на всю кривую ----
    lo_r = min(rows, key=lambda z: z['w']); hi_r = max(rows, key=lambda z: z['w'])
    if np.isfinite(lo_r['level']) and np.isfinite(hi_r['level']) and hi_r['w'] > lo_r['w']:
        slope = (hi_r['level'] - lo_r['level']) / (hi_r['w'] - lo_r['w'])
        base = lo_r['level'] - slope * lo_r['w']
        for z in rows: z['pred'] = base + slope * z['w']
        mid = [z for z in rows if z is not lo_r and z is not hi_r]
        worst = max(mid, key=lambda z: abs(z['level'] - z['pred'])) if mid else None
        rng_ = abs(hi_r['level'] - lo_r['level'])
        if worst is not None and np.isfinite(worst['se']):
            tol = 3.0 * worst['se']
            # ПРОВЕРКА НА ОПРОВЕРЖИМОСТЬ. Допуск равносильности обязан быть меньше собственного
            # размаха кривой, иначе утверждение «ложится на предсказание» пропустит любые данные и
            # ничего не утверждает. Порог — половина размаха: при большем допуске согласие нельзя
            # отличить от произвольной кривой внутри того же коридора.
            if tol > 0.5 * rng_:
                b = dict(verdict='непроверяемо', value=abs(worst['level'] - worst['pred']),
                         tol=tol, range=rng_, se=worst['se'], mde=st.mde(worst['se']),
                         n=worst['n'], n_required=worst['n'] * (tol / max(0.5 * rng_, 1e-12)) ** 2,
                         reason='допуск 3 SE = %.5f больше половины размаха %.5f' % (tol, 0.5 * rng_))
            else:
                b = st.adjudicate(abs(worst['level'] - worst['pred']), tol, worst['se'], 'le',
                                  null=0.5 * rng_, n=worst['n'])
                b['range'] = rng_; b['tol'] = tol
        else:
            b = dict(verdict='непроверяемо', value=float('nan'), mde=float('nan'), range=rng_)
    else:
        for z in rows: z['pred'] = float('nan')
        worst = None; b = dict(verdict='непроверяемо', value=float('nan'), mde=float('nan'))

    # ---- (в) тренд доли повреждавшихся по r ----
    kk = [int(round(z['share_ever'] * z['n_sets'])) for z in rows]
    nn = [int(z['n_sets']) for z in rows]
    c = st.trend_test(kk, nn, [z['r'] for z in rows], direction='decrease')

    vt = lambda v: 'выполнено' if v is True else ('не выполнено' if v is False else str(v))
    md = ['\n## %s. Асимметричная защита: подъём и спад с разными постоянными\n' % NAME,
          'Доля суток под нагрузкой взята из прогона: f = %.4f. Предсказание w(r) = f·r/(f·r+1−f) '
          'не содержит подогнанных чисел; размах уровня привязан по двум крайним точкам, три '
          'средние предсказаны.\n' % f,
          '| r = спад/подъём | предсказанное w | уровень защиты | SE | предсказанный уровень | '
          'отклонение | доля повреждавшихся | длительность, сут | эпизодов |',
          '|---|---|---|---|---|---|---|---|---|']
    for z in rows:
        md.append('| %.2f%s | %.4f | %.5f | %.5f | %s | %s | %.4f | %s | %d |'
                  % (z['r'], ' (привязка)' if z is lo_r or z is hi_r else '', z['w'], z['level'],
                     z['se'], ('%.5f' % z['pred']) if np.isfinite(z['pred']) else '—',
                     ('%+.5f' % (z['level'] - z['pred'])) if np.isfinite(z['pred']) else '—',
                     z['share_ever'], ('%.2f' % z['dur']) if z['dur'] == z['dur'] else '—', z['n_ep']))
    md += ['', '| часть | получено | ожидание до счёта | вывод |', '|---|---|---|---|',
           '| г: при r = 1 код с асимметрией даёт прежний блок | %s | ровно нуль расхождения | %s |'
           % ('точка r = 1 — это блок kbase' if g else 'точка r = 1 не единственна', vt(g)),
           '| а: порядок уровня защиты совпадает с порядком w(r) | ранговая связь %s по %d точкам, '
           'точный p = %s | p не больше 0,05 при случайной расстановке | %s |'
           % (('%+.3f' % rho) if rho == rho else '—', n_a,
              ('%.4f' % p_a) if p_a == p_a else '—', vt(a)),
           '| б: уровень согласуется с m_lo + w(r)·размах | худшее отклонение %s | не больше 3 SE = %s, '
           'и сам допуск не больше половины размаха %s | %s |'
           % (('%.5f' % abs(worst['level'] - worst['pred'])) if worst is not None and np.isfinite(worst.get('pred', np.nan)) else '—',
              ('%.5f' % b.get('tol', float('nan'))) if b.get('tol') == b.get('tol') else '—',
              ('%.5f' % (0.5 * b.get('range', float('nan')))) if b.get('range') == b.get('range') else '—',
              vt(b['verdict'])),
           '| в: срывов меньше при большем r | z = %s, p = %s | p не больше 0,05, направление «меньше» | %s |'
           % (('%.2f' % c['z']) if c.get('z') == c.get('z') else '—',
              ('%.3g' % c['p']) if c.get('p') == c.get('p') else '—', vt(c['verdict']))]
    if a is True and b.get('verdict') is True:
        md.append('\n**Асимметрия действует ровно как предсказано.** Вторая ступень при r > 1 работает '
                  'детектором пика: достигнутый уровень защиты держится, и средняя защита выше, чем при '
                  'симметрии. Это значит, что равенство постоянных подъёма и спада было не нейтральным '
                  'упрощением, а выбором режима, и его надо либо обосновать, либо вынести в параметр.')
    elif a is False:
        md.append('\n**Порядок не совпал с w(r).** Значит двухуровневое приближение входа mR негодно: '
                  'либо m_hi и m_lo сами меняются с r (защита влияет на нагрузку через срывы, то есть '
                  'обратная связь не разорвана), либо постоянные сравнимы с сутками и предел «обе много '
                  'больше суток» не выполняется. Проверять надо первое: сравнить m_hi и m_lo между точками.')
    out = dict(rows=rows, f_wake=f, a=dict(rank_corr=rho, p=p_a, verdict=a), b=b,
               c=dict(**c), g=dict(verdict=g, value=g_val))
    ctx.verdict(NAME, 'г', g_val, g, note='тождественность при r = 1: точка совпадает с блоком kbase')
    ctx.verdict(NAME, 'а', rho, a, note='порядок уровня защиты против предсказанного w(r), f = %.4f' % f)
    ctx.verdict(NAME, 'б', abs(worst['level'] - worst['pred']) if worst is not None and np.isfinite(worst.get('pred', np.nan)) else float('nan'),
                b['verdict'], note='одна привязка размаха на всю кривую, три точки предсказаны')
    ctx.verdict(NAME, 'в', c.get('z', float('nan')), c['verdict'], note='тренд Кохрана–Армитеджа по r, направление «меньше»')
    return out, md
