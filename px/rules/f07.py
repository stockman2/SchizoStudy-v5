# -*- coding: utf-8 -*-
"""Ф7: длина эпизода, и через что вести связь со сном.

КАК ЗАПИСАНО
  (а) средняя длительность эпизода при k = 0 не больше 2 суток;  (б) доля эпизодов короче суток
  не меньше 0,30. По наблюдениям эпизод длится от часов до нескольких суток; в прогоне при q = 0,5
  выходило 4,6 суток при k = 0, а эпизодов короче суток не было вовсе.

ВЫКЛАДКИ ДЛЯ ДВОЙНИКОВ
  (а′) Двойка суток — КЛИНИЧЕСКАЯ цель, а не ожидание модели. Ожидание модели теперь известно
       измеренным законом Ф16: длительность АФФИННА по памяти защиты, dur = 1,63 + 0,73*tau_защиты
       (сутки; RMS подгонки 0,22 сут на пяти точках перебора). При рабочей памяти это даёт
       предсказание, которое печатается рядом. Двойник проверяет ДВА разных утверждения:
         а′-1  согласуется ли наблюдение с законом Ф16 (попадает в 2 SE предсказания);
         а′-2  превышает ли оно клиническую цель 2 суток больше чем на MDE.
       Если выполнены оба, то вывод записан заранее: пассивная защита не доводит эпизод до двух
       суток НИГДЕ внутри измеренного диапазона памяти, и дорога на этом кончается — дальше только
       примирование (Ф19).
  (б′) Доля коротких считается МЕДИАНОЙ ПО НАБОРАМ и структурно обнуляется, едва короткие эпизоды
       есть меньше чем у половины наборов (найдено 14.10 по замечанию пользователя: «доля
       повреждённых всегда 0,00»). Двойник считает долю по ВСЕМ эпизодам с биномиальной SE.
  (в′) НОВАЯ часть, записана до счёта. Два блока отличаются только тем, через что идёт связь:
       через среднее повреждение или через долю повреждённых. Доля равна нулю ровно до тех пор,
       пока первая клетка не перешагнёт порог, поэтому у ПОДПОРОГОВОГО повреждения через неё нет
       пути к сну вовсе. Отсюда направление, заданное заранее: через долю эпизод должен выходить
       НЕ КОРОЧЕ (direction = increase), и сравнение парное по наборам.
"""
import numpy as np
from .. import predict as P
from .. import stats as st
from . import _blocks as B
from ._meas import meas

NAME = 'Ф7'
TARGET = 2.0            # клиническая цель, сутки


def needs(cfg): return [B.base_block(cfg), B.kbase_block(cfg), B.frac_block(cfg)]


def run(ctx):
    S = ctx.S; cfg = ctx.cfg; nd = cfg.d['run']['days']; band = S['band']
    m0 = meas(ctx.b('base'), nd, band); mB = meas(ctx.b('kbase'), nd, band); mD = meas(ctx.b('frac'), nd, band)
    se = st.boot_se(m0['dur_arr'][np.isfinite(m0['dur_arr'])]) * max(m0['dur'], 1e-9)   # абсолютная SE медианы
    a = st.adjudicate(m0['dur'], TARGET, se, 'le', n=m0['n_ep_sets'])
    pred = P.episode_dur_affine(cfg.d['model']['taus'])
    # Закон Ф16 мерился на подвыборке «полоса И кратность индукции >= 2», поэтому сверять его надо
    # на НЕЙ ЖЕ: иначе сравниваются два разных числа. Записанное правило при этом остаётся на всей
    # полосе, как было записано.
    sub = band & (S['bfac'] >= 2.0)
    msub = meas(ctx.b('base'), nd, sub)
    dsub = msub['dur_arr'][np.isfinite(msub['dur_arr'])]
    se_sub = st.boot_se(dsub) * max(msub['dur'], 1e-9)
    a1 = st.adjudicate(abs(msub['dur'] - pred), st.eq_tol(se_sub), se_sub, 'le', null=0.0, n=msub['n_ep_sets'])
    # Проверяемость решается расстоянием между клинической целью и предсказанием закона Ф16:
    # если их не отличить при нашем шуме, то и говорить, что цель не достигнута, нельзя.
    a2 = st.adjudicate(msub['dur'], TARGET, se_sub, 'ge', null=pred, n=msub['n_ep_sets'])
    sep = st.prop_se(m0['short_pool'], m0['n_ep'])
    b = st.adjudicate(m0['short'], 0.30, st.prop_se(m0['short'], m0['n_ep']), 'ge', n=int(m0['n_ep']))
    bp = st.adjudicate(m0['short_pool'], 0.30, sep, 'ge', null=0.0, n=int(m0['n_ep']))
    dB = mB['dur_arr']; dD = mD['dur_arr']
    sg = st.sign_adjudicate(st.sign_test(dB, dD, np.isfinite(dB) & np.isfinite(dD), 'increase'))

    vt = lambda v: 'выполнено' if v is True else ('не выполнено' if v is False else str(v))
    md = ['\n## %s. Длина эпизода\n' % NAME,
          'Блок %s (k = 0): связь со сном выключена, чтобы она не удлиняла эпизод сама. Закон Ф16 '
          'предсказывает при рабочей памяти %.0f ч длительность %.2f суток.\n'
          % (ctx.key('base'), cfg.d['model']['taus'] * 24, pred),
          '\n| часть | получено | порог | нулевое значение | SE | MDE | вывод |\n|---|---|---|---|---|---|---|',
          '| а: длительность (как записано) | %.2f сут на %d наборах с эпизодами | не больше 2 сут | 2 сут | %.3f | %.3f | %s |'
          % (m0['dur'], m0['n_ep_sets'], se, a['mde'], vt(a['verdict'])),
          '| а′-1: согласие с законом Ф16 на ЕГО подвыборке | %.2f сут на %d наборах (кратность ≥ 2), промах %.2f при предсказании %.2f | не больше %.2f (3 SE) | 0 | %.3f | %.3f | %s |'
          % (msub['dur'], msub['n_ep_sets'], abs(msub['dur'] - pred), pred, st.eq_tol(se_sub),
             se_sub, a1['mde'], vt(a1['verdict'])),
          '| а′-2: превышает ли клиническую цель | %.2f сут | не меньше %.2f | %.2f (предсказание Ф16) | %.3f | %.3f | %s |'
          % (msub['dur'], TARGET, pred, se_sub, a2['mde'], vt(a2['verdict'])),
          '| б: коротких эпизодов (как записано, медиана по наборам) | %.3f | не меньше 0,30 | 0,30 | %.3f | %.3f | %s |'
          % (m0['short'], st.prop_se(m0['short'], m0['n_ep']), b['mde'], vt(b['verdict'])),
          '| б′: то же по ВСЕМ эпизодам | %.3f на %d эпизодах; самый короткий %s сут | не меньше 0,30 | 0 | %.4f | %.4f | %s |'
          % (m0['short_pool'], int(m0['n_ep']), ('%.2f' % m0['ep_min']) if m0['ep_min'] == m0['ep_min'] else '—',
             sep, bp['mde'], vt(bp['verdict'])),
          '| в′: через долю повреждённых эпизод не короче | %d из %d наборов длиннее, p = %s | p не больше 0,05 | 1/2 | — | мощность %.2f | %s |'
          % (sg['k'], sg['n'], ('%.3f' % sg['p']) if sg['p'] == sg['p'] else '—', sg['power'], vt(sg['verdict'])),
          '\n### Через что вести связь: среднее повреждение или доля повреждённых (k = %.1f, одно зерно)\n' % B.KB(cfg),
          '| связь идёт через | длительность, сут | коротких по всем | доля повреждавшихся | застряли >1,5 сут | среднее повреждение | доля повреждённых |\n|---|---|---|---|---|---|---|',
          '| среднее повреждение (блок %s) | %.2f | %.3f | %.3f | %.3f | %.4f | %.4f |'
          % (ctx.key('kbase'), mB['dur'], mB['short_pool'], mB['share_ever'], mB['stuck15'], mB['Dmbar'], mB['Dbar']),
          '| долю повреждённых (блок %s) | %.2f | %.3f | %.3f | %.3f | %.4f | %.4f |'
          % (ctx.key('frac'), mD['dur'], mD['short_pool'], mD['share_ever'], mD['stuck15'], mD['Dmbar'], mD['Dbar'])]
    if a1['verdict'] is True and a2['verdict'] is True:
        md.append('\n**Вывод, записанный заранее, включается.** Длительность согласуется с аффинным законом '
                  'Ф16 и превышает клиническую цель достоверно. Аффинный закон не насыщается, поэтому внутри '
                  'измеренного диапазона памяти защиты (24–88 ч) двух суток не достичь НИГДЕ: чтобы получить '
                  '2 суток, нужна память %.1f ч, то есть отрицательная добавка к ней. Пассивная защита '
                  'исчерпана, и дальше работает только примирование.' % (24 * (TARGET - 1.63) / 0.73))
    out = dict(a=a, a_affine=dict(pred=pred, dur_sub=msub['dur'], n_sub=msub['n_ep_sets'], **a1),
               a_target=a2, b=b, b_pool=bp, coupling_paired=sg, dur_k0=m0['dur'], se_dur=se,
               coupling=dict(mean_damage={k: v for k, v in mB.items() if k != 'dur_arr'},
                             fraction={k: v for k, v in mD.items() if k != 'dur_arr'}))
    ctx.verdict(NAME, 'а', m0['dur'], a['verdict'], note='клиническая цель 2 суток, не ожидание модели')
    ctx.verdict(NAME, 'а′-1', abs(m0['dur'] - pred), a1['verdict'], note='согласие с аффинным законом Ф16 (%.2f сут)' % pred)
    ctx.verdict(NAME, 'а′-2', m0['dur'], a2['verdict'], note='превышение клинической цели')
    ctx.verdict(NAME, 'б', m0['short'], b['verdict'], note='медиана по наборам: статистика вырождена')
    ctx.verdict(NAME, 'б′', m0['short_pool'], bp['verdict'], note='доля по всем эпизодам')
    ctx.verdict(NAME, 'в′', float(sg['k']), sg['verdict'], note='парно: связь через долю против среднего, increase')
    return out, md
