# -*- coding: utf-8 -*-
"""Ф3: сон как следствие повреждения. Перебор связи k.

ЧТО ПЕРЕНЕСЕНО КАК ЗАПИСАНО
  (а) средняя длительность эпизода при k = k_база не меньше чем в 1,5 раза больше, чем при k = 0
      (парно, одно зерно);  (б) доля наборов с бодрствованием дольше двух суток больше нуля и
      растёт с k;  (в) доля эпизодов короче суток ниже 0,50.

ВЫКЛАДКИ ДЛЯ ДВОЙНИКОВ
  (а″) ПАРНОСТЬ НЕ НА ТОМ УРОВНЕ, исправлено 16.10. Отношение длительностей считалось по сидам:
       медиана трёх (потом шести) чисел, и её ошибка меряется по РАЗБРОСУ МЕЖДУ СИДАМИ. При шести
       сидах SE вышла 0,030, MDE 0,073, а предсказание переключателя отстоит от нуля всего на
       0,037 — непроверяемо. Добавление сидов не помогло и помочь не могло: разброс между сидами
       никуда не девается, а при трёх точках сама оценка SE имеет две степени свободы и ненадёжна
       (по ней выходило, что хватит четырёх сидов, — не хватило и шести).
       Правильный уровень парности — НАБОР, а не сид: блоки k = 0 и k = k_база считаются на ОДНИХ
       И ТЕХ ЖЕ наборах с одним потоком шума, поэтому отношение длительностей берётся у каждого
       набора по отдельности, а медиана и её ошибка — по сотням наборов, а не по шести сидам.
  (а′) Отношение 1,5 было взято из прежней модели (там выходило 1,67), а не выведено. Вывести его
       можно: повреждение входит в приток к сонному ядру ровно как -k*D, поэтому длину
       бодрствования при постоянном k*D даёт сам переключатель, без всякого счёта клеток.
       Если эпизод живёт, пока нагрузка держится выше верха окна, а бодрствование — это и есть
       время, когда нагрузка поднята, то длительность эпизода растёт в том же отношении, что и
       бодрствование: отношение = w(k*D_эп)/w(0). Это и есть порог двойника, и он ЖЁСТЧЕ, чем
       записанный, если переключатель даёт больше 1,5, и мягче, если меньше — во втором случае
       записанное правило требовало от механизма невозможного, и это надо сказать прямо.
  (б′) Доля «застрявших» — доля наборов, у которых хоть раз было бодрствование дольше двух суток.
       Лестница пропуска ночей посчитана в разделе 0 заранее: при k около 7,5 мВ пропускается
       ночь. Но k входит в ядро через k*D, то есть эффективное торможение равно k*D_эп, и при
       D_эп около 0,5 лестница сдвигается вдвое: порог пропуска ждём около k = 15 мВ, то есть
       ВНЕ перебора. Значит монотонность роста — всё, что здесь вообще проверяемо, и двойник
       проверяет её знаковым критерием по парам соседних k, а не на глаз.
  (в′) Доля эпизодов короче суток считается МЕДИАНОЙ ПО НАБОРАМ, а эта статистика структурно
       обнуляется, едва короткие эпизоды есть меньше чем у половины наборов (найдено 14.10).
       Двойник считает долю по ВСЕМ эпизодам и даёт ей биномиальную SE по числу эпизодов.
"""
import numpy as np
from .. import predict as P
from .. import stats as st
from . import _blocks as B
from ._meas import meas

NAME = 'Ф3'


def needs(cfg): return B.kscan(cfg) + B.seed_pairs(cfg)


def run(ctx):
    S = ctx.S; cfg = ctx.cfg; nd = cfg.d['run']['days']; band = S['band']; kb = B.KB(cfg)
    rows = [dict(k=ks, **{k_: v for k_, v in meas(ctx.b(B.tag_k(ks)), nd, band).items() if k_ != 'dur_arr'})
            for ks in B.KSCAN]
    m0 = [z for z in rows if z['k'] == 0.0][0]; mB = [z for z in rows if abs(z['k'] - kb) < 1e-9][0]
    sd0 = int(cfg.d['run']['seed'])
    pairs = [dict(seed=sd0, dur0=m0['dur'], durb=mB['dur'], ratio=mB['dur'] / max(m0['dur'], 1e-9))]
    for i in range(1, int(cfg.d['run'].get('nseed', B.NSEED3))):
        sd = sd0 + 1000 * i
        d0 = meas(ctx.b('sd_%d_0' % sd), nd, band)['dur']; db = meas(ctx.b('sd_%d_b' % sd), nd, band)['dur']
        pairs.append(dict(seed=sd, dur0=d0, durb=db, ratio=db / d0 if d0 > 0 else float('nan')))
    rts = np.array([p_['ratio'] for p_ in pairs], float); rmed = float(np.nanmedian(rts))
    nr = int(np.isfinite(rts).sum())
    se_r = float(np.nanstd(rts, ddof=1) / np.sqrt(nr)) if nr >= 2 else float('nan')

    # ---- (а) и (а′) ----
    a = st.adjudicate(rmed, 1.5, se_r, 'ge', null=1.0, n=nr)
    dep = float(mB['Dmbar']) if cfg.d['model']['usedm'] else float(mB['Dbar'])
    bg = P.bout_gain(kb, 0.0, max(dep, 1e-6))
    ap = st.adjudicate(rmed, bg['ratio'], se_r, 'ge', null=1.0, n=nr)

    # ---- (а″) парно по наборам ----
    d0 = meas(ctx.b(B.tag_k(0.0)), nd, band)['dur_arr']
    db = meas(ctx.b(B.tag_k(kb)), nd, band)['dur_arr']
    okp = np.isfinite(d0) & np.isfinite(db) & (d0 > 0)
    rat = db[okp] / d0[okp]
    rmed_s = float(np.median(rat)) if len(rat) >= 5 else float('nan')
    se_s = float(st.boot_se(rat) * abs(rmed_s)) if len(rat) >= 5 else float('nan')
    # ДВА РАЗНЫХ ВОПРОСА, и их нельзя мерить одной частью (разобрано 16.10 по прогону):
    #  1) ЕСТЬ ЛИ УСИЛЕНИЕ: наблюдение выше того, что даёт переключатель? Нулевое значение здесь —
    #     само предсказание переключателя, и зазор равен |набл. − предсказание| = велик.
    #  2) РАЗЛИЧИМ ЛИ ВКЛАД ПЕРЕКЛЮЧАТЕЛЯ сам по себе: отличается ли предсказание 1,037 от единицы
    #     при нашем шуме? Зазор здесь |предсказание − 1| = 0,037, и это другой вопрос, обычно
    #     непроверяемый. Раньше обе проверки были слиты в одну, и ответ выдавался по второй.
    app = st.adjudicate(rmed_s, bg['ratio'], se_s, 'ge', n=int(len(rat)))
    app2 = st.adjudicate(rmed_s, bg['ratio'], se_s, 'ge', null=1.0, n=int(len(rat)))
    sgn = st.sign_adjudicate(st.sign_test(d0, db, okp, 'increase'))

    # ---- (б) и (б′) ----
    stu = [z['stuck'] for z in rows]
    mono = bool(all(stu[i + 1] >= stu[i] - 1e-12 for i in range(len(stu) - 1)) and max(stu[1:]) > 0)
    # 15.10: знаковый критерий по парам соседних k заменён НАКЛОНОМ со своей ошибкой. Причина —
    # у знакового критерия тут не было мощности: доля застрявших меняется лишь в двух парах из
    # шести, и при n = 2 нужно 23 пары. У наклона работают все точки сразу, а ошибка каждой точки
    # биномиальная и известна. Старая часть осталась в журнале, новая стоит рядом.
    nb_ = int(S['band'].sum())
    # 16.10: наклон взвешенной прямой заменён критерием тренда Кохрана–Армитеджа. Причина — доля
    # застрявших идёт клюшкой (нули до k = 4, затем 0,026 и 0,499), прямая по таким точкам занижена
    # и не доходит до своего MDE, хотя между краями перебора тридцать сигм. У Кохрана–Армитеджа
    # дисперсия берётся по ОБЩЕЙ доле, поэтому нулевые ячейки не ломают веса.
    sg = st.trend_test([v * nb_ for v in stu], [nb_] * len(stu), [z['k'] for z in rows], 'increase')
    lad = P.wake_h(kb * max(dep, 1e-6)); lad0 = P.wake_h(0.0)

    # ---- (в) и (в′) ----
    c = st.adjudicate(mB['short'], 0.50, st.prop_se(mB['short'], mB['n_ep']), 'le', n=int(mB['n_ep']))
    se_p = st.prop_se(mB['short_pool'], mB['n_ep'])
    cp = st.adjudicate(mB['short_pool'], 0.50, se_p, 'le', null=0.0, n=int(mB['n_ep']))

    vt = lambda v: 'выполнено' if v is True else ('не выполнено' if v is False else str(v))
    md = ['\n## %s. Сон как следствие повреждения\n' % NAME,
          'Перебор k по полосе, блоки %s. Парное сравнение — те же наборы и тот же быстрый шум, '
          'меняется только k.\n' % ', '.join(ctx.key(B.tag_k(ks))[:6] for ks in B.KSCAN),
          '\n| зерно | длительность при k = 0 | при k = %.1f | отношение |\n|---|---|---|---|' % kb]
    for p_ in pairs:
        md.append('| %d | %s | %s | %s |' % (p_['seed'], ('%.2f' % p_['dur0']) if p_['dur0'] == p_['dur0'] else '—',
                  ('%.2f' % p_['durb']) if p_['durb'] == p_['durb'] else '—',
                  ('%.2f' % p_['ratio']) if p_['ratio'] == p_['ratio'] else '—'))
    md += ['\n| часть | получено | порог | нулевое значение | SE | MDE | вывод |\n|---|---|---|---|---|---|---|',
           '| а: удлиняет ли связь эпизод (как записано) | %.2f по %d зёрнам | не меньше 1,5 | 1,0 | %.3f | %.3f | %s |'
           % (rmed, nr, se_r, a['mde'], vt(a['verdict'])),
           '| а′: не ниже отношения, которое даёт сам переключатель | %.2f | %.3f (бодрствование %.2f ч против %.2f ч при k*D = %.3f) | 1,0 | %.3f | %.3f | %s |'
           % (rmed, bg['ratio'], bg['wake_hi_h'], bg['wake_lo_h'], kb * dep, se_r, ap['mde'], vt(ap['verdict'])),
           '| а″-1: есть ли усиление сверх переключателя (парно по наборам) | %s по %d наборам | не ниже %.3f | %.3f (сам переключатель) | %s | %s | %s |'
           % (('%.3f' % rmed_s) if rmed_s == rmed_s else '—', len(rat), bg['ratio'], bg['ratio'],
              ('%.4f' % se_s) if se_s == se_s else '—',
              ('%.4f' % app['mde']) if app['mde'] == app['mde'] else '—', vt(app['verdict'])),
           '| а″-2: различим ли вклад САМОГО переключателя | %s | не ниже %.3f | 1,0 | %s | %s | %s |'
           % (('%.3f' % rmed_s) if rmed_s == rmed_s else '—', bg['ratio'],
              ('%.4f' % se_s) if se_s == se_s else '—',
              ('%.4f' % app2['mde']) if app2['mde'] == app2['mde'] else '—', vt(app2['verdict'])),
           '| а‴: у скольких наборов эпизод удлинился | %d из %d, p = %s | p не больше 0,05 | 1/2 | — | мощность %.2f | %s |'
           % (sgn['k'], sgn['n'], ('%.3g' % sgn['p']) if sgn['p'] == sgn['p'] else '—',
              sgn['power'], vt(sgn['verdict'])),
           '| б: доля застрявших растёт с k (как записано) | %s | растёт и где-то больше нуля | — | — | — | %s |'
           % (' → '.join('%.3f' % s_ for s_ in stu), vt(mono)),
           '| б′: рост не случаен (критерий тренда по упорядоченным k) | z = %s, p = %s, по %d точкам | p не больше 0,05 | общая доля %s | — | — | %s |'
           % (('%.1f' % sg['z']) if sg['z'] == sg['z'] else '—',
              ('%.3g' % sg['p']) if sg['p'] == sg['p'] else '—', sg['n'],
              ('%.4f' % sg['p_pooled']) if 'p_pooled' in sg else '—', vt(sg['verdict'])),
           '| в: эпизодов короче суток (как записано, медиана по наборам) | %.3f | ниже 0,50 | 0,50 | %.3f | %.3f | %s |'
           % (mB['short'], st.prop_se(mB['short'], mB['n_ep']), c['mde'], vt(c['verdict'])),
           '| в′: то же по ВСЕМ эпизодам | %.3f на %d эпизодах | ниже 0,50 | 0 | %.4f | %.4f | %s |'
           % (mB['short_pool'], int(mB['n_ep']), se_p, cp['mde'], vt(cp['verdict'])),
           '\n| k, мВ | длительность эпизода, сут | коротких: медиана / по всем | застряли >2 сут | застряли >1,5 сут | срывов во второй половине | доля повреждавшихся |\n|---|---|---|---|---|---|---|']
    for z in rows:
        md.append('| %.2f | %s | %.3f / %.3f | %.3f | %.3f | %.3f | %.3f |' % (
            z['k'], ('%.2f' % z['dur']) if z['dur'] == z['dur'] else '—', z['short'], z['short_pool'],
            z['stuck'], z['stuck15'], z['late'], z['share_ever']))
    md += ['\nЛестница пропуска ночей: при k*D = %.3f свободное бодрствование %.2f ч против %.2f ч при нулевом '
           'повреждении. Пропуск ночи начинается около 7,5 мВ ЭФФЕКТИВНОГО торможения, то есть при D около '
           '%.2f это k около %.0f мВ — вне перебора. Поэтому часть (б) может проверять только монотонность, '
           'и двойник её так и проверяет.' % (kb * dep, lad, lad0, dep, 7.5 / max(dep, 1e-6))]
    if rmed == rmed and bg['ratio'] == bg['ratio'] and rmed > bg['ratio'] + st.mde(se_r):
        md.append('\n**Наблюдение сильно ВЫШЕ того, что даёт переключатель** (%.2f против %.2f). Значит '
                  'удлинение эпизода НЕ объясняется тем, что бодрствование стало длиннее: длина бодрствования '
                  'растёт всего на %.0f %%, а эпизод — на %.0f %%. Между ними есть усиление, и его место '
                  'известно: за длинное бодрствование набирается большая доза нагрузки, глубже уходит x, '
                  'и возврат к порогу занимает больше времени, чем само удлинение. Это предсказание '
                  'проверяемо отдельно: при одном и том же k рост длительности должен идти не с длиной '
                  'бодрствования, а с ИНТЕГРАЛОМ нагрузки за него. Записано в план.'
                  % (rmed, bg['ratio'], 100 * (bg['ratio'] - 1), 100 * (rmed - 1)))
    out = dict(a_paired=dict(ratio=rmed_s, n_sets=int(len(rat)), **app),
               a_paired_null1=app2, a_sign=sgn,
               a=dict(ratio=rmed, ratios=[float(x) for x in rts], **a),
               a_tight=dict(switch=bg, **ap), b=dict(stuck=stu, monotone=mono, **{}),
               b_tight=sg, c=c, c_tight=cp, rows=rows, pairs=pairs,
               wake_h=dict(at_kD=lad, at_zero=lad0, kD=kb * dep, D_used=dep))
    ctx.verdict(NAME, 'а', rmed, a['verdict'], note='порог 1,5 взят из прежней модели, не выведен')
    ctx.verdict(NAME, 'а′', rmed, ap['verdict'], note='по сидам: ошибка меряется разбросом между сидами')
    ctx.verdict(NAME, 'а″-1', rmed_s, app['verdict'], note='усиление сверх переключателя (%.3f), парно по наборам' % bg['ratio'])
    ctx.verdict(NAME, 'а″-2', rmed_s, app2['verdict'], note='различим ли вклад самого переключателя (зазор %.3f)' % (bg['ratio'] - 1))
    ctx.verdict(NAME, 'а‴', float(sgn['k']), sgn['verdict'], note='знаковый критерий по наборам')
    ctx.verdict(NAME, 'б', float(max(stu)), mono, note='монотонность на глаз, как записано')
    ctx.verdict(NAME, 'б′', sg.get('z', float('nan')), sg['verdict'],
                note='тренд доли застрявших по k, критерий Кохрана–Армитеджа')
    ctx.verdict(NAME, 'в', mB['short'], c['verdict'], note='медиана по наборам: статистика структурно вырождена')
    ctx.verdict(NAME, 'в′', mB['short_pool'], cp['verdict'], note='доля по всем эпизодам')
    return out, md
