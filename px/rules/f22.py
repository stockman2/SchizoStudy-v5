# -*- coding: utf-8 -*-
"""Ф22: ТРЕТИЙ путь, которым число клеток J влезло в модель, и как его закрыть.

ОТКУДА ВОПРОС. Ф13 на выборке 2000 наборов показал настоящую зависимость от J: размах длительности
по непрерывной переменной 0,208 и размах Ф5 0,241 при потолке шума 0,055 и 0,042 соответственно.
Два известных пути были закрыты заранее: хвост распределения уязвимости (закреплённая сетка) и
квантование порога эпизода (мера по непрерывной переменной). Значит есть третий.

ВЫКЛАДКА, КОТОРАЯ ЕГО НАХОДИТ БЕЗ ВСЯКОГО СЧЁТА. Множители уязвимости берутся как
      v_j = exp(sigma_v * z_{p_j}) / mean,   p_j равномерно от P0 до 1 - P0.
Края закреплены, и они действительно не ползут: наименьший множитель 0,8002 при J = 8 и 0,8029 при
J = 2048. Но РЕАЛИЗОВАННЫЙ разброс конечной сетки меньше сигмы и растёт к ней только в пределе:
      std(ln v) = 0,1226 / 0,1062 / 0,0982 / 0,0944 / 0,0910  при J = 8 / 16 / 32 / 64 / бесконечность
при sigma_v = 0,10. От J = 16 к J = 64 это 11 % по ЭФФЕКТИВНОЙ сигме разброса. А модель к sigma_v
крайне чувствительна: по прежнему перебору доля времени в середине шкалы шла 0,017 / 0,056 / 0,133
при sigma_v 0,05 / 0,10 / 0,15, то есть логарифмическая чувствительность около 2,5. Значит 11 % по
сигме дают около 25 % по измеряемым величинам — ровно тот размах, который Ф13 и нашла.
Иначе говоря: J входит в модель как ЭФФЕКТИВНАЯ СИГМА РАЗБРОСА, а не как разрешение.

ПРАВИЛО Ф22, ЗАПИСАНО ДО СЧЁТА
  (а) Арифметика сетки: реализованный разброс std(ln v) падает с ростом J больше чем на 5 % между
      J = 16 и J = 64. Это чистая арифметика, модель не участвует, и проверяется мгновенно.
  (б) ГЛАВНАЯ ЧАСТЬ, решающая. Если J действует ТОЛЬКО через эффективную сигму, то блок при J = 32
      с sigma_v, подменённой на реализованный разброс сетки J = 16, обязан дать те же величины, что
      блок при J = 16 с обычной sigma_v, — в пределах 3 SE (допуск равносильности). То же для J = 64.
      Если совпало — путь найден и объяснён целиком. Если не совпало — есть ещё один путь, и его
      надо искать дальше.
  (в) Поправка, записанная заранее: заменить в сетке sigma_v на sigma_v * (sigma_v / std(ln v_J)),
      то есть растянуть сетку так, чтобы реализованный разброс равнялся заданному при ЛЮБОМ J.
      Множители поправки печатаются ниже. ВАЖНО: эта поправка меняет px/core.py, то есть хеш кода
      модели, и тем обесценивает весь кэш блоков. Поэтому она НЕ сделана здесь, а записана как
      отдельный шаг: её надо делать осознанно, одним прогоном, с парным контролем.

ЦЕНА. Два новых блока (J = 32 с подменённой sigma_v). Остальное — блоки Ф13, они уже посчитаны.
"""
import numpy as np
from .. import stats as st
from ..batch import Block
from . import _blocks as B
from ._meas import meas, mid_time
from ..core import vuln

NAME = 'Ф22'
JPAIR = (16, 64)          # с какими J сверяемся подменой сигмы
NHD = 20


def sig_eff(J, sigv):
    """Реализованный разброс логарифма множителей на закреплённой сетке при данном J."""
    return float(np.std(np.log(vuln(J, sigv, 1.0)[0])))


def needs(cfg):
    sv = float(cfg.d['model']['sigv'])
    return B.j_scan(cfg) + [Block('sv_%d' % J, kd=0.0, sigs=B.SIGS[0], taus=B.TAU_S,
                                  sigv=sig_eff(J, sv)) for J in JPAIR]


def run(ctx):
    S = ctx.S; cfg = ctx.cfg; nd = cfg.d['run']['days']; band = S['band']
    sv = float(cfg.d['model']['sigv']); J0 = int(cfg.d['run']['J'])
    grid = {J: sig_eff(J, sv) for J in (8, 16, 32, 64, 128, 2048)}
    drop = (grid[16] - grid[64]) / max(grid[16], 1e-12)
    a = st.adjudicate(drop, 0.05, 0.0, 'ge', null=0.0, n=None)
    a['verdict'] = bool(drop >= 0.05)                       # чистая арифметика: шума нет вовсе
    KK = (('share_ever', 'доля повреждавшихся'), ('dur_m', 'длительность по непрерывной, сут'),
          ('mid', 'Ф5: середина шкалы'))

    def vals(tag, J):
        rr = ctx.b(tag); mm = meas(rr, nd, band); mall = meas(rr, nd)
        midD, _, se_mid, neff, _, _ = mid_time(rr, nd, len(rr['nb']), mall['dur'], NHD)
        v = mm['dur_arr'][np.isfinite(mm['dur_arr'])]
        return dict(share_ever=mm['share_ever'], dur_m=mm['dur_m'], mid=midD,
                    se_share_ever=st.prop_se(mm['share_ever'], int(band.sum())),
                    se_dur_m=(st.boot_se(v) * max(mm['dur_m'], 1e-9)) if len(v) >= 5 else float('nan'),
                    se_mid=se_mid, J=J)
    rows = []
    for J in JPAIR:
        real = vals(B.tag_j(J, 1), J)                       # честный блок при этом J
        subs = vals('sv_%d' % J, J0)                        # J = 32, но сигма подменена на разброс сетки J
        for k, lab in KK:
            se = max([x for x in (real['se_' + k], subs['se_' + k]) if x == x] or [float('nan')])
            d = abs(real[k] - subs[k])
            z = st.adjudicate(d, st.eq_tol(se), se, 'le', null=0.0, n=int(band.sum()))
            rows.append(dict(J=J, key=k, label=lab, real=real[k], subs=subs[k], diff=d, se=se,
                             tol=st.eq_tol(se), verdict=z['verdict'], mde=z['mde']))
    good = [z for z in rows if z['verdict'] is True]
    bad = [z for z in rows if z['verdict'] is False]
    weak = [z for z in rows if z['verdict'] == 'непроверяемо']
    b = ('непроверяемо' if weak and not bad else bool(not bad))
    fix = {J: sv / max(grid[J], 1e-12) * sv for J in (8, 16, 32, 64, 128)}
    vt = lambda v: 'выполнено' if v is True else ('не выполнено' if v is False else str(v))
    md = ['\n## %s. Третий путь, которым J влез в модель\n' % NAME,
          'Края сетки уязвимости закреплены и действительно не ползут, но РЕАЛИЗОВАННЫЙ разброс конечной '
          'сетки меньше заданной сигмы и подходит к ней только в пределе. Это чистая арифметика сетки, '
          'модель в ней не участвует.\n',
          '\n| J | std(ln v) при sigma_v = %.2f | в долях предела | множитель поправки |\n|---|---|---|---|' % sv]
    for J in (8, 16, 32, 64, 128, 2048):
        md.append('| %d | %.5f | %.3f | %s |' % (J, grid[J], grid[J] / grid[2048],
                  ('%.4f' % (sv / grid[J] * sv)) if J in fix else '—'))
    md += ['\n| часть | получено | порог | вывод |\n|---|---|---|---|',
           '| а: реализованный разброс падает с J | от J = 16 к J = 64 на %.1f %% | больше 5 %% | %s |'
           % (100 * drop, vt(a['verdict'])),
           '| б: J действует ТОЛЬКО через эффективную сигму | совпало %d из %d сверок, не совпало %d, непроверяемо %d | все сверки в 3 SE | %s |'
           % (len(good), len(rows), len(bad), len(weak), vt(b)),
           '| в: поправка записана, но НЕ применена | множители выше; она меняет px/core.py и обесценивает кэш | применять отдельным прогоном | записано |',
           '\n### Сверка подменой сигмы: J = 32 с чужим разбросом против честного J\n',
           '| J | величина | честный блок при J | J = 32 с sigma_v = std(ln v_J) | расхождение | допуск 3 SE | вывод |\n|---|---|---|---|---|---|---|']
    for z in rows:
        md.append('| %d | %s | %s | %s | %s | %s | %s |' % (
            z['J'], z['label'],
            *[('%.4f' % z[k]) if z[k] == z[k] else '—' for k in ('real', 'subs', 'diff', 'tol')],
            vt(z['verdict'])))
    if b is True:
        md.append('\n**Путь найден и объяснён целиком.** Зависимость от J — это зависимость от эффективной '
                  'сигмы разброса уязвимости: подменив сигму, мы воспроизвели чужое J, не меняя J. Значит '
                  'прежние прогоны при J = 32 и J = 64 отличались не разрешением, а РАЗБРОСОМ, и поправка '
                  '(в) закрывает вопрос одной строкой в сетке. До поправки сравнивать прогоны с разным J '
                  'нельзя — это сравнение двух разных моделей.')
    elif b is False:
        md.append('\n**Есть ещё путь.** Подмена сигмы воспроизводит чужое J не во всём (%s), значит кроме '
                  'эффективного разброса J входит куда-то ещё. Где смотреть дальше: средняя по населению '
                  'нормировка (mean = 1 ровно при любом J, но ДИСПЕРСИЯ среднего падает как 1/J, то есть '
                  'связь через среднее повреждение при малом J шумнее), и дискретность самой доли '
                  'повреждённых в обратной связи на сон.' % ', '.join('%s при J = %d' % (z['label'], z['J']) for z in bad))
    out = dict(a=dict(drop=drop, grid=grid, verdict=a['verdict']), b=dict(verdict=b, rows=rows),
               fix_factors=fix, note='поправка меняет px/core.py и обесценивает кэш блоков; применять осознанно')
    ctx.verdict(NAME, 'а', drop, a['verdict'], note='падение реализованного разброса сетки от J = 16 к 64')
    ctx.verdict(NAME, 'б', float(len(bad)), b, note='воспроизводится ли чужое J подменой сигмы')
    return out, md
