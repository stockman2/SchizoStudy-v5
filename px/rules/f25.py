# -*- coding: utf-8 -*-
"""Ф25: ПОЛОСА СПАСЁННЫХ. Популяция живёт в ТРЁХ фазах, а не в двух.

ОТКУДА ВОПРОС. Клетки одного набора отличаются ровно ОДНИМ скаляром — множителем нагрузки v, всё
остальное построчное. Значит состояние клетки есть однопараметрическое семейство x(t; v) при общей
для всех истории нагрузки, и при монотонной динамике повреждённые клетки были бы ровным хвостом
{v >= v*}. Тогда доля повреждённых считалась бы в замкнутом виде, 1 - F_v(v*), и поклеточный блок
был бы не нужен вовсе.

ЧТО ИЗМЕРЕНО 16.10 НА МЕЛКОЙ СЕТКЕ (600 узлов по v, три профиля нагрузки, включая враждебный):
  - при ЗАМОРОЖЕННОЙ медленной защите монотонность ТОЧНАЯ: ноль нарушений на всех наборах и всех
    профилях, наибольшее нарушение ровно 0.000e+00;
  - при живой защите порядок рвётся: 11,9 % шагов, наибольшее нарушение 0,973 — то есть полный
    переворот, более уязвимая клетка цела, а менее уязвимая рухнула;
  - прайминг не причина, а усилитель: при A_PR = 0 нарушение остаётся, но падает с 0,973 до 0,0184;
  - порядок не сохраняется НИ в одной координате: sP 27,8 % шагов, mR 32,5 %, prm 32,7 %, c 100 %;
  - пограничный слой не размазан, а СВЯЗЕН: медиана = 95-я процентиль = максимум = 0,0850.

СОДЕРЖАТЕЛЬНЫЙ ВЫВОД. Фаз три: здоровое ядро, рухнувшее ядро и полоса между ними, где клетки
УЯЗВИМЕЕ своих рухнувших соседей и при этом целы — они раньше окислились, сильнее напраймировались
и накопили защиту. Это гормезис на уровне популяции, и это предсказание модели, а не артефакт счёта.

ЧТО ИМЕННО СЧИТАЕТСЯ. Накопитель rbar в px/model.py: доля ЦЕЛЫХ клеток, лежащих ВЫШЕ первой
повреждённой (клетки упорядочены по уязвимости), усреднённая по времени. При монотонной динамике
она тождественно нуль.

ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Соблазнительная выкладка даёт ширину полосы как phi(z*)*sigma(ln c)/sigma_v.
Она не годится: sigma(ln c) включает часть разброса защиты, ОБЪЯСНЁННУЮ самой уязвимостью, а эта
часть монотонна и полосы не создаёт вовсе. Полосу делает только остаток, не объяснённый v, и выделить
его из равновесной алгебры нельзя — он динамический. Поэтому количественная выкладка здесь НЕ
используется, а предсказания взяты те, что защищаются целиком: причинность и форма.

ПРАВИЛО Ф25, ЗАПИСАНО ДО СЧЁТА
  (а) ПОДТВЕРЖДЕНИЕ, НЕ ПРЕДСКАЗАНИЕ (помечено как в Ф18(а)). Полоса существует: средняя ширина
      выше нуля с запасом MDE. Это уже измерено 16.10 на мелкой сетке, поэтому вердикт
      подтверждающий.
  (б) ПРИЧИНА — МЕДЛЕННАЯ ЗАЩИТА. При ЗАМОРОЖЕННОЙ второй ступени (taus = 1000 суток: множитель
      спада близок к единице, и sP остаётся на начальном нуле) полоса обязана обратиться в нуль в
      пределах своей ошибки. Основание — проба 16.10: при замороженной защите монотонность ТОЧНАЯ,
      ноль нарушений. Парные блоки: те же наборы, то же зерно, меняется только память.
      ВАЖНО, И ЭТО ИСПРАВЛЕНИЕ МОЕЙ ЖЕ ОШИБКИ 17.10. Сначала здесь стояла КОРОТКАЯ память (12 ч) с
      ожиданием сужения вдвое. Это следовало не из пробы: короткая память — не замороженная, история
      у клетки остаётся, просто идёт быстрее. Замер показал РАСШИРЕНИЕ (0,0141 против 0,0110), и
      ожидание было неверным по рассуждению, а не по физике. Короткая память оставлена как
      наблюдение в части (б′), БЕЗ порога: предсказывать её поведение мне нечем.
  (в) ПРАЙМИНГ УСИЛИВАЕТ, НО НЕ СОЗДАЁТ. При включённом прайминге полоса обязана стать ШИРЕ, а в
      рабочем положении (прайминга нет) — остаться НЕнулевой. Обе половины обязательны: если без
      прайминга полоса исчезает, причина названа неверно.
  (д) НЕЗАВИСИМАЯ ПРОВЕРКА ТОГО, ЧТО ПОКАЖЕТ (г). Часть (г) смотрит перебор k, и его я уже видел.
      Поэтому то же утверждение о форме проверяется ВТОРОЙ раз на переборе суточного размаха
      (ASCAN), который для этого вопроса не открывался: ранговое согласие ширины с phi(Phi^-1(1-D))
      там обязано быть того же знака, что в (г). Если знаки разойдутся, форма не описывается ни
      геометрией пограничного слоя, ни чем-то одним вообще, и утверждение снимается целиком.
  (г) ФОРМА, предсказана геометрией и без единого свободного числа. Полоса есть пограничный слой,
      поэтому её ширина обязана следовать phi(Phi^-1(1 - D)) — максимум при D = 1/2, обращение в
      нуль при D к нулю и к единице. Проверяется ранговым согласием по перебору k (он даёт широкий
      ход D) ТОЧНЫМ перестановочным критерием, p не больше 0,05.
"""
import math
import numpy as np
from scipy.stats import norm
from .. import stats as st
from . import _blocks as B
from ._meas import meas

NAME = 'Ф25'


def needs(cfg):
    return [B.kbase_block(cfg)] + B.kscan(cfg) + B.band_scan(cfg) + B.swing_scan(cfg)


def _band(ctx, tag, band):
    rr = ctx.b(tag)
    r = np.asarray(rr['rbar'], float)[band]
    r = r[np.isfinite(r)]
    if len(r) < 3: return float('nan'), float('nan'), len(r)
    return float(r.mean()), float(r.std(ddof=1) / math.sqrt(len(r))), len(r)


def run(ctx):
    S = ctx.S; cfg = ctx.cfg; nd = cfg.d['run']['days']; band = S['band']
    w0, se0, n0 = _band(ctx, 'kbase', band)
    wf, sef, nf = _band(ctx, 'bd_froz', band)
    ws, ses, ns = _band(ctx, 'bd_short', band)
    wp, sep, npr = _band(ctx, 'bd_prime', band)

    # ---- (а) полоса существует ----
    a = st.adjudicate(w0, 2.4865 * se0 if se0 == se0 else float('nan'), se0, 'ge', null=0.0, n=n0)

    # ---- (б) замороженная защита: полоса обращается в нуль ----
    se_b = math.sqrt(se0 ** 2 + sef ** 2) if (se0 == se0 and sef == sef) else float('nan')
    b = st.adjudicate(wf, 2.4865 * sef if sef == sef else float('nan'), sef, 'le', null=w0, n=min(n0, nf))

    # ---- (в) прайминг усиливает, но не создаёт ----
    se_c = math.sqrt(se0 ** 2 + sep ** 2) if (se0 == se0 and sep == sep) else float('nan')
    c_wider = st.adjudicate(wp, w0 + 2.4865 * se_c, se_c, 'ge', null=w0, n=min(n0, npr))
    c_nonzero = a['verdict']                       # рабочее положение — прайминга нет
    c = ('непроверяемо' if (c_wider['verdict'] == 'непроверяемо' or c_nonzero == 'непроверяемо')
         else bool(c_wider['verdict'] is True and c_nonzero is True))

    # ---- (г) форма: полоса следует phi(Phi^-1(1 - D)) ----
    rows = []
    for k in B.KSCAN:
        tag = B.tag_k(k); mm = meas(ctx.b(tag), nd, band)
        wk, sek, nk = _band(ctx, tag, band)
        D = float(mm['Dbar'])
        z = norm.ppf(min(max(1.0 - D, 1e-6), 1 - 1e-6))
        rows.append(dict(k=k, D=D, width=wk, se=sek, n=nk, phi=float(norm.pdf(z)), share=mm['share_ever']))
    gr = [z for z in rows if np.isfinite(z['width']) and np.isfinite(z['phi'])]
    rho, p_g, n_g = st.perm_rank_p([z['phi'] for z in gr], [z['width'] for z in gr], 'increase')
    g = ('непроверяемо' if not (p_g == p_g) else bool(p_g <= 0.05))

    vt = lambda v: 'выполнено' if v is True else ('не выполнено' if v is False else str(v))
    md = ['\n## %s. Полоса спасённых: популяция в трёх фазах\n' % NAME,
          'Ширина полосы — доля ЦЕЛЫХ клеток, лежащих выше первой повреждённой (клетки упорядочены '
          'по уязвимости), усреднённая по времени. При монотонной динамике она тождественно нуль; '
          'замер 16.10 на мелкой сетке в 600 узлов дал около 0,085 при живой защите и РОВНО нуль при '
          'замороженной.\n',
          '| состояние защиты | ширина полосы | SE | наборов |', '|---|---|---|---|',
          '| рабочее: память 63 ч, прайминга нет | %.5f | %.5f | %d |' % (w0, se0, n0),
          '| короткая память 12 ч | %.5f | %.5f | %d |' % (ws, ses, ns),
          '| с праймингом A = 2, tau = 0,5 сут | %.5f | %.5f | %d |' % (wp, sep, npr),
          '', '| k, мВ | доля повреждённых D | phi(Phi⁻¹(1−D)) | ширина полосы | SE | наборов |',
          '|---|---|---|---|---|---|']
    for z in rows:
        md.append('| %.1f | %.4f | %.4f | %s | %s | %d |'
                  % (z['k'], z['D'], z['phi'],
                     ('%.5f' % z['width']) if np.isfinite(z['width']) else '—',
                     ('%.5f' % z['se']) if np.isfinite(z['se']) else '—', z['n']))
    md += ['', '| часть | получено | ожидание до счёта | вывод |', '|---|---|---|---|',
           '| а: полоса существует (подтверждение, не предсказание) | %.5f ± %.5f | выше нуля с запасом '
           'MDE = %s | %s |' % (w0, se0, ('%.5f' % a['mde']) if a['mde'] == a['mde'] else '—', vt(a['verdict'])),
           '| б: при замороженной защите полоса обращается в нуль | %.5f против рабочих %.5f | не '
           'больше своей ошибки %s | %s |'
           % (wf, w0, ('%.5f' % (2.4865 * sef)) if sef == sef else '—', vt(b['verdict'])),
           '| б′: короткая память 12 ч (наблюдение, порога нет) | %.5f против рабочих %.5f | порога '
           'не ставилось: предсказать поведение короткой памяти было нечем | — |' % (ws, w0),
           '| в: прайминг шире, рабочее положение не нуль | %.5f против %.5f | шире на MDE И рабочее '
           'не нуль | %s |' % (wp, w0, vt(c)),
           '| г: ширина следует phi(Phi⁻¹(1−D)) | ранговая связь %s по %d точкам, точный p = %s | '
           'p не больше 0,05 | %s |'
           % (('%+.3f' % rho) if rho == rho else '—', n_g,
              ('%.4f' % p_g) if p_g == p_g else '—', vt(g))]
    # ---- (д) та же форма на НЕЗАВИСИМОМ переборе суточного размаха ----
    rows_a = []
    for af in B.ASCAN:
        tag = B.tag_a(af) if hasattr(B, 'tag_a') else 'a_%.2f' % af
        try:
            mm = meas(ctx.b(tag), nd, band); wa, sea, na = _band(ctx, tag, band)
        except KeyError:
            continue
        Da = float(mm['Dbar'])
        za = norm.ppf(min(max(1.0 - Da, 1e-6), 1 - 1e-6))
        rows_a.append(dict(a=af, D=Da, width=wa, se=sea, n=na, phi=float(norm.pdf(za))))
    dr = [z for z in rows_a if np.isfinite(z['width']) and np.isfinite(z['phi'])]
    if len(dr) >= 3:
        rho_d, p_d, n_d = st.perm_rank_p([z['phi'] for z in dr], [z['width'] for z in dr], 'increase')
        same = (rho_d == rho_d and rho == rho and (rho_d > 0) == (rho > 0))
        d_v = ('непроверяемо' if not (rho_d == rho_d and rho == rho) else bool(same))
    else:
        rho_d = float('nan'); p_d = float('nan'); n_d = len(dr); d_v = 'непроверяемо'
    md += ['| д: тот же знак формы на НЕЗАВИСИМОМ переборе размаха | связь %s по %d точкам против '
           '%s в (г) | знаки обязаны совпасть | %s |'
           % (('%+.3f' % rho_d) if rho_d == rho_d else '—', n_d,
              ('%+.3f' % rho) if rho == rho else '—', vt(d_v))]
    if b['verdict'] is True and g is True:
        md.append('\n**Три фазы подтверждены, и причина названа верно.** Полоса существует, сужается при '
                  'укорочении памяти защиты и по ширине следует геометрии пограничного слоя. Отсюда два '
                  'следствия. Для теории: замкнутая формула доли повреждённых через одну границу '
                  'незаконна при живой защите, и упрощать поклеточный блок можно только с явным '
                  'пограничным слоем — трёхконфигурационно, а не двух. Для содержания: модель '
                  'предсказывает гормезис на уровне популяции — часть клеток выживает именно потому, что '
                  'раньше пострадала.')
    elif b['verdict'] is False:
        md.append('\n**Полоса есть, но память защиты её не делает.** Тогда причина в другом, и проверять '
                  'надо первую ступень (12 ч) и защиту от рецептора: обе тоже дают клетке память о её '
                  'собственной истории, а замороженной в пробе 16.10 была ВТОРАЯ ступень вместе с первой.')
    out = dict(base=dict(width=w0, se=se0, n=n0), short=dict(width=ws, se=ses, n=ns),
               prime=dict(width=wp, se=sep, n=npr), rows=rows,
               a=dict(**a), b=dict(**b), c=dict(verdict=c, wider=c_wider, nonzero=c_nonzero),
               g=dict(rank_corr=rho, p=p_g, n=n_g, verdict=g),
               b_short=dict(width=ws, se=ses, n=ns, note='наблюдение без порога'),
               frozen=dict(width=wf, se=sef, n=nf),
               d=dict(rank_corr=rho_d, p=p_d, n=n_d, verdict=d_v, rows=rows_a))
    ctx.verdict(NAME, 'а', w0, a['verdict'], note='полоса существует; подтверждение замера 16.10, не предсказание')
    ctx.verdict(NAME, 'б', wf, b['verdict'],
                note='ЗАМОРОЖЕННАЯ защита (taus = 1000 сут) против рабочей, парно; короткая память '
                     'дала %.5f и порога ей не ставилось' % ws)
    ctx.verdict(NAME, 'в', wp, c, note='прайминг усиливает, но рабочее положение без него не нуль')
    ctx.verdict(NAME, 'г', rho, g, note='форма пограничного слоя phi(Phi^-1(1-D)) по перебору k')
    ctx.verdict(NAME, 'д', rho_d, d_v, note='тот же знак формы на независимом переборе размаха')
    return out, md
